import math, collections
import numpy as np
from PIL import Image

def biggest_blob(mask):
    H, W = mask.shape; lab = np.zeros((H,W), np.int32); n=0; best=(0,None)
    for y0 in range(H):
        for x0 in range(W):
            if mask[y0,x0] and lab[y0,x0]==0:
                n+=1; dq=collections.deque([(y0,x0)]); lab[y0,x0]=n; c=0
                while dq:
                    y,x=dq.popleft(); c+=1
                    for dy,dx in ((1,0),(-1,0),(0,1),(0,-1)):
                        ny,nx=y+dy,x+dx
                        if 0<=ny<H and 0<=nx<W and mask[ny,nx] and lab[ny,nx]==0:
                            lab[ny,nx]=n; dq.append((ny,nx))
                if c>best[0]: best=(c,n)
    return lab==best[1]

def ellipse_axes(mask):
    """Полуоси и угол эллипса по вторым моментам заполненной области."""
    ys, xs = np.nonzero(mask)
    cy, cx = ys.mean(), xs.mean()
    y, x = ys-cy, xs-cx
    cov = np.array([[ (x*x).mean(), (x*y).mean() ], [ (x*y).mean(), (y*y).mean() ]])
    w, v = np.linalg.eigh(cov)
    order = np.argsort(w)[::-1]
    w, v = w[order], v[:, order]
    a, b = 2*math.sqrt(w[0]), 2*math.sqrt(w[1])   # для сплошного эллипса λ = (полуось)²/4
    ang = math.degrees(math.atan2(v[1,0], v[0,0]))
    return (cx, cy), a, b, ang


def boundary_points(mask, drop_frame=True):
    """Точки границы области. Пиксели на рамке кадра выбрасываются: там граница — не ободок
    тарелки, а обрез снимка, и она увела бы подгонку."""
    H, W = mask.shape
    m = mask
    edge = m & ~(np.roll(m,1,0) & np.roll(m,-1,0) & np.roll(m,1,1) & np.roll(m,-1,1))
    ys, xs = np.nonzero(edge)
    if drop_frame:
        keep = (xs > 1) & (ys > 1) & (xs < W-2) & (ys < H-2)
        ys, xs = ys[keep], xs[keep]
    return xs.astype(float), ys.astype(float)


def fit_conic(x, y):
    """Эллипс по точкам: A x² + B xy + C y² + D x + E y + F = 0, наименьшие квадраты через SVD.

    Работает по ДУГЕ — этим и отличается от вторых моментов, которым нужна вся фигура.
    Возвращает (центр, большая полуось, малая полуось, угол в градусах).
    """
    sx, sy = x.mean(), y.mean()
    sc = max(x.std(), y.std())
    u, v = (x - sx) / sc, (y - sy) / sc                  # нормировка: без неё SVD плывёт
    D = np.column_stack([u*u, u*v, v*v, u, v, np.ones_like(u)])
    _, _, Vt = np.linalg.svd(D, full_matrices=False)
    A, B, C, Dc, E, F = Vt[-1]
    M = np.array([[A, B/2], [B/2, C]])
    if np.linalg.det(M) <= 0: return None                # не эллипс
    cen = np.linalg.solve(2*M, [-Dc, -E])
    val = A*cen[0]**2 + B*cen[0]*cen[1] + C*cen[1]**2 + Dc*cen[0] + E*cen[1] + F
    w, vec = np.linalg.eigh(M / (-val))
    if np.any(w <= 0): return None
    ax = 1/np.sqrt(w)
    order = np.argsort(ax)[::-1]
    ax, vec = ax[order], vec[:, order]
    import math
    return ((cen[0]*sc + sx, cen[1]*sc + sy), ax[0]*sc, ax[1]*sc,
            math.degrees(math.atan2(vec[1,0], vec[0,0])))


# ── НАКЛОН ИЗ ЭЛЛИПСА ──────────────────────────────────────────────────────────
# Формулы не было в файле вовсе (issue #120): число 41° стояло в докстринге и в
# docs/kitchen-practice.md, полученное разовым прогоном В СТОРОНЕ, и шаг от сжатия 1,33
# к 41° не воспроизводился в репозитории ничем. Это тот же класс, что «замер, которого
# нет»: число подано как результат инструмента, а инструмент его не считал.
#
# Круг радиуса R, наклонённый на угол θ к плоскости кадра, проецируется в эллипс с
# большой полуосью R и малой R·cos θ. Значит сжатие a/b = 1/cos θ, откуда θ = acos(b/a).
def tilt_from_axes(a, b):
    """Наклон камеры в градусах по полуосям эллипса тарелки (a — большая)."""
    if a <= 0 or b <= 0 or b > a: return None
    return math.degrees(math.acos(b / a))


def arc_span_deg(x, y, cen):
    """Какую дугу эллипса покрывают точки — в градусах, по самому широкому пропуску.

    Не размах углов: точки могут идти двумя кусками по разные стороны, и размах тогда
    покажет 360° там, где видно два коротких серпа. Берём наибольший пропуск между
    соседними углами и вычитаем его из полного круга.
    """
    ang = np.sort(np.arctan2(y - cen[1], x - cen[0]))
    if ang.size < 2: return 0.0
    gaps = np.diff(np.concatenate([ang, [ang[0] + 2 * math.pi]]))
    return math.degrees(2 * math.pi - gaps.max())


def rms_residual(x, y, cen, a, b, phi_deg):
    """Среднеквадратичная невязка точек от подогнанного эллипса, в пикселях.

    Показатель доверия, которого у инструмента не было: подгонка МОЖЕТ вернуть эллипс,
    прекрасно сидящий на своих точках и при этом не имеющий отношения к тарелке.
    Большой RMS — это точно плохо; малый сам по себе ничего не доказывает, потому и
    печатается рядом с длиной дуги, а не вместо неё.
    """
    ph = math.radians(phi_deg)
    dx, dy = x - cen[0], y - cen[1]
    u = dx * math.cos(ph) + dy * math.sin(ph)
    v = -dx * math.sin(ph) + dy * math.cos(ph)
    r = np.hypot(u / a, v / b)
    return float(np.sqrt(np.mean((r - 1) ** 2)) * (a + b) / 2)


# Порог годности дуги. ⚑ ПОДОБРАН ЗАМЕРОМ, А НЕ НАЗНАЧЕН — `--selftest` его воспроизводит.
#
# Внешнее ревью предлагало 30° как границу годности. Монте-Карло (эллипс 400×300, истинный
# наклон 41,4°, 200 прогонов на ячейку) показало, что 30° — это не граница, а зона полного
# вранья: медиана 88–89° при истинных 41,4°, и подгонка вдобавок проваливается в 188 случаях
# из 200. То есть инструмент возвращал почти предельный наклон вместо умеренного, и молча.
#
#     дуга   медиана при шуме 2 px   разброс 10–90 %
#      30°          89,1°                 —          (199 провалов из 200)
#      60°          85,4°             80,7…87,3      (160 провалов)
#      90°          46,2°             31,7…70,7
#     120°          42,8°             38,5…47,0      ← первая, где медиана верна
#     150°          41,5°             40,2…43,3      ← первая, где и разброс мал
#     200°          41,4°             40,8…42,1
#
# Взято 150°, а не 120°: на 120° медиана уже верна (ошибка 1,4°), но разброс ещё 8,5°, то есть
# на отдельном снимке ошибка в полтора десятка градусов законна. На 150° разброс втрое меньше.
# Сито должно отбирать снимки, а не создавать видимость отбора.
ARC_MIN_DEG = 150.0


def verdict(tilt, arc, rms, axis_ratio):
    """Вердикт словами: годен ли снимок и, если нет, чем именно плох."""
    beef = []
    if arc < ARC_MIN_DEG:
        beef.append(f'дуга {arc:.0f}° короче {ARC_MIN_DEG:.0f}° — подгонке верить нельзя')
    if rms > 0.03 * axis_ratio * 100:
        beef.append(f'невязка {rms:.1f} px велика — точки не лежат на одном эллипсе')
    if tilt is None:
        beef.append('эллипс не построился')
    elif tilt > 15:
        beef.append(f'наклон {tilt:.0f}° больше 15° — в силуэт войдёт боковая стенка')
    return ('ГОДЕН', beef) if not beef else ('НЕ ГОДЕН', beef)


def _selftest(n=200, seed=20260901):
    """Монте-Карло: врёт ли подгонка на короткой дуге, и с какой дуги перестаёт.

    Воспроизводит замер из issue #120 и подбирает ARC_MIN_DEG вместо того, чтобы его
    назначить. Эллипс 400×300 (сжатие 1,333) даёт истинный наклон 41,4°.
    """
    rng = np.random.default_rng(seed)
    A, B = 200.0, 150.0
    истина = tilt_from_axes(A, B)
    print(f'эталон: полуоси {A:.0f}×{B:.0f}, сжатие {A/B:.3f}, истинный наклон {истина:.1f}°')
    print(f'{"дуга":>6} {"шум":>5} {"медиана":>9} {"10–90 %":>16} {"провалов":>9}')
    порог = None
    for arc in (30, 60, 90, 120, 150, 180, 200, 240, 300, 360):
        for шум in (0.5, 2.0):
            углы, провалов = [], 0
            for _ in range(n):
                нач = rng.uniform(0, 2 * math.pi)
                t = нач + np.linspace(0, math.radians(arc), 120)
                x = A * np.cos(t) + rng.normal(0, шум, t.size)
                y = B * np.sin(t) + rng.normal(0, шум, t.size)
                f = fit_conic(x, y)
                if f is None: провалов += 1; continue
                _, a, b, _ = f
                тл = tilt_from_axes(a, b)
                if тл is None: провалов += 1; continue
                углы.append(тл)
            if not углы: print(f'{arc:>5}° {шум:>5} {"—":>9} {"—":>16} {провалов:>4}/{n}'); continue
            углы = np.array(углы)
            med, p10, p90 = np.median(углы), np.percentile(углы, 10), np.percentile(углы, 90)
            print(f'{arc:>5}° {шум:>5} {med:>8.1f}° {p10:>7.1f}…{p90:<7.1f} {провалов:>4}/{n}')
            # Годной считаем дугу, на которой медиана не врёт больше чем на 3° и разброс
            # укладывается в ±5°: сито должно отбирать снимки, а не создавать их видимость.
            if порог is None and шум == 2.0 and abs(med - истина) <= 3 and (p90 - p10) <= 10:
                порог = arc
    print(f'\nпервая годная дуга: {порог}°  ·  в файле ARC_MIN_DEG = {ARC_MIN_DEG:.0f}°')
    return порог


def _measure(path):
    """Замер по снимку: наклон, дуга, невязка, отношение осей и вердикт."""
    im = Image.open(path).convert('RGB')
    a = np.asarray(im).astype(np.float32)
    # Тарелка — самое светлое и наименее насыщенное пятно кадра; порог грубый, и это
    # намеренно: инструмент отбирает кадры, а не сегментирует блюдо.
    mx, mn = a.max(axis=2), a.min(axis=2)
    mask = (mx > 150) & ((mx - mn) < 40)
    mask = biggest_blob(mask)
    if mask is None or mask.sum() < 200:
        print(f'{path}: светлого пятна не нашлось — тарелка не опознана'); return
    ys, xs = boundary_points(mask)
    f = fit_conic(xs.astype(float), ys.astype(float))
    if f is None:
        print(f'{path}: эллипс не построился ({xs.size} точек границы)'); return
    cen, ax_a, ax_b, phi = f
    tilt = tilt_from_axes(ax_a, ax_b)
    arc = arc_span_deg(xs.astype(float), ys.astype(float), cen)
    rms = rms_residual(xs.astype(float), ys.astype(float), cen, ax_a, ax_b, phi)
    исход, чем = verdict(tilt, arc, rms, ax_a / ax_b)
    print(f'{path}')
    print(f'  полуоси      {ax_a:.1f} × {ax_b:.1f} px   сжатие {ax_a/ax_b:.3f}')
    print(f'  наклон       {tilt:.1f}°' if tilt is not None else '  наклон       —')
    print(f'  дуга         {arc:.0f}°   (порог {ARC_MIN_DEG:.0f}°)')
    print(f'  невязка RMS  {rms:.2f} px по {xs.size} точкам')
    print(f'  ВЕРДИКТ      {исход}')
    for b in чем: print(f'     · {b}')


