#!/usr/bin/env node
// ВАРИАНТЫ РОЛЛА ПО ГРАММАМ — калибровка модели тем языком, которым говорят рецепты.
//
// ЗАЧЕМ. Владелец 01.09: «нам бы понять, что если столько грамм риса на такой-то длине,
// и мы положили полоску лосося сантиметр на сантиметр, то примерно должно получиться вот
// такое». Рецепты меряют граммами, модель — миллиметрами, и до сих пор их никто не сводил:
// толщину постели ставили из паспорта машины, а не из веса, который называет повар.
//
// ЧТО СЧИТАЕТ. Граммы → объём (по плотности) → толщина постели → прогон модели → диаметр,
// доля начинки, радиус ядра. То есть отвечает на вопрос «что выйдет, если положить N грамм».
//
//   node tools/variants.js            все сценарии таблицей
//   node tools/variants.js --json     машиночитаемо
//
// ⚑ ПЛОТНОСТЬ 0,758 г/см³ — не догадка. Взята из промышленной таблицы «сечение ↔ вес риса»
// (株式会社トップ TSM-900RSR): у хосомаки рис почти сплошной, и его кажущаяся плотность и есть
// плотность шари. Разбор — docs/kitchen-practice.md, раздел «Количественно».
//
// ⚠ РАЗБРОС РУЧНОЙ СКРУТКИ НИКЕМ НЕ ИЗМЕРЕН. Рецепты дают вилку 200–300 г на футомаки, и
// это не погрешность, а сама вариативность: «маки могут получиться разными» (решение
// владельца, #131). Таблица показывает КРАЯ этой вилки, а не единственно верный ответ.

const { execFileSync } = require('child_process');
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const JSON_OUT = process.argv.includes('--json');

const Ρ = 0.758;              // г/см³, плотность шари
const ШИРИНА = 190;           // мм, ширина ролла (сторона листа вдоль оси)

// Сценарии: что кладёт повар. Граммы — из рецептов, размеры начинок — из них же.
const СЦЕНАРИИ = [
  { имя: 'хосомаки · тунец 7,5 мм',  база: 'hoso', г: 80,  постель: 92.4,
    начинки: [['tuna', 0.50]], источник: '細巻 80–100 г (トップ); тунец 7–8 мм角 (白ごはん.com)' },
  { имя: 'хосомаки · огурец',        база: 'hoso', г: 100, постель: 92.4,
    начинки: [['cucumber', 0.50]], источник: 'каппамаки, огурец 「縦6〜8等分」' },
  { имя: 'футомаки · 200 г, канон',  база: 'futo', г: 200, постель: 176.8,
    начинки: [['denbu',0.44],['tamago',0.48],['kanpyo',0.52],['shiitake',0.56],['cucumber',0.60]],
    источник: 'самое частое в рецептах — 200 г' },
  { имя: 'футомаки · 250 г, канон',  база: 'futo', г: 250, постель: 176.8,
    начинки: [['denbu',0.44],['tamago',0.48],['kanpyo',0.52],['shiitake',0.56],['cucumber',0.60]],
    источник: '太巻 200–250 г (トップ); 250 г (米子医療センター)' },
  { имя: 'футомаки · 250 г, лосось', база: 'futo', г: 250, постель: 176.8,
    начинки: [['salmon',0.48],['avocado',0.54],['cucumber',0.60]],
    источник: 'лосось и авокадо 「1cm角の棒状」 (クラシル)' },
];

// Толщина постели из веса: V = г/ρ, T = V / (длина × ширина).
const толщина = (г, постель) => (г / Ρ * 1000) / (постель * ШИРИНА);

function прогон(сц) {
  const T = толщина(сц.г, сц.постель);
  const код = `
    S.base = ${JSON.stringify(сц.база)}; S.wrap = null; S.turns = null; S.shape = 'round';
    S.hand = { air: 0, wobble: 0, phase: 0, press: 1, v: 1, cv: 0, hold: 0 };
    BASES[S.base].T = ${(T / 5).toFixed(6)};
    S.lists[S.base] = ${JSON.stringify(сц.начинки)}.map(([kind, u], i) =>
      ({ kind, u, v: 0.5, z0: 0, z1: 0, phase: i * 1.3 }));
    touchModel(); layout();
    const мод = getModel(), ветер = windFor(мод, 0.5), Р = мод.Rmax, N = 240;
    let нач = 0, точек = 0, сумР = 0;
    for (let i = 0; i < N; i++) for (let j = 0; j < N; j++) {
      const x = (i + 0.5) / N * 2 - 1, y = (j + 0.5) / N * 2 - 1, rr = Math.hypot(x, y);
      if (rr > 1) continue; точек++;
      const q = materialAt(мод, ветер, 0.5, rr * Р, Math.atan2(y, x));
      if (q && q.cls === 'patch') { нач++; сумР += rr; }
    }
    globalThis.ВЫХОД = { d: 2 * Р * U_MM, доля: нач / точек,
      ядро: мод.core ? мод.core.R / Р : null, витков: ветер.turns,
      обхват: Math.PI * 2 * Р * U_MM, средний: нач ? сумР / нач : null };
  `;
  const врем = path.join(require('os').tmpdir(), 'вариант.js');
  fs.writeFileSync(врем, код);
  const out = execFileSync('node', [path.join(ROOT, 'tools', 'measure-slice.js'), '--eval', врем],
    { encoding: 'utf8' });
  return JSON.parse(out);
}

const строки = СЦЕНАРИИ.map(сц => {
  const T = толщина(сц.г, сц.постель);
  let r; try { r = прогон(сц); } catch (e) { return { ...сц, T, ошибка: e.message }; }
  return { имя: сц.имя, г: сц.г, T, ...r, источник: сц.источник };
});

if (JSON_OUT) { console.log(JSON.stringify(строки, null, 2)); process.exit(0); }

console.log('\n══ ЧТО ВЫЙДЕТ, ЕСЛИ ПОЛОЖИТЬ СТОЛЬКО ГРАММ ══\n');
console.log('  сценарий                       рис г   T мм    ⌀ мм   нахлёст  начинка  ядро/R');
for (const s of строки) {
  if (s.ошибка) { console.log('  ' + s.имя.padEnd(30) + ' — ' + s.ошибка.slice(0, 40)); continue; }
  const лист = s.имя.startsWith('хосо') ? 105 : 210;
  console.log('  ' + s.имя.padEnd(30) + String(s.г).padStart(5) + '  ' + s.T.toFixed(1).padStart(5) +
    '  ' + s.d.toFixed(1).padStart(6) + '  ' + (лист - s.обхват).toFixed(1).padStart(7) +
    '  ' + (100 * s.доля).toFixed(1).padStart(6) + ' % ' + (s.ядро ?? 0).toFixed(3).padStart(7));
}
console.log('\n  нахлёст: сколько нори осталось после обхвата. Отрицательный — ролл не обернуть.');
console.log('  источники сценариев:');
for (const s of строки) console.log('    ' + s.имя.padEnd(30) + s.источник);
console.log('');
