#!/bin/bash
# ВЕЧЕРНЯЯ СВЕРКА — механическая часть.
#
# ЗАЧЕМ. За 31.08.2026 нашлось четыре расхождения ОДНОГО СОРТА: формула в трёх копиях,
# шапка файла против его же кода, сторож, меривший не ту величину, документ ядра, отставший на два
# поколения. Ни одно не было замечено само — все четыре нашлись, когда владелец ткнула
# пальцем. Значит проверка не должна зависеть от того, вспомню ли я про неё.
#
# Этот скрипт НИЧЕГО НЕ ЧИНИТ. Он называет расхождения и молчит там, где всё сходится.
# Всё, что можно проверить командой, — здесь. Всё, что требует прочитать и рассудить, —
# в скиле .claude/skills/end-of-day/SKILL.md, и туда же ведёт итог.
#
#   ./tools/end-of-day.sh
# ⚠ ИМЕНА ПЕРЕМЕННЫХ ТОЛЬКО ЛАТИНИЦЕЙ. Bash кириллицу в именах не берёт и падает
# невнятно: «разных=1: command not found». Первая редакция этого файла на этом и упала.
# Тексты и комментарии — по-русски, идентификаторы — нет. Та же болезнь, что уронила
# воркфлоу 31.08: JSON Schema отвергает кириллические ключи (STATE.md).
set -uo pipefail
cd "$(dirname "$0")/.."
bad=0
say()  { printf '%s\n' "$*"; }
warn() { bad=$((bad+1)); printf '  ✗ %s\n' "$*"; }
ok()   { printf '  ✓ %s\n' "$*"; }

# ─────────────────────────────────────────────────────────────── 1. маркеры кэша
# Правило проекта: ?v=N в play/index.html поднимается ПОСЛЕ правки скриптов. Забыть его —
# значит показывать владельцу вчерашнюю игру и спорить о том, что уже исправлено.
say "── маркеры кэша ?v="
ver=$(grep -o 'v=[0-9]\+' play/index.html | head -1 | cut -d= -f2)
if [ -z "$ver" ]; then warn "в play/index.html не нашлось ни одного ?v="; else
  nvers=$(grep -o 'v=[0-9]\+' play/index.html | sort -u | wc -l | tr -d ' ')
  [ "$nvers" != "1" ] && warn "маркеры разные ($nvers штук) — часть файлов отдастся из кэша"
  # newer ли index.html, чем скрипты, которые он грузит
  newer=0
  while read -r f; do
    [ -f "play/$f" ] || { warn "index.html грузит play/$f, а файла нет"; continue; }
    # ⚠ ВРЕМЯ ПРАВКИ — НЕ ДОКАЗАТЕЛЬСТВО ПРАВКИ. Файл можно тронуть, не изменив: 01.09 перебор
    # толщины риса переписывал catalog.js одним и тем же содержимым, и сторож потребовал поднять
    # маркер там, где браузеру нечего перезагружать. Поэтому время — лишь первый фильтр, а
    # решает git: если содержимое совпадает с закоммиченным и index.html закоммичен тем же
    # состоянием, тревоги нет.
    if [ "play/$f" -nt play/index.html ]; then
      if git diff --quiet -- "play/$f" 2>/dev/null && git diff --quiet -- play/index.html 2>/dev/null; then
        :   # оба чисты в git — содержимое то же, что при последнем бампе
      else
        warn "play/$f новее index.html — маркер не поднят"; newer=1
      fi
    fi
  done < <(grep -o 'src="[^"?]*' play/index.html | cut -d'"' -f2)
  [ "$newer" = "0" ] && ok "v=$ver, все скрипты старше index.html"
fi

# ⚑ МАРКЕР НУЖЕН НЕ ТОЛЬКО СКРИПТАМ, НО И САМИМ СТРАНИЦАМ (issue #144, заведено 01.09).
# Владелец трижды прислала снимок сломанной таблицы; я трижды правила файл и пушила, а она
# видела то же самое — её браузер отдавал кэш, потому что ССЫЛКА на страницу не менялась.
# Полчаса и три неверных диагноза. У скриптов игры маркер есть с начала, и там такого не было.
# Проверка та же по духу: страница правится → ссылка на неё обязана измениться.
say "── маркеры кэша у страниц"
pnewer=0
# ⚠ Имена переменных ТОЛЬКО латиницей: кириллица даёт «not a valid identifier», цикл молча
# не выполняется, и проверка светит зелёным, ничего не проверив. Наступала 01.09 дважды.
while IFS='|' read -r src dst; do
  [ -f "$dst" ] || { warn "$src ссылается на $dst, а файла нет"; continue; }
  base=$(basename "$dst" .html)
  dir=$(dirname "$dst" | sed 's|^\./||')
  if ! grep -q "$base\.html?v=" "$src" 2>/dev/null && ! grep -q "$dir/?v=" "$src" 2>/dev/null; then
    warn "$src ссылается на $dst без ?v= — правка вёрстки не дойдёт до открывавших"; pnewer=1
  fi
done <<'СПИСОК'
index.html|play/index.html
index.html|docs/index.html
docs/index.html|docs/reports/piece-body.html
docs/index.html|docs/reports/kinematics.html
СПИСОК
[ "$pnewer" = "0" ] && ok "все ссылки между страницами несут ?v="

# ⚑ СТОРОЖ МОДЕЛИ — ТЕПЕРЬ ЗДЕСЬ, А НЕ ТОЛЬКО В БРАУЗЕРЕ (issue #147, 01.09).
# До этого весь play/checks.js жил только в странице: чтобы узнать, не сломала ли правка
# модель, надо было ПОМНИТЬ открыть ?check. За вечер 01.09 это поймало три регрессии — и
# столько же раз я забывала сходить. Теперь механическая часть зовёт его сама.
# ⚠ Числа про пиксели и вёрстку отсюда читать нельзя (ширину текста считает заглушка) —
# за ними в браузер. Модель, эталоны, слепок, практика, фасад, пазл и жест проверены полностью.
say "── сторож модели (play/checks.js без браузера)"
if node tools/check.js --quiet 2>&1 | tail -20 | grep -q '^ВСЁ ЦЕЛО'; then
  ok "$(node tools/check.js --quiet 2>/dev/null | head -1)"
else
  node tools/check.js --quiet 2>&1 | tail -20 | while read -r строка; do warn "$строка"; done
fi

# ─────────────────────────────────────────────────────────────── 2. кодировка отчётов
# HTML без charset отдаётся кракозябрами с любого сервера, не шлющего заголовок. Ловилось.
# ⚑ ССЫЛКИ ПО НОМЕРУ СТРОКИ (issue #149, заведено 01.09).
# Комментарий, ссылающийся на «geometry.js:675», указывает на другую строку через час работы —
# и врёт тем увереннее, чем дольше живёт. Замер 01.09: из четырёх таких ссылок в проекте ТРИ
# уже указывали не туда, и две из них были написаны в тот же вечер. Ссылаться надо на ИМЯ —
# функцию, константу, набор: имя переживает правку, номер нет.
# ⚠ Имена переменных здесь ЛАТИНИЦЕЙ. Кириллическое имя bash не принимает («not a valid
# identifier»), цикл молча не выполняется, и проверка рапортует зелёным. Поймано трижды.
say "── ссылки по номеру строки в комментариях"
linerefs=$(grep -rn -E '(geometry|slice|sheet|checks|practice|actions|controls|catalog|util|state|album|puzzle|fixtures|roll)\.js:[0-9]+' play tools 2>/dev/null | grep -v 'end-of-day.sh' | grep -E '^\S+:[0-9]+: *(//|\*|#)' || true)
if [ -z "$linerefs" ]; then ok "ссылок по номеру строки нет"; else
  echo "$linerefs" | while IFS= read -r ln; do warn "${ln:0:150}"; done
fi

say "── HTML: <meta charset>"
n=0
while read -r f; do
  grep -qi 'charset' "$f" || { warn "$f без <meta charset> — кракозябры вне GitHub Pages"; n=1; }
done < <(git ls-files '*.html')
[ "$n" = "0" ] && ok "во всех HTML указана кодировка"

# ─────────────────────────────────────────────────────────────── 3. в git только исходники
# 72 скриншота отработанного ревью весили 4,5 МБ из 6,1 МБ репозитория. git хранит все
# версии навсегда, поэтому ловить надо на входе, а не когда список распух.
say "── в git только исходники"
junk=$(git ls-files | grep -Ei '\.(png|jpg|jpeg|gif|mp4|npy|npz|log)$' | grep -v '^play/assets/' | grep -v '/docs/')
if [ -n "$junk" ]; then
  warn "результаты прогонов в git:"; printf '%s\n' "$junk" | sed 's/^/      /'
else ok "бинарных результатов нет"; fi
size=$(du -sh .git | cut -f1); ok "репозиторий: $size"

# ─────────────────────────────────────────────────────────────── 4. язык
# Правило владельца 31.08: устоявшийся термин НЕ переводим (коммит, пуш, issue, milestone,
# baseline, pipeline). Убираем кальку-метафору — буквальный перевод, который по-русски не
# значит того, что значил в оригинале. Образец: «сгнить» вместо bit rot.
say "── русский язык: кальки, а не термины"
calques='сгни|гнил|задропа|заапрув|пофикси|зарелиз|задеплой|заюзать|апрувну|чекну|засабмит|отревьюи|проапдейт|смёржи|заассайн'
n=0
while read -r f; do
  # ⚠ УПОТРЕБЛЕНИЕ ПРОТИВ ЦИТИРОВАНИЯ. Первая редакция поймала саму себя: правило, которое
  # объясняет, почему «сгнить» плохо, содержит слово «сгнить». Строка, где калька стоит в
  # кавычках-ёлочках, — это разбор слова, а не его употребление, и она законна.
  m=$(grep -niE "$calques" "$f" | grep -vE '«[^»]*('"$calques"')' | grep -v "^[0-9]*:calques=" | head -3)
  [ -n "$m" ] && { warn "$f:"; printf '%s\n' "$m" | sed 's/^/      /'; n=1; }
done < <(git ls-files '*.md' '*.js' '*.py' '*.sh')
[ "$n" = "0" ] && ok "калек не нашлось"

# ─────────────────────────────────────────────────────────────── 5. ссылки внутри доков
# ⚠ ЛОВИТСЯ НЕ ОТСУТСТВИЕ ФАЙЛА, А МОЛЧАНИЕ О НЁМ. Ссылаться на файл, которого нет, можно:
# журнал обязан помнить растворённые доки, план обязан называть ещё не написанные. Нельзя
# другое — упоминать его так, будто он есть. Поэтому строка считается честной, если рядом
# сказано: в архиве, растворён, удалён, ещё не написан, планируется, будет.
say "── ссылки на файлы и issues"
n=0
honest='в архиве|архив|растворё|растворен|удалён|удален|не написан|не существует|планируется|будущий|будет написан|появится'
while read -r f; do
  while read -r ref; do
    [ -e "$ref" ] || [ -e "$(dirname "$f")/$ref" ] || {
      grep -F "$ref" "$f" | grep -qiE "$honest" || { warn "$f ссылается на $ref — файла нет, и об этом не сказано"; n=1; }
    }
  done < <(grep -oE '`(docs|play|sim|tools)/[A-Za-z0-9_./-]+`' "$f" | tr -d '`' | sort -u)
done < <(git ls-files '*.md')
[ "$n" = "0" ] && ok "несуществующие файлы названы честно"

# ─────────────────────────────────────────────────────────────── 6. одно определение
# Формула, живущая в двух файлах, разойдётся. s_fold жил в одиннадцати; cutSpan и свёртка
# карты уже расходились. Здесь — только известные имена: список пополняется по факту.
say "── одно определение на всех"
n=0
# ⚠ ПОЧЕМУ ЗДЕСЬ НЕТ U_MM И GRAIN, хотя они дублируются. Проверка ревью 31.08 нашла три
# настоящих дубля, и все три этим сторожем НЕ ЛОВЯТСЯ по устройству: они совпадают ЗНАЧЕНИЕМ
# под РАЗНЫМИ именами — 5 мм как U_MM · MAT_U_MM · PRIM_U_MM, зерно 0,7 как GRAIN и
# GRAIN_ACROSS. Список ищет имена. Попытка внести их сюда сработала только подстрокой
# (U_MM нашёлся внутри MAT_U_MM) — то есть случайно, и вывод зашумился десятком файлов.
# Случайная ловля хуже отсутствия: она создаёт видимость проверки. Дубли заведены задачей.
for name in S_FOLD_MARGIN FOLD_CAP rollMapDigest cutSpan; do
  files=$(grep -rl "$name" play/ sim/mat-sdf sim/spiral-roll sim/judge.py tools/ 2>/dev/null \
          | grep -v '__pycache__' | grep -v '/out/')
  cnt=$(printf '%s\n' "$files" | grep -c . )
  if [ "$cnt" -gt 1 ]; then
    # ⚠ ПАТТЕРН ОБЪЯВЛЕНИЯ, А НЕ УПОМИНАНИЯ. Прежний искал "$name *=" — и ловил СРАВНЕНИЕ:
    # строка `typeof rollMapDigest === 'function'` подходила под него и давала ложное красное
    # 01.09. Ложное срабатывание дороже пропуска: сторож, который кричит на исправном коде,
    # приучает не читать его вывод. Требуем ключевое слово объявления слева.
    decl_files=$(printf '%s\n' "$files" | xargs grep -l \
        "^\s*\(const\|let\|var\)\s\+$name\s*=\|^\s*function\s\+$name\b\|^\s*def\s\+$name\b" 2>/dev/null)
    decls=$(printf '%s\n' "$decl_files" | grep -c .)
    # И печатаем ФАЙЛЫ С ОБЪЯВЛЕНИЯМИ, а не все, где имя встретилось: прежний вывод показывал
    # четыре файла на два объявления, и разобраться в нём было нельзя.
    [ "${decls:-0}" -gt 1 ] && { warn "$name объявлено в $decls файлах:"; printf '%s\n' "$decl_files" | sed 's/^/      /'; n=1; }
  fi
done
[ "$n" = "0" ] && ok "известные определения — по одному месту"

# ─────────────────────────────────────────────────────────── 7. gh без предела врёт
# ⚠ ЭТА ПРОВЕРКА ЗАВЕДЕНА 31.08.2026, ПОТОМУ ЧТО Я СНОВА НА ЭТОМ ПОПАЛАСЬ. gh list без
# --limit молча отдаёт ТРИДЦАТЬ элементов и не говорит, что список обрезан. 30.08 я так
# сообщила владельцу «30 открытых, 70 закрытых» вместо 82 и 18; предупреждение об этом
# написано в tools/state-check.sh — и вечером 31.08 я прочитала его, а через час всё равно
# отчиталась «открыто 30», когда открытых было 55. Комментарий в чужом файле не спасает.
say "── gh: явный предел в скриптах"
n=0
while read -r f; do
  m=$(grep -nE 'gh (issue|pr|project) (list|item-list)' "$f" | grep -v -- '--limit' | head -3)
  [ -n "$m" ] && { warn "$f — gh list без --limit (молча отдаст 30):"; printf '%s\n' "$m" | sed 's/^/      /'; n=1; }
done < <(git ls-files '*.sh')
[ "$n" = "0" ] && ok "во всех скриптах предел задан явно"

# ──────────────────────────────────────────────── 8. шапка «Обновлено» против коммитов
# ⚠ ЗАВЕДЕНО 31.08 ПОСЛЕ ПРОВЕРКИ РЕВЬЮ. Ревьюер предлагал ругаться на ЛЮБУЮ дату старше
# 30 дней — это дало бы сто процентов ложных: репозиторий младше порога, а исторические даты
# в комментариях стоят НАМЕРЕННО (правило «отменённое зачёркивают с датой»). Но узкая версия
# той же мысли работает: у доков есть штамп «Обновлено ДД.ММ» в шапке, и он ОБЯЗАН идти
# вровень с последним содержательным коммитом. Проверка нашла четыре отставших дока.
say "── доки: штамп «Обновлено» против последнего коммита"
n=0
while read -r f; do
  stamp=$(grep -om1 'Обновлено [0-9][0-9]\.[0-9][0-9]\.[0-9]\{4\}' "$f" 2>/dev/null | grep -o '[0-9.]*$' || true)
  [ -z "${stamp:-}" ] && continue
  iso=$(echo "$stamp" | awk -F. '{print $3"-"$2"-"$1}')
  last=$(git log -1 --format=%ad --date=short -- "$f")
  [ -z "$last" ] && continue
  # ⚠ ФИГУРНЫЕ СКОБКИ ОБЯЗАТЕЛЬНЫ. Было «$stamp» — и bash съедал первый байт закрывающей
  # ёлочки как часть имени переменной: «line 144: stampВ»: unbound variable». Многобайтовый
  # символ вплотную к $имени ломает разбор. Та же семья, что кириллица в идентификаторах.
  if [ "$iso" \< "$last" ]; then warn "$f — шапка «${stamp}», а правился ${last}"; n=$((n+1)); fi
done < <(git ls-files 'docs/*.md' '*.md')
[ "$n" = "0" ] && ok "штампы идут вровень с правками"

# ─────────────────────────────────────────────────────────────── итог
say ""
if [ "$bad" = "0" ]; then
  say "МЕХАНИЧЕСКАЯ ЧАСТЬ ЧИСТА."
else
  say "РАСХОЖДЕНИЙ: $bad."
fi
say ""
say "Это не вся сверка. Осталось то, что командой не проверить:"
say "  · сторожа зелены и мерят ТО, ЧТО НАЗЫВАЮТ (?check, ?check&practice, state-check.sh);"
say "  · док и код говорят одно — включая шапку файла против его же кода;"
say "  · утверждения без источника и с истёкшей датой;"
say "  · issues описывают сегодняшнее состояние, а не вчерашнее;"
say "  · оба HTML-отчёта: свежие ли кадры, те ли подписи."
say "Порядок и глубина — .claude/skills/end-of-day/SKILL.md"
exit 0
