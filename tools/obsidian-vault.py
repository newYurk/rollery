def уровни_для(k):
    """На каких уровнях пазла эта начинка может попасть в цель.

    Не пересказ, а тот же отбор, что в `genTarget` (play/modes/puzzle.js): нори и волнистую пасту
    цель не берёт вовсе; краска идёт только в слоты `paint`, длинный лист — только в слот `sheet`,
    короткая начинка — только в слоты `local`, а всё остальное добирает цель до нужного числа и
    потому встречается на любом уровне. Порядок проверок тот же, что в игре, иначе краска с
    короткой длиной попала бы не в свой слот."""
    v = CAT['ing'][k]
    L = PUZ['levels']
    if k == 'nori' or v['wave']:
        return []
    if v['paint']:
        return [i for i, lv in enumerate(L) if lv.get('paint')]
    if v['wU'] >= 6:
        return [i for i, lv in enumerate(L) if lv.get('sheet')]
    if v['dv'] < 1:
        return [i for i, lv in enumerate(L) if lv.get('local')]
    return list(range(len(L)))


def список_уровней(ns):
    """Номера уровней словами: «1–16» вместо перечисления шестнадцати чисел."""
    if not ns:
        return ''
    ns = sorted(n + 1 for n in ns)
    куски, a = [], ns[0]
    for x, y in zip(ns, ns[1:] + [None]):
        if y != (x + 1):
            куски.append(str(a) if a == x else '%d–%d' % (a, x))
            a = y
    return ', '.join(куски)


