def шапка(поля, простые=()):
    """ЗАВИСИМОСТЬ ПИШЕТСЯ ОДИН РАЗ — в frontmatter той заметки, которая зависит (18.09).

    Ссылка в свойстве даёт настоящее ребро графа, попадает в Backlinks и читается Breadcrumbs
    (имя поля = имя ребра). Обратную ссылку не пишем НИКОГДА: A↔B рисует два ребра друг поверх
    друга, и направление прочитать нельзя. Ссылки в YAML обязаны быть в кавычках.
    Свойства по-русски: владелец читает их в панели «Свойства»."""
    # Простые значения (вид, вкус) — НЕ ссылки: признак не должен давать ребро, иначе каждый
    # признак становится узлом-хабом, к которому сходится полкаталога. Их место — фильтр и цвет.
    стр = ['%s: %s' % (имя_поля, v) for имя_поля, v in простые if v]
    for имя_поля, v in поля:
        if not v:
            continue
        if isinstance(v, list):
            стр.append(имя_поля + ':')
            стр += ['  - "%s"' % link(x) for x in v]
        else:
            стр.append('%s: "%s"' % (имя_поля, link(v)))
    return ('---\n%s\n---\n\n' % '\n'.join(стр)) if стр else ''


