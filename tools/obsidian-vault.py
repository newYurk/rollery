def сторож_места():
    """⚑ ХРАНИЛИЩЕ ЖИВЁТ В ВЕТКЕ, А НЕ В ЛЮБОЙ РАБОЧЕЙ КОПИИ (17.09).

    Первый прогон я сделал из копии на `main`, где хранилища нет: генератор послушно создал папку
    рядом с игрой, она осталась вне git, и владелец нашла её раньше меня — «вижу эту папку не там,
    где у других проектов». Поэтому без явного пути пишем только туда, где хранилище уже под
    контролем git: в чужой копии инструмент теперь отказывается работать, а не плодит вторую."""
    if len(sys.argv) > 1:
        return
    r = subprocess.run(['git', '-C', ROOT, 'ls-files', '--', 'Rollery-Obsidian'], capture_output=True, text=True)
