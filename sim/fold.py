"""ГДЕ ПРИЗЕМЛЯЕТСЯ БЛИЖНИЙ КРАЙ — ОДНО ОПРЕДЕЛЕНИЕ НА ВСЮ ЛАБОРАТОРИЮ.

До 31.08.2026 это правило жило в ТРЁХ местах и все три разошлись:

  • sim/mat-sdf/run.py    — fold_zone(): конец начинок + 1 T, с потолком 0,45 L;
  • sim/judge.py:48-54    — руками вписанная копия тех же чисел, и в комментарии
                            честно стояло «same rule in both attempts»;
  • sim/spiral-roll/run.py:1471 — третий вариант: без потолка и без кластеризации,
                            просто max по ВСЕМ прямоугольникам.

Расхождение не теоретическое. Владелец увидела в прогонах хвостик нори внутри
ролла, с рисом по обе стороны от него, и сказала, что так быть не должно. Она
права: край садился на 14–23 % листа вместо 88–95 %, лист складывался почти
вдвое, и отсюда брались погребённый крючок и 1,3–1,4 оборота вместо одного.

ЧТО ГОВОРИТ ИСТОЧНИК. Край ведут ДО ДАЛЬНЕЙ КРОМКИ РИСА — до границы «рис / голая
нори». Одиннадцать источников, японских и английских, говорят это почти дословно
одинаково (разбор с цитатами — sim/KINEMATICS.md, раздел от 31.08.2026). Перелёт
источники называют ошибкой по имени: 「すし飯をのせていない海苔を越える失敗」.
Недолёт на половину листа не рассматривают вовсе.

ГЕОМЕТРИЯ САМА ПОДТВЕРЖДАЕТ ЦИТАТУ, и это лучшая проверка, какая тут возможна.
Рис начинается в x = 0 и кончается в x = L − flap. Если вести край именно туда,
начало риса встречает конец риса ТОРЕЦ В ТОРЕЦ — ровно то, что источник описывает
отдельной фразой 「寿司飯と寿司飯の端を合わせて」. Остаток листа (flap, のりしろ) —
голая нори, она обходит снаружи и заклеивает шов. Один оборот, как и сказано.
Ни одно другое положение края такого совпадения не даёт.

⚠ ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Начинки на дальность подворота НЕ ВЛИЯЮТ. Прежние
константы (FOLD_REACH, FOLD_GAP, S_FOLD_MARGIN, S_FOLD_EMPTY, FOLD_CAP) исходили
из того, что край заводят «за начинки», и потому пустой лист сворачивался иначе,
чем полный. В источниках такой зависимости нет: цель края — кромка риса, и она
одна и та же, лежит ли на листе тунец или ничего. Начинки решают, что попадёт
ВНУТРЬ ядра (fold_members ниже), а не куда доедет край.

⚠ ОГОВОРКА ЧЕСТНОСТИ, её нельзя терять при копировании. Ни один источник не
описывает, ГДЕ КРОМКА ОКАЗЫВАЕТСЯ ПОСЛЕ скрутки: все инструкции обрываются на
«шов вниз, дай отлежаться». Всё, что здесь есть, — про ЦЕЛЬ движения, и она
процитирована. Про исход движения лаборатория и должна ответить; подсказывать ей
ответ нельзя, иначе прибор перестанет быть прибором.

Расхождение в корпусе, которое тоже нельзя замолчать: 銀座わたり про футомаки
говорит иначе — 「具の端に持っていくイメージで」 (к краю начинок), а про 中巻き
「全体の1/3のあたりに」 (на треть листа). Тот же источник про хосомаки говорит «до
границы риса и нори», то есть противоречит сам себе. Десять источников против
одного противоречивого — берём десять, но факт записан.
"""

# Коридор, в который обязана попасть посадка, — доля листа. Из тех же одиннадцати
# источников. Это СИТО, а не цель: цель считается geometrically ниже, а коридор
# ловит случай, когда чья-то правка снова уведёт край на половину листа.
LANDING_WINDOW = (0.85, 0.97)

# ⚠ ГДЕ ЭТО ОПРЕДЕЛЕНИЕ ДЕЙСТВУЕТ, А ГДЕ НЕТ — граница проведена сознательно.
# На него переведены живой путь и судья: sim/mat-sdf/run.py, sim/spiral-roll/run.py, sim/judge.py.
# НЕ переведены ДЕВЯТЬ прежних попыток, и это не забывчивость:
#     kin-grab · kin-mat · mat-chain · play · reference · reference2 · spiral · spiral-curl · spiral-seed
# Почти у каждой в out/ лежат метрики, посчитанные ИМЕННО тем кодом — кроме sim/play/,
# где каталога out/ нет вовсе: эта попытка заморожена без прогонов. Правка кода задним числом сделала
# бы запись невоспроизводимой — попытка перестала бы быть записью о том, что было. Они остаются
# как есть, со старым правилом внутри, и читать их надо как прогоны ДО исправления.
# Новая попытка обязана импортировать этот модуль, а не копировать константы.


def fold_landing(l_sheet, l_flap):
    """x, куда ведут ближний край: дальняя кромка риса. В тех же единицах, что лист."""
    return max(0.0, l_sheet - l_flap)


def landing_fraction(l_sheet, l_flap):
    """Та же посадка долей листа — число, которое сверяют с источником и с коридором."""
    return fold_landing(l_sheet, l_flap) / l_sheet if l_sheet > 0 else 0.0


def landing_ok(l_sheet, l_flap):
    lo, hi = LANDING_WINDOW
    return lo <= landing_fraction(l_sheet, l_flap) <= hi


def fold_members(rects, s_fold):
    """Начинки, оказавшиеся ВНУТРИ ядра подворота, и их площадь.

    Прямоугольник — (x, y, dx, dy, round, name). Внутрь попадает то, что целиком
    легло ближе посадки: край проходит над ним и заворачивает его в первый виток.
    Круглым (round) считается площадь эллипса, как и везде в лаборатории.

    Отдельно от посадки, потому что это ДРУГОЙ вопрос: посадка — про кинематику
    (куда доехал край), состав ядра — про площадь (что внутри). Прежний код решал
    оба одной формулой, и оттого правка одного ломала другое.
    """
    sel = [r for r in rects if r[0] + r[2] <= s_fold]
    area = sum((3.141592653589793 / 4 if r[4] else 1.0) * r[2] * r[3] for r in sel)
    return sel, area
