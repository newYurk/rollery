#!/bin/bash
# Лаборатория скрутки — открыть стенд в браузере.
#   ./lab.sh          запустить (работает и на маке, и с телефона в той же сети)
#   Ctrl+C            остановить
#
# Слушаем 0.0.0.0, а не только 127.0.0.1: иначе лаборатория открывалась ТОЛЬКО на самом маке,
# а с телефона молча не отвечала — и выглядело это как «лаборатория сломалась» (30.08.2026).
# Отдельный phone.sh для этого больше не нужен.
#
# Если нужно закрыть доступ из сети (чужой Wi-Fi, кафе):  LAB_HOST=127.0.0.1 ./lab.sh
cd "$(dirname "$0")"
source ../.venv/bin/activate
PORT="${LAB_PORT:-8770}"
( sleep 1.2; open "http://127.0.0.1:$PORT" 2>/dev/null ) &
LAB_HOST="${LAB_HOST:-0.0.0.0}" LAB_PORT="$PORT" python serve.py
