// ---------------------------------------------------------------- модель листа
// Размеры патча: у обёрточных нори-патчей размеры и высота переопределены под начинку.
function sheetLen(b) { if (!S.turns) return b.L; const P0 = b.T + b.w, th = TAU * S.turns; return R0 * th + P0 * th * th / (2 * TAU); }
// ПАРАМЕТР g — ПАСПОРТ МОДЕЛИ, а не глобальное «сейчас».
// Модель строится один раз и потом живёт своей жизнью: её карту материалов спрашивают из «Пазла»
// (цель против игрока), из альбома, из будущего inverse design. Пока геометрия читала S.base / S.turns
// напрямую, построенная модель хосомаки после переключения базы на рулет считалась по параметрам рулета
// (замерено: 8 % пикселей карты уезжало). Поэтому всё, что зависит от базы, проходит через g;
// g === undefined — старое поведение «по текущей базе», чтобы не ломать вызовы из UI.
function gL(g) { return g ? g.L : sheetLen(B()); }
function dims(p, g) { const d = ING[p.kind], T = g ? g.T : B().T; return { du: (p.wU ?? d.wU) / gL(g), dv: p.dv ?? d.dv, h: (p.hU ?? d.hU) / T }; }
// Патч может лежать под углом rot к оси ролла: 0 — вдоль, 90° — поперёк, 45° — по диагонали.
// Тогда в каждом ломтике он оказывается на другом месте листа — рисунок меняется от кусочка к кусочку.
function bounds(p, g) {
  const d = ING[p.kind], m = dims(p, g), L = gL(g), Wv = g ? g.Wv : B().Wv, amp = d.wave ? d.wave.amp : 0, rot = p.rot || 0, c = Math.abs(Math.cos(rot)), sn = Math.abs(Math.sin(rot));
  const w = m.du * L, len = m.dv * Wv, hu = (w * c + len * sn) / 2 / L, hv = (w * sn + len * c) / 2 / Wv;
  return { u0: p.u - hu - amp, u1: p.u + hu + amp, v0: p.v - hv, v1: p.v + hv };
}
// Отрезок листа (в единицах длины, вдоль u), который патч занимает в ломтике v; null — патча в этом ломтике нет.
// ОТВЕТ КЭШИРУЕТСЯ НА ПАТЧЕ. Отрезок не зависит ни от радиуса, ни от угла — только от патча, ломтика v
// и паспорта g, — а спрашивают его на КАЖДОМ шаге профиля толщины (тысячи шагов на ломтик) и на КАЖДОМ
// пикселе среза. На рулете это сотни тысяч одинаковых вычислений тригонометрии и столько же выброшенных
// массивов на одну модель. Ключ — не округлённая позиция (на этом легко обмануться: сдвиг в 1e-7 не
// различается и меряешь попадание в кэш), а САМИ поля патча: запись хранит g и всё, от чего зависит
// отрезок, и выбрасывается, как только хоть одно поле разошлось.
// Возвращённый массив ОБЩИЙ для всех вызывающих — его нельзя менять (никто и не менял: все только читают).
const SR_MAX = 64;   // ломтиков на модель — второй десяток; больше — значит v идёт непрерывно, и кэш пора сбросить
function srReset(p, g) {
  const c = { g, kind: p.kind, u: p.u, v: p.v, rot: p.rot, wU: p.wU, dv: p.dv, phase: p.phase, m: new Map() };
  // не перечислимое: патч уходит и в JSON.parse(JSON.stringify(...)) при клонировании модели, и в localStorage
  if (Object.prototype.hasOwnProperty.call(p, '_sr')) p._sr = c;
  else Object.defineProperty(p, '_sr', { value: c, writable: true, configurable: true, enumerable: false });
  return c;
}
function patchSRange(p, v, g) {
  if (g === undefined) return srCompute(p, v, g);   // без паспорта размеры берутся из текущей базы и могут уехать — не кэшируем
  let c = p._sr;
  if (c === undefined || c.g !== g || c.kind !== p.kind || c.u !== p.u || c.v !== p.v || c.rot !== p.rot || c.wU !== p.wU || c.dv !== p.dv || c.phase !== p.phase) c = srReset(p, g);
  let r = c.m.get(v);
  if (r === undefined) { r = srCompute(p, v, g); if (c.m.size >= SR_MAX) c.m.clear(); c.m.set(v, r); }
  return r;
}
function srCompute(p, v, g) {
  const d = ING[p.kind], m = dims(p, g), L = gL(g), Wv = g ? g.Wv : B().Wv, rot = p.rot || 0, c = Math.cos(rot), sn = Math.sin(rot);
  const w = m.du * L, len = m.dv * Wv, dv_ = (v - p.v) * Wv;
  let lo = -1e9, hi = 1e9;
  if (Math.abs(c) > 1e-6) { const a = (-w / 2 - dv_ * sn) / c, e = (w / 2 - dv_ * sn) / c; lo = Math.max(lo, Math.min(a, e)); hi = Math.min(hi, Math.max(a, e)); }
  else if (Math.abs(dv_) > w / 2) return null;
  if (Math.abs(sn) > 1e-6) { const a = (dv_ * c - len / 2) / sn, e = (dv_ * c + len / 2) / sn; lo = Math.max(lo, Math.min(a, e)); hi = Math.min(hi, Math.max(a, e)); }
  else if (Math.abs(dv_) > len / 2) return null;
  if (hi <= lo) return null;
  let uc = p.u; if (d.wave) uc += d.wave.amp * Math.sin(TAU * d.wave.freq * v + p.phase);
  return [uc * L + lo, uc * L + hi, uc, w, len, c, sn, dv_];
}
// Патч в ФИЗИЧЕСКИХ координатах листа (su = u·L вдоль скрутки, sv = v·Wv вдоль оси):
// центр, единичная ось ПОПЕРЁК куска (та же, по которой patchSRange считает across) и полуразмеры.
function patchBox(p, g) {
  const m = dims(p, g), L = gL(g), Wv = g ? g.Wv : B().Wv, rot = p.rot || 0;
  return { cx: p.u * L, cy: p.v * Wv, ax: Math.cos(rot), ay: Math.sin(rot), hw: m.du * L / 2, hl: m.dv * Wv / 2 };
}
// Разделяющая ось (SAT) для двух прямоугольников: если хоть на одной из четырёх осей проекции
// разошлись — пересечения нет.
function boxHit(A, Bb) {
  const dx = Bb.cx - A.cx, dy = Bb.cy - A.cy;
  for (let i = 0; i < 4; i++) {
    const src = i < 2 ? A : Bb, nx = i & 1 ? -src.ay : src.ax, ny = i & 1 ? src.ax : src.ay;
    const ra = A.hw * Math.abs(A.ax * nx + A.ay * ny) + A.hl * Math.abs(A.ax * ny - A.ay * nx);
    const rb = Bb.hw * Math.abs(Bb.ax * nx + Bb.ay * ny) + Bb.hl * Math.abs(Bb.ax * ny - Bb.ay * nx);
    if (Math.abs(dx * nx + dy * ny) > ra + rb) return false;
  }
  return true;
}
// ПОЧЕМУ не один AABB. Габарит повёрнутого куска вдвое шире самого куска: две диагональные полоски,
// разведённые на сантиметр, габаритами пересекаются, и restack клал одну НА другую. Ролл после этого
// бугрился там, где начинки нет. Теперь AABB — только дешёвая отсечка (не пересеклись габариты —
// не пересеклись и прямоугольники), а решает SAT. Неповёрнутые патчи идут прежним путём, без потери скорости.
function overlap(a, b, g) {
  const A = bounds(a, g), Bb = bounds(b, g);
  if (!(A.u0 < Bb.u1 && Bb.u0 < A.u1 && A.v0 < Bb.v1 && Bb.v0 < A.v1)) return false;
  if (!a.rot && !b.rot) return true;                        // габарит и есть прямоугольник
  if (ING[a.kind].wave || ING[b.kind].wave) return true;    // волнистая паста — не прямоугольник, для неё габарит и остаётся
  return boxHit(patchBox(a, g), patchBox(b, g));
}
// Стопка: что положено позже, лежит выше. Стопка вдавлена в намазку сверху: её верх — на поверхности
// намазки (z=1), пока стопка не выше намазки; выше — торчит и утолщает ролл.
// Возвращает верх намазки в долях её толщины (≥1).
function restack(list, g) {
  const n = list.length, adj = list.map(() => []), paint = list.map(p => !!ING[p.kind].paint);
  for (let i = 0; i < n; i++) for (let j = 0; j < i; j++) if (!paint[i] && !paint[j] && overlap(list[i], list[j], g)) { adj[i].push(j); adj[j].push(i); }
  for (let i = 0; i < n; i++) {
    const p = list[i]; let base = 0;
    for (const j of adj[i]) if (j < i) base = Math.max(base, list[j].z1);
    p.z0 = base; p.z1 = base + dims(p, g).h;
  }
  const seen = new Array(n).fill(false); let top = 1;
  for (let i = 0; i < n; i++) {
    if (paint[i]) { list[i].z0 = 0; list[i].z1 = 1; seen[i] = true; continue; }   // краска: вся толщина намазки, не бугрит
    if (seen[i]) continue;
    const comp = [i]; seen[i] = true;
    for (let k = 0; k < comp.length; k++) for (const j of adj[comp[k]]) if (!seen[j]) { seen[j] = true; comp.push(j); }
    let ctop = 0; for (const k of comp) ctop = Math.max(ctop, list[k].z1);
    const shift = Math.max(0, 1 - (g ? g.kappa : B().kappa) * ctop);   // рис под стопкой сжат частично (κ), не выдавлен целиком
    for (const k of comp) { list[k].z0 += shift; list[k].z1 += shift; top = Math.max(top, list[k].z1); }
  }
  return top;
}
// Какой материал лежит в точке листа (u, v, z). null — намазка.
function matAt(u, v, z, list, g) {
  const L = gL(g);
  for (let pass = 0; pass < 2; pass++) for (let i = list.length - 1; i >= 0; i--) {
    const p = list[i], d = ING[p.kind];
    if (p.inCore || !!d.paint !== (pass === 1)) continue;
    if (!d.paint && (z < p.z0 || z > p.z1)) continue;
    const rg = patchSRange(p, v, g); if (!rg) continue;
    const sU = u * L; if (sU < rg[0] || sU > rg[1]) continue;
    const du_ = sU - rg[2] * L, across = du_ * rg[5] + rg[7] * rg[6], along = -du_ * rg[6] + rg[7] * rg[5];
    const lu = across / rg[3];
    const lz = d.paint ? 0.5 : (z - p.z0) / (p.z1 - p.z0);
    if (!d.paint) { const sp = cutSpan(d, lu); if (lz < sp[0] || lz > sp[1]) continue; }
    return { p, d, lu, lz, lv: along / rg[4] };
  }
  return null;
}
// Геометрия. Единица длины — толщина намазки суши-ролла.
function geometry() { const b = B(); restack(patches()); return { T: b.T, w: b.w, r0: R0, L: sheetLen(b) }; }
const NB = 1440, DPHI = TAU / NB, KMAX = 9;
// ФОРМА КУСКА — ОДНО ОПРЕДЕЛЕНИЕ НА ВСЕХ. Раньше её задавали ДВЕ независимые формулы:
// предикат в matAt/coreMaterial (что закрашивать) и heightAt (какой бугор получается в намотке).
// Они не совпадали, и у ломтика верхний рог срезался ровной горизонталью — не рисовался никогда.
// Теперь определение ровно одно — cutTop, — а форма среза из него выводится (см. cutSpan ниже).
// Всё меряется в долях собственной толщины куска; lu — поперёк куска, −0,5…0,5.
// ФАСКА. Ребро бруска не бывает острым: нож оставляет скругление, и оно тем заметнее, чем
// мягче продукт. Радиус задан в ЕДИНИЦАХ (1 ед. = 5 мм), а не долей куска, — это физический
// размер, одинаковый для толстого тамаго и тонкой ветчины. Ограничители нужны, чтобы фаска
// не съела сам кусок: у листа нори толщиной 0,15 ед. скругление в 0,45 не помещается.
// ⚠ Это МЕНЯЕТ ИГРУ, а не только картинку: у бруска стало чуть меньше вытесняемого риса
// (замер после правки — в docs/journal.md). Так и надо: тело описано честнее, чем было.
const ARRIS = 0.45;

// ── ФОРМА СЕЧЕНИЯ: ТАБЛИЦА ПРОФИЛЕЙ, А НЕ НАБОР ФЛАГОВ (issue #10) ───────────
// Раньше форму выбирали булевы флаги round / lens / flatBottom, и каждая новая форма требовала
// нового флага и новой ветки в cutTop. Разбор японских источников (docs/kitchen-practice.md)
// показал, что форм нужно не три: сектор (огурец «вдоль на 6–8»), полукруг (半月切り, раскрытая
// креветка), полумесяц (долька авокадо), четверть круга (いちょう切り). Флагами это не набрать.
//
// ИМЯ ФОРМЫ БЕРЁТСЯ ИЗ КАТАЛОГА — поле `cut`, которое там уже было, но лежало декорацией:
// его показывали игроку и нигде не читали. Теперь оно и есть выбор профиля, то есть каталог
// сам отвечает за форму, а геометрия только считает. Одно описание вместо двух рассинхронных.
//
// Профиль — ПАРА границ, а не одна с зеркалом: половина форм несимметрична сверху вниз.
// Аргументы: d — запись каталога, a — поперечная координата −1…1, q = 1 − a² (её считают все).
const brickTop = (d, a) => {
  const W = d.wU / 2, H = d.hU;
  const r = Math.min(ARRIS, W * 0.5, H * 0.25);   // ограничители: фаска не съедает кусок
  const s = W * (1 - Math.abs(a));                // расстояние до боковой стенки
  if (s >= r) return 1;
  return 1 - (r - Math.sqrt(Math.max(0, r * r - (r - s) * (r - s)))) / H;
};
const CUT_PROFILES = {
  // симметричные сверху вниз
  'брусок':   { top: (d, a, q) => brickTop(d, a),                  low: (d, a, q) => 1 - brickTop(d, a) },
  'кружок':   { top: (d, a, q) => 0.5 + Math.sqrt(q) / 2,          low: (d, a, q) => 0.5 - Math.sqrt(q) / 2 },
  'ломтик':   { top: (d, a, q) => 0.5 + Math.pow(q, 0.55) / 2,     low: (d, a, q) => 0.5 - Math.pow(q, 0.55) / 2 },
  // с плоским дном: лежат на рисе всей гранью
  'полукруг': { top: (d, a, q) => Math.sqrt(q),                    low: () => 0 },
  // СЕКТОР — первая форма, НЕСИММЕТРИЧНАЯ ЛЕВО-ПРАВО. Так режут огурец для каппамаки:
  // «вдоль на 6–8 частей» (白ごはん.com), и долька ложится на плоскую грань. В сечении это
  // не треугольник: апекс в одном нижнем углу, прямая грань по низу, дуга-кожица сверху.
  //
  //         B                     Прямая грань поднимается от апекса O к точке B, где
  //        /‾‾-_                  второй радиус встречает дугу; дальше дуга опускается
  //       /     ‾-_               к дальнему углу A. Оба конца лежат на нижней грани,
  //      O__________A             вершина смещена — вот она, асимметрия.
  //
  // При t = (a+1)/2 ∈ 0…1 и полном угле 2θ:
  //     t ≤ cos2θ :  верх = t / cos2θ            (прямая грань)
  //     t > cos2θ :  верх = √(1−t²) / sin2θ      (дуга)
  // В точке склейки обе ветки дают ровно 1 — фигура непрерывна.
  // Отсюда же пропорция: wU/hU = 1/sin2θ, то есть для восьми долей ровно √2.
  'сектор': {
    top: (d, a, q) => {
      const t = (a + 1) / 2, c = Math.cos(SECTOR_ANGLE), sn = Math.sin(SECTOR_ANGLE);
      return t <= c ? t / c : Math.sqrt(Math.max(0, 1 - t * t)) / sn;
    },
    low: () => 0,
  },
};
// Полный угол дольки. Источник даёт «на 6–8 частей»; берём 8 — это 45°, и при нём пропорция
// куска выходит √2, то есть огурец ⌀28 мм даёт дольку 14 × 9,9 мм. Шесть долей (60°) дали бы
// кусок вдвое толще, чем влезает в хосомаки.
const SECTOR_ANGLE = Math.PI / 4;
// Класс нарезки из каталога → профиль. Лист и присыпка — тот же брусок (плоская крышка,
// разная толщина); паста рисуется жгутом, но телом остаётся кружком.
const CUT_TO_PROFILE = {
  'брусок': 'брусок', 'лист': 'брусок', 'присыпка': 'брусок',
  'кружок': 'кружок', 'паста': 'кружок', 'ломтик': 'ломтик', 'полукруг': 'полукруг',
  'сектор': 'сектор',
};
// ⚠ Старые флаги round/lens ЧИТАЮТСЯ ДО СИХ ПОР и это не лень: сохранённые роллы в альбоме и
// ссылки-пазлы могут нести запись, сделанную до этой правки. Каталог главнее флагов.
function cutProfile(d) {
  const name = CUT_TO_PROFILE[d.cut] || (d.round ? 'кружок' : d.lens ? 'ломтик' : 'брусок');
  return CUT_PROFILES[name] || CUT_PROFILES['брусок'];
}

// ВЕРХ фигуры в поперечной позиции lu (−0,5…0,5), в долях собственной толщины куска.
function cutTop(d, lu) {
  const a = clamp(lu * 2, -1, 1), q = Math.max(0, 1 - a * a);
  return cutProfile(d).top(d, a, q);
}
// НИЗ фигуры. У симметричных форм это зеркало верха, у форм с плоским дном — ноль; и то и
// другое записано В САМОМ ПРОФИЛЕ, а не выведено допущением снаружи. Флаг `flatBottom`
// остаётся как ручное снятие зеркала для случаев, которым отдельная форма пока не заведена
// (ломтик рыбы кожей вниз): он кладёт кусок на плоское дно, не меняя верхний контур.
function cutLow(d, lu) {
  if (d.flatBottom) return 0;
  const a = clamp(lu * 2, -1, 1), q = Math.max(0, 1 - a * a);
  return cutProfile(d).low(d, a, q);
}
// ФОРМА СРЕЗА — две границы одного контура. Вид сверху и вид в срезе НЕ выводятся друг из
// друга: они ДЕЛЯТ верхний контур. Сверху он читается как рельеф поверхности (что видно
// глазу в позиции lu), в срезе — как верхняя половина фигуры. Низ виден только в срезе.
function cutSpan(d, lu) { return [cutLow(d, lu), cutTop(d, lu)]; }
// СИММЕТРИЧЕН ЛИ КУСОК ПОПЕРЁК. От этого зависит, сколько РАЗНЫХ положений даёт поворот:
// у симметричного 180° — это то же самое, что 0°, и гонять игрока по лишним щелчкам незачем;
// у сектора 180° даёт другую фигуру (замерено: 186 точек среза из 3136 меняются).
//
// ⚠ Проверяется ПРОБОЙ ПО САМОМУ ПРОФИЛЮ, а не флагом в каталоге. Флаг — это второе описание
// той же правды, и оно разъедется с формой при первой же правке; ровно от этого лечили cutSpan.
// Ответ кэшируется по имени профиля: форм всего несколько, а спрашивают на каждой отрисовке.
const SYMM_CACHE = new Map();
function cutSymmetric(d) {
  const key = CUT_TO_PROFILE[d.cut] || (d.round ? 'кружок' : d.lens ? 'ломтик' : 'брусок');
  if (SYMM_CACHE.has(key)) return SYMM_CACHE.get(key);
  let sym = true;
  for (let i = 1; i < 16 && sym; i++) {
    const lu = i / 32;                                  // 0 не проверяем: там всегда совпадёт
    if (Math.abs(cutTop(d, lu) - cutTop(d, -lu)) > 1e-6) sym = false;
    if (Math.abs(cutLow(d, lu) - cutLow(d, -lu)) > 1e-6) sym = false;
  }
  SYMM_CACHE.set(key, sym);
  return sym;
}

// ── ВНЕШНИЙ ВИД КУСКА — ОДНО ОПРЕДЕЛЕНИЕ НА ОБА ВИДА (issue #105) ────────────
// У куска два вида: СВЕРХУ (лежит на листе) и В СРЕЗЕ (после нарезки). Их рисовали две
// независимые функции: patchColor знала про прожилки лосося и семечки клубники, а
// drawPatchShape в рендере листа рисовала свои полоски своим градиентом. Ничто не мешало им
// разойтись — и они разошлись: на листе кусок стал гладко-геометрическим, в срезе остался
// фактурным. Это ТА ЖЕ ошибка, что была с ФОРМОЙ и уже исправлена выше (см. cutSpan):
// одно свойство, два независимых описания. Лечится тем же способом — одним определением.
//
// Кусок — ТЕЛО, и оба вида из него выводятся:
//   · ЧТО ЭТО ЗА ВЕЩЕСТВО в точке — patchColor(lu, lz, lv). Одна на оба вида.
//   · ГДЕ ПОВЕРХНОСТЬ, если смотреть сверху — cutTop(lu): в поперечной позиции lu глаз
//     видит верх тела именно на этой высоте. У бруска это 1 везде (плоская крышка),
//     у кружка — дуга: посередине видно макушку, у краёв — бок.
//   · КАК ОСВЕЩЕНО — из наклона той же поверхности. Свет не рисуется руками ступеньками
//     светлоты: валик светел посередине не потому, что там нарисован блик, а потому что
//     там поверхность смотрит вверх.
//
// ⚠ ЧЕГО ЗДЕСЬ ЕЩЁ НЕТ. Тело — призма: сечение задано поперёк (cutSpan), а вдоль оно
// постоянно. Значит сверху кусок — ПРЯМОУГОЛЬНИК (цилиндр сверху и есть прямоугольник),
// и скруглённые торцы прежнего рисунка были враньём: домен (patchSRange) считает кусок
// прямоугольным, и срез у самого торца показал бы вещество там, где рисунок обещал пустоту.
// Профиль ВДОЛЬ куска (свёрнутая креветка, половинка авокадо) — это #10: он должен войти
// в тело и в patchSRange разом, а не появиться отдельной картинкой.
// Свет СКОЛЬЗЯЩИЙ, а не отвесный, и подсветки немного. Причина не в красоте: кусок на листе
// шириной всего 7 арт-пикселей, и при отвесном свете разница между серединой и фаской выходила
// 4 % — глаз её не видит, кусок читается плоской полосой. Скользящий свет делает ту же
// геометрию различимой, ничего в ней не меняя.
const LIGHT_ACROSS = [-0.58, 0.815];  // откуда светит, в плоскости «поперёк куска — вверх»
const AMBIENT = 0.34;                 // сколько света есть всегда: без него бок уходит в чёрное

// Наклон верхней поверхности поперёк куска. Края обрезаны на epsilon: у кружка там
// вертикальная касательная, и производная уходит в бесконечность.
function pieceSlope(d, lu) {
  const e = 1e-3, a = clamp(lu, -0.5 + e, 0.5 - e);
  return (cutTop(d, a + e) - cutTop(d, a - e)) / (2 * e);
}
// Доля света на верхней поверхности: 0 — тень, 1 — прямо на свет. Свет закреплён в системе
// самого куска, а не мира: повёрнутый кусок освещён так же, как лежащий прямо.
function pieceLight(d, lu) {
  const s = pieceSlope(d, lu);
  return clamp((-s * LIGHT_ACROSS[0] + LIGHT_ACROSS[1]) / Math.hypot(s, 1), 0, 1);
}
// ВИД СВЕРХУ в точке (lu поперёк, lv вдоль): вещество спрашивается у ТОЙ ЖЕ patchColor,
// что красит срез, — только на глубине видимой поверхности.
function pieceTopColor(p, d, lu, lv, px, py) {
  return shade(patchColor({ p, d, lu, lz: cutTop(d, lu), lv }, px, py),
               AMBIENT + (1 - AMBIENT) * pieceLight(d, lu));
}
// БОКОВАЯ ГРАНЬ — тоже вид тела, а не обводка. Смотрим на бок: он вертикален, прямого света
// на нём нет, вещество берётся с середины толщины. Именно она отделяет кусок от риса —
// чёрный контур для этого не годится, он читается как «обёрнут в нори» (владелец, 31.08).
function pieceSideColor(p, d, lu, lv, px, py, k) {
  return shade(patchColor({ p, d, lu, lz: 0.5, lv }, px, py), AMBIENT * k);
}

function covers(p, u, v, g) { return heightAt(p, u, v, g) > 0; }
// Высота начинки над листом в точке (u, v), с учётом ФОРМЫ сечения (нарезки), в долях полной высоты.
// Брусок держит высоту по всей ширине; кружок и ломтик — только в середине. От этого зависит,
// насколько ролл раздувается в этом месте и сколько риса вытесняется: круглый брусок вытесняет меньше.
function heightAt(p, u, v, g) {
  if (p.inCore) return 0;
  const rg = patchSRange(p, v, g); if (!rg) return 0;
  const sU = u * gL(g);
  if (sU < rg[0] || sU > rg[1]) return 0;
  // ⚠ ПОПЕРЁК СЧИТАЕТСЯ ТАК ЖЕ, КАК В matAt, и это не педантизм. Здесь стояло
  // (sU − середина отрезка) / длина отрезка — то есть профиль сечения растягивался на ту
  // часть листа, которую кусок занимает вдоль u. Для НЕПОВЁРНУТОГО куска это его ширина и
  // всё сходится; для повёрнутого — его ДЛИНА, и профиль ложился поперёк не той оси.
  // Замер (креветка ⌀ 10 мм, повёрнута на 90°, идём вдоль её длины): matAt честно говорит
  // «поперёк = 0» во всех точках, а heightAt выдавала высоту 0,543 → 0,866 → 1 → 0,866 → 0,543.
  // То есть рис вытеснялся по одной фигуре, а красился кусок по другой — ровно та болезнь
  // «две формулы на одну форму», от которой заводили cutSpan (см. выше).
  // Сейчас поворот редок (кнопка и два уровня пазла), но при раскладке кистью повёрнут будет
  // КАЖДЫЙ мазок, и дефект стал бы системным.
  const du_ = sU - rg[2] * gL(g);
  const lu = (du_ * rg[5] + rg[7] * rg[6]) / rg[3];
  return cutTop(ING[p.kind], lu);                          // верх ТОЙ ЖЕ фигуры, что рисует matAt
}
// Толщина «намазка + стопка» в точке листа (без обёртки), в единицах: рис под начинкой выдавлен, когда стопка выше намазки.
function stackTopAt(u, v, list, g) {
  let H = 0;
  for (const p of list) {
    if (ING[p.kind].paint) continue;
    const f = heightAt(p, u, v, g); if (f <= 0) continue;
    H = Math.max(H, p.z0 + (p.z1 - p.z0) * f);             // форма куска задаёт профиль бугра
  }
  return H;
}
// Начинка толще намазки при надавливании циновкой сжимается: слой растёт только на β от избытка.
// ДАЛЬНИЙ КРАЙ: БОРТИК, А НЕ СХОД НА НЕТ. Здесь стоял `TAPER` — рис плавно сходил к нулю перед
// голой полосой. Источники говорят обратное, и в один голос: перед норисиро рис намеренно
// ПОДНИМАЮТ — 「ふちを高く」, три независимых источника (oisiiryouri шаг 8, Kurashiru, Tokiwa).
// Причина названа прямо: 「向こう側を高くしておくと、合わせ目のすし飯がうすくならずに、具が中心にきます」 —
// чтобы на стыке рис не оказался тонким и начинка осталась по центру. Мы моделировали ровно тот
// дефект, который повара исправляют. Разбор — docs/reality-check.md, раздел 2.
// МАССА РИСА СОХРАНЯЕТСЯ. Повар кладёт отмеренную порцию (SUZUMO SVR-SAE: 80 г хосомаки,
// 235 г футомаки),
// ⚠ ЗДЕСЬ СТОЯЛО «160 г футомаки», и это была ошибка: 160 — ДЛИНА пласта в миллиметрах у
// машины SVS-FCA (small 7×80, large 12×160), а не масса. 80 случайно совпало с 80 г, и
// миллиметры уехали в граммы вместе с ним. Масса — с другой линии, SVR-SAE (docs/reality-check.md §4).
// и бортик он НАБИРАЕТ из той же грядки, а не досыпает. Поэтому профиль нормирован: средняя по
// грядке равна 1, грядка проседает на 1 %, бортик поднимается на 29 %.
// ⚑ inferred: высоты бортика в миллиметрах нет НИ В ОДНОМ источнике (docs/reality-check.md: «Высота
// бортика нигде не дана в миллиметрах — источника нет»). RIM_W и RIM_H — оценка, не замер.
const RIM_W = 0.05;   // доля листа под бортиком: ≈ 10 мм на футомаки, ≈ 5 мм на хосомаки
const RIM_H = 1.30;   // во сколько раз бортик выше грядки
// СЛАДКИЙ РУЛЕТ — ЗЕРКАЛЬНО К СУШИ, И ЭТО НЕ ОПЕЧАТКА. Крем кладут густо у БЛИЖНЕГО края и
// сводят на нет к дальнему; у суши наоборот — бортик перед норисиро. Три источника:
//   cotta: 「手前は厚め、巻き終わりになる奥側のクリームは少し薄めに」
//   ABC Cooking: 「クリームは手前から3cm程度を厚めに、奥に向かうほど薄くします」
//   macaroni: 「手前をクリームたっぷりにすることで、ロールケーキの芯の部分がしっかりでき」 — густой
//   ближний край нужен, чтобы СЕРДЦЕВИНА рулета получилась плотной.
// Раньше сюда применялся суши-бортик: +30 % крема уходило в ПОСЛЕДНИЙ виток — самый длинный и
// самый заметный на срезе. То есть главный узор сладкой базы был перевёрнут.
// Доли подобраны так, чтобы средняя осталась 1 — крема кладут отмеренную порцию, его не
// прибавляется от того, что размазали иначе.
// Крем кладут не ровным слоем, а ГРЯДОЙ у ближнего края — вот дословно:
//   cotta / DelishKitchen: 「手前から3cm位のところを山高に、奥にいくほどクリームは薄くします」
//   («горкой примерно в 3 см от ближней кромки, дальше к дальнему краю — тоньше»)
//   macaroni: 「手前をクリームたっぷりにすることで、ロールケーキの芯の部分がしっかりでき」 — густой
//   ближний край нужен, чтобы вышла плотная СЕРДЦЕВИНА. Отсюда узнаваемый вид японского
//   ролл-кейка: толстое белое ядро и тонкая спираль снаружи.
// ⚠ Проверено арифметикой, и она сломала расхожее мнение: по базовому рецепту cotta (противень
// 27×27, 3 яйца, 55 г муки, 180 г сливок) бисквит выходит 10–13 мм, а крем 4,4–5,4 мм В СРЕДНЕМ.
// То есть японский рулет НЕ «кремовый»: теста в нём даже больше, чем у нас (8,5 мм). Белым он
// выглядит из-за грядки у сердцевины, а не из-за количества крема.
// БЛИЖНИЙ КРАЙ: ГОЛАЯ ПОЛОСА, А НЕ СХОД НА НЕТ. У нас рис лежал вплотную к самой кромке, и
// именно от этого предостерегает oisiiryouri: 「海苔の手前いっぱいまで広げると巻きづらくなります」 —
// «расстелить рис вплотную к ближней кромке — крутить будет тяжело».
//   marron (руководство с видео): 「すし飯を手前1cm、向こう側2cmほどあけて広げる」 — оставить 1 см
//   у ближнего края и 2 см у дальнего. Единственный источник с миллиметрами на ближний край.
//   Сираи Норико («栄養と料理», 2019/02): 「手前に少し山をつくって、脇は1cm、奥は2cmほどあけると」.
// 1 см на ближнем крае ЦЕЛОГО листа — marron, подтверждено. Для ПОЛУЛИСТА (хосомаки) числа
// на ближний край нет ни в одном источнике: 5 мм у oisiiryouri — это поля ПО БОКАМ и дальняя
// голая полоса, а не ближняя (docs/kitchen-practice.md §1). ⚑ inferred: 0,048 распространено
// на хосомаки как есть; альтернатива из docs/reality-check.md A2 — 10/105 = 0,095.
// ⚠ ЗДЕСЬ СТОЯЛО «оба источника дают одну и ту же долю» — второго источника не существует.
// Полоса нужна не для красоты: ближняя кромка нори садится на ДАЛЬНЮЮ ГОЛУЮ ПОЛОСУ, то есть
// нори на нори — 白ごはん.com: 「すし飯を広げていない海苔の上の端に手前を巻きつけるように」.
// Масса риса сохраняется: грядка стала короче, значит при той же порции она чуть толще.
const SPREAD_START = 0.048;
// Грядка не обрывается стеной. Было: 16,4 мм риса и сразу ноль — на контуре это давало ступеньку
// 2,6 мм по диаметру на трёх часах, и владелец её увидела: «что за артефакт справа посередине».
// Рис так не кладут: у самой кромки его остаётся на пару зёрен, и он сходит на нет. Само нори
// при этом ступеньки дать не может — 0,1 мм при ролле в 50 мм это две тысячных диаметра.
// ⚑ inferred: ширина схода 4 мм на целом листе — оценка по размеру зерна (7,7 мм), замера нет.
const RIM_EDGE = 0.019;
// ⚠ ОТСЮДА УДАЛЁН КРЕМ. База «Рулет» снята решением владельца 31.08: «у нас рулета не будет,
// бисквитный вообще просто никогда — у нас японская тематика». Вместе с ней ушли константы
// CREAM_P / CREAM_A0 / CREAM_PK / CREAM_FAR и ветка `if (b.sweet)` в этой функции: без базы
// её никто не звал, а мёртвый код с калибровочными комментариями — ровно то, на что ругался
// аудит честности чисел (#109).
function spreadAt(u, g) {
  const b = g || B();
  const se = b.spreadEnd; if (u >= se) return 0;
  const s0 = b.spreadStart === undefined ? SPREAD_START : b.spreadStart;
  if (u < s0) return 0;                               // голая полоса у ближнего края
  const span = se - s0, w = Math.min(RIM_W, span * 0.5), e = Math.min(RIM_EDGE, w * 0.6);
  // Нормировка на сохранение массы: грядка + подъём бортика + сход на нет.
  const k = se / ((span - w) + (w - e) * (1 + RIM_H) / 2 + e * RIM_H / 2);
  if (u <= se - w) return k;
  if (u <= se - e) return k * (1 + (RIM_H - 1) * (u - (se - w)) / (w - e));   // подъём к бортику
  return k * RIM_H * (se - u) / e;                    // и сход на нет: стеной рис не стоит
}
const betaEff = g => clamp((g ? g.beta : B().beta) * (g ? g.press : (S.hand ? S.hand.press : 1)), 0.15, 0.95);
// Намотка листа переменной толщины: по угловым бинам, виток за витком. sMax — сколько листа съедено (для анимации скрутки).
const PROF_DS = 0.02, SMOOTH_R = 0.9;   // шаг профиля толщины и радиус сглаживания (единицы ≈ 5 мм)
// Профиль толщины листа вдоль u, сглаженный: лист и рис не дают бугру быть уступом.
// СЧИТАЕТСЯ ОТ НАЧИНОК, а не от каждого шага. Раньше на каждом из M шагов (у рулета их 2849) вызывался
// stackTopAt, то есть все патчи, то есть patchSRange — при шестнадцати ломтиках под двести тысяч вызовов
// на модель, и это было главным расходом построения модели. Но patchSRange от u не зависит: отрезок листа
// у патча один на весь ломтик. Поэтому отрезки берутся ОДИН РАЗ на ломтик, и каждый патч заполняет только
// своё окно индексов — вне окна он и раньше давал ноль. Формула шага не тронута: u, sU, порядок max
// и «(r + β·max(0, H − r))·T» — те же, что были в bandAt/heightAt; вне начинок H = 0 и выражение
// сводится к r·T ровно так же, как сводилось раньше.
// КАРТА ВЫСОТ, редакция 1: рис и начинка разведены в ДВА ПОЛЯ.
// `bed[i]` — верх риса в столбике i, `fill[i]` — верх стопки начинок; оба нормированы на T,
// шаг сетки PROF_DS вдоль листа. Пока `bed[i]` в точности равен `spreadAt(u)`, то есть вывод
// побитово прежний — и это проверено: 50 контрольных сумм FNV-1a по битам Float32 (пять баз ×
// пять раскладок × два почерка × пять срезов) совпали до последнего бита мантиссы.
//
// ЗАЧЕМ ШАГ, КОТОРЫЙ НИЧЕГО НЕ МЕНЯЕТ. Смысл не в поведении, а в том, что у риса появилось
// МЕСТО. Раньше его высота была ВЫРАЖЕНИЕМ внутри цикла — двигать было нечего, и потому
// вытесненный начинкой рис исчезал (issue #1: замерено, начинка удаляет рис почти один к одному,
// 138 мм² из 644 при 145 мм² начинки, а диаметр растёт на 0,2 мм вместо ~1,5).
// Растекание встанет сюда, между заполнением bed и его сложением с fill.
//
// Float64, не Float32: bed и fill складываются как double, иначе округление сдвинет результат.
function riceField(vSlice, g, list) {
  const M = Math.ceil(g.L / PROF_DS) + 2, L = g.L;
  const bed = new Float64Array(M), fill = new Float64Array(M), lo = new Float64Array(M).fill(Infinity);
  for (const p of list) {
    const d = ING[p.kind]; if (d.paint || p.inCore) continue;   // краска не бугрит, подвёрнутое в ядро — не в намотке
    const rg = patchSRange(p, vSlice, g); if (!rg) continue;
    // Поперечная координата — той же формулой, что в matAt и heightAt (см. комментарий там).
    const uc = rg[2] * L;
    // окно с запасом в три шага: границы всё равно перепроверяются тем же сравнением, что и в heightAt
    const i0 = Math.max(0, Math.floor(rg[0] / PROF_DS) - 3), i1 = Math.min(M - 1, Math.ceil(rg[1] / PROF_DS) + 3);
    for (let i = i0; i <= i1; i++) {
      const sU = Math.min(1, i * PROF_DS / L) * L;
      if (sU < rg[0] || sU > rg[1]) continue;
      const f = cutTop(d, ((sU - uc) * rg[5] + rg[7] * rg[6]) / rg[3]); if (f <= 0) continue;
      const h = p.z0 + (p.z1 - p.z0) * f; if (h > fill[i]) fill[i] = h;
      if (p.z0 < lo[i]) lo[i] = p.z0;                    // низ стопки — нужен для ТОЛЩИНЫ начинки
    }
  }
  for (let i = 0; i < M; i++) { bed[i] = spreadAt(Math.min(1, i * PROF_DS / L), g); if (!isFinite(lo[i])) lo[i] = fill[i]; }
  return { M, bed, fill, lo };
}
// Ширина растекания: рис зернистый и уезжает на считанные зёрна, а не по всему листу.
// ⚑ inferred: замера нет. 1,4 ед. = 7 мм ≈ две ширины зерна (зерно 3,5 мм, Matsui 2001).
// Это условность отрисовки-модели, а не физическая величина: в таблицу толщин её класть нельзя.
// Ширина проверена замером 28.08, а не выбрана на глаз: прогон по 7 / 13 / 20 / 30 / 45 / 70 мм
// на трёх базах и трёх достижимых почерках сдвигает худшую некруглость всего с 63 % до 61 %.
// То есть ВЫСОТА ВАЛИКА на силуэт почти не влияет, и подбирать её под приёмку бессмысленно —
// оставлено физически осмысленное значение в две ширины зерна.
const SPREAD_W = 1.4;
// РИС, ВЫТЕСНЕННЫЙ НАЧИНКОЙ, РАСТЕКАЕТСЯ ВБОК (issue #1).
// Было: `h = bed + β·max(0, fill − bed)` — начинка лежит ВНУТРИ риса, занимая его место, и
// вытесненный рис исчезает. Замерено на хосомаки: 138 мм² риса из 644 пропадают при 145 мм²
// начинки, диаметр растёт на 0,2 мм вместо ≈1,5.
//
// ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ДОБАВИТЬ РАСТЕКАНИЕ К СТАРОЙ ФОРМУЛЕ. β и растекание описывают ОДНО И ТО ЖЕ:
// циновка давит бугор. β его просто теряет, растекание — переносит. Наложить одно на другое значит
// сжать дважды и потерять калибровку β (0,55 у суши-баз, 0,7 у рулета).
//
// Поэтому объём делится ровно надвое, без остатка:
//   содержимое столбика = bed + ft            (рис плюс толщина начинки, ft = fill − lo)
//   высота столбика     = bed + β·max(0, fill − bed)      ← в точности прежняя формула
//   разница             = ft − β·max(0, fill − bed)       ← ровно это и уезжает вбок
// Сумма высот после раздачи равна сумме содержимого ТОЧНО: Σ(bed + β·exc) + Σ(ft − β·exc) = Σ(bed + ft).
// Прежняя калибровка β не тронута: при пустом листе ft = 0, уезжать нечему, выражение сводится к bed·T.
//
// Рис не кладётся на голое нори: раздача идёт только в столбики, где грядка есть, и нормируется
// заново, чтобы сумма сошлась после отсечения.
function thicknessProfile(vSlice, g, list) {
  const fld = riceField(vSlice, g, list), M = fld.M, bed = fld.bed, H = fld.fill, lo = fld.lo;
  let a = new Float32Array(M), tmp = new Float32Array(M);
  const bt = betaEff(g);
  const move = new Float64Array(M);
  let total = 0;
  for (let i = 0; i < M; i++) {
    const exc = Math.max(0, H[i] - bed[i]), ft = Math.max(0, H[i] - lo[i]);
    const m = ft - bt * exc;
    if (m > 0) { move[i] = m; total += m; }
  }
  const add = new Float64Array(M);
  if (total > 1e-12) {
    const R = Math.max(1, Math.round(SPREAD_W / 2 / PROF_DS));
    let cur = move, buf = new Float64Array(M);
    for (let pass = 0; pass < 2; pass++) {            // два прохода box ≈ гаусс шириной SPREAD_W
      let acc = 0; for (let i = -R; i <= R; i++) acc += cur[Math.min(M - 1, Math.max(0, i))];
      for (let i = 0; i < M; i++) { buf[i] = acc / (2 * R + 1); acc += cur[Math.min(M - 1, i + R + 1)] - cur[Math.max(0, i - R)]; }
      const sw = cur; cur = buf; buf = sw;
    }
    // КАНАВКА (くぼみ): рис НЕ возвращается в углубление под куском.
    // Ито-Ёкадо: 「酢飯の中央より少しだけ手前に3本のくぼみをつくり」 — под каждую полосу начинки
    // повар ВЫДАВЛИВАЕТ углубление ЗАРАНЕЕ, и кусок садится В рис, а не НА рис. Этим и объясняется
    // то, что у настоящего маки над начинкой нет бугра (docs/reality-check.md, раздел 2).
    // Без этого запрета раздача симметрична, и столбик получает обратно почти весь свой же
    // вытесненный рис: замерено 28.08 — над куском 1,86 против 1,06 вдали, то есть бугор +76 %.
    // Поэтому принимающими считаются только столбики, где грядка есть И начинки нет; сумма
    // нормируется заново, так что объём по-прежнему сходится точно.
    let kept = 0;
    const free = i => bed[i] > 1e-9 && H[i] <= 1e-9;
    for (let i = 0; i < M; i++) if (free(i)) kept += cur[i];
    // Вырожденный случай: начинка покрыла ВЕСЬ лист, принимать некому. Тогда раздаём как раньше —
    // по всей грядке: лучше вернуть рис себе же, чем потерять его и снова сломать сохранение объёма.
    if (kept <= 1e-12) { for (let i = 0; i < M; i++) if (bed[i] > 1e-9) kept += cur[i]; }
    if (kept > 1e-12) { const k = total / kept, any = free;
      let sum2 = 0; for (let i = 0; i < M; i++) if (free(i)) sum2 += cur[i];
      const useFree = sum2 > 1e-12;
      for (let i = 0; i < M; i++) add[i] = (useFree ? free(i) : bed[i] > 1e-9) ? cur[i] * k : 0; }
  }
  for (let i = 0; i < M; i++) { const r = bed[i]; a[i] = (r + bt * Math.max(0, H[i] - r) + add[i]) * g.T; }
  const R = Math.max(1, Math.round(SMOOTH_R / PROF_DS));
  for (let pass = 0; pass < 2; pass++) {              // два прохода box-blur ≈ гаусс
    let acc = 0; for (let i = -R; i <= R; i++) acc += a[Math.min(M - 1, Math.max(0, i))];
    for (let i = 0; i < M; i++) { tmp[i] = acc / (2 * R + 1); acc += a[Math.min(M - 1, i + R + 1)] - a[Math.max(0, i - R)]; }
    const sw = a; a = tmp; tmp = sw;
  }
  return a;
}
// ДВА РЕЖИМА. Полный заводит массивы витков (rin/rout/u0/u1 — по KMAX·NB = 12 960 чисел, 200 КБ на один
// ломтик) и нужен только тому ломтику, который действительно рисуют. Лёгкий (routOnly) ведёт ТУ ЖЕ намотку
// по тем же формулам и с тем же Float32-накоплением в top[], но массивов не заводит: ему нужен только
// внешний радиус, а тот считается исключительно по top[] — и в цикле, и после прижима циновкой (внутренний
// цикл прижима трогает лишь rin/rout и на Rout не влияет). Из-за этого модели больше не нужно мотать все
// шестнадцать ломтиков ради Rmax: полную намотку строит windFor по требованию.
function wind(vSlice, sMax, g, list, routOnly) {
  const n = KMAX * NB;
  const rin = routOnly ? null : new Float32Array(n).fill(-1), rout = routOnly ? null : new Float32Array(n),
        u0 = routOnly ? null : new Float32Array(n), u1 = routOnly ? null : new Float32Array(n);
  const top = new Float32Array(NB).fill(g.r0), prof = thicknessProfile(vSlice, g, list);
  // Спиральные базы (без подворота): начало листа прижато и сходит на нет — сердцевина растёт на толщину слоя
  // за первый оборот; все витки наследуют этот подъём, и выходит настоящая спираль без шва на угле 0.
  if (!g.tuck && !(g.sStart > 0)) { const t0 = prof[0] + g.w; for (let b = 0; b < NB; b++) top[b] = g.r0 + t0 * (b / NB); }
  let s = g.sStart || 0, k = 0, b = 0, phiEnd = -1, lastIdx = -1, Rout = g.r0, bins = 0, sClose = -1, sEnd = g.L;
  if (sMax < s) Rout = g.r0 * Math.sqrt(Math.max(0.05, sMax / s));   // ядро ещё сминается
  // `one` — это «ролл замыкается ровно за ОДИН оборот, лишний лист обрезан». Оно ехало на том же
  // флаге, что и подворот, и в этом была вся путаница. Замыкание за оборот ОПРОВЕРГНУТО 26.08:
  // симуляция даёт 1,85–1,91 оборота у футомаки (sim/reference2, раскладка 7), и в срезе видно
  // два слоя нори — их и обводит strokeWrapperTurns. Поэтому флаг сняли с баз, но вместе с ним
  // случайно отключился и подворот: computeCore смотрел на тот же `oneTurn`. Теперь подворот на
  // своём флаге `tuck`, а обрезка за оборот выключена НАМЕРЕННО и здесь и остаётся.
  const one = false, flap = g.flap || 0;
  while (s < Math.min(sMax, sEnd) && k < KMAX) {
    const idx = k * NB + b, u = s / g.L;
    if (one && k >= 1 && sClose < 0) { sClose = s; sEnd = Math.min(g.L, s + flap); }   // ролл замкнулся: лишний лист обрезан, нори сомкнулась стык в стык
    let t;
    if (sClose >= 0) t = g.w * clamp((sEnd - s) / 2.5, 0.15, 1);                       // клапан нори, прижатый к концу
    else {
      const pv = prof[Math.min(prof.length - 1, Math.round(s / PROF_DS))];
      // ВОЗДУХ ЖИВЁТ В НАМАЗКЕ, А НЕ ПОД ГОЛЫМ НОРИ. `air` прибавлялся к КАЖДОМУ шагу намотки, в том
      // числе за spreadEnd — на голой полосе у дальнего края, где на листе только нори 0,1 мм. При
      // почерке `air` 0,20 (верх достижимого диапазона, docs/noise-floor.md) это давало хвостовому
      // витку 2,0 мм вместо 0,1, и materialAt красил всё, кроме внешних `w`, РИСОМ: снаружи ролла
      // появлялся полумесяц риса шириной 2 мм, отчёркнутый собственной линией нори. Это и есть
      // «раздвоение контура на трёх часах», которое увидела владелец: на луче 20° нори пересекалась
      // ДВАЖДЫ, а на 359° — один раз. Замерено 27.08 на футомаки, 6 начинок, срез v = 0,33.
      // Код и сам это уже утверждал: у прижатого клапана (ветка sClose выше) толщина — ровно `g.w`,
      // без воздуха. Здесь то же правило, только полоса опознаётся не флагом, а тем, что на ней
      // ничего не намазано. Гейт берётся от prof, а не от spreadAt: prof уже сглажен, и воздух
      // сходит на нет тем же клином, что и грядка, — новой ступеньки на spreadEnd не появляется.
      // ⚑ inferred: замера толщины воздушной прослойки под голым нори нет; величина 0 выбрана как
      // единственная, согласованная с уже записанным в коде поведением клапана.
      t = pv + (g.air || 0) * clamp(pv / g.T, 0, 1);
      // Шов: у выхода из ядра (или в самом центре спирали) намазки ещё нет — она входит клином,
      // поэтому обёртка продолжается прямо с поверхности ядра и спираль читается как одна линия.
      t += g.w;
      if (g.wobble) t *= 1 + g.wobble * Math.sin(TAU * (s / g.L) * 2.5 + (g.phase || 0));   // рывки при тяге
      if (!one) { const tail = g.L - s; if (tail < 5) t *= clamp(tail / 5, 0.03, 1) * clamp(tail / 5, 0.03, 1) * (3 - 2 * clamp(tail / 5, 0.03, 1)); }   // спираль: конец листа прижат и сходит на нет (плавно, ≈2,5 см)
    }
    const ri = top[b], rm = ri + t / 2, ds = rm * DPHI;
    if (!routOnly) { rin[idx] = ri; rout[idx] = ri + t; u0[idx] = u; }
    top[b] = ri + t; if (ri + t > Rout) Rout = ri + t; bins++;
    const sStop = Math.min(sMax, sEnd);
    if (s + ds >= sStop) { if (!routOnly) u1[idx] = sStop / g.L; phiEnd = b * DPHI + (sStop - s) / rm; lastIdx = idx; s = sStop; break; }
    s += ds; if (!routOnly) u1[idx] = s / g.L;
    if (++b === NB) { b = 0; k++; }
  }
  // Прижим циновкой: ролл подгоняется к круглому сечению — слои сжимаются пропорционально,
  // поэтому клин у шва и бугры от начинок не оставляют ступенек на контуре.
  // ОБЖИМ ЦИНОВКОЙ. После намотки ролл сдавливают в циновке, и спираль садится в круг.
  //
  // ⚠ ЗДЕСЬ СТОЯЛО «настоящий маки круглый». Это НЕВЕРНО, и разбор источников 31.08 показал,
  // насколько: для двух самых каноничных хосомаки японские источники называют только две формы,
  // и круга среди них НЕТ. Тэкка-маки — 「四角形かトンネル形（馬蹄形）に成形する」; канпё-маки —
  // квадрат либо かまぼこ型 (плоское дно, купол сверху). Обобщающая статья 巻き寿司 говорит
  // 「断面が方形あるいは円形のものが多い」 — квадрат назван ПЕРВЫМ.
  //
  // И форма зависит не от региона, а от НАЧИНКИ: 江戸前寿司 — 「カンピョウなら丸に、鉄火なら
  // 四角く絞めてきめる」. Твёрдая сердцевина → квадрат, мягкая → купол.
  //
  // Что из этого следует для модели, но ещё НЕ СДЕЛАНО (#19): форма должна задаваться не
  // сжатием к цели, а НАБОРОМ ЗАЖАТЫХ ГРАНЕЙ — так её и описывает повар: три пальца на трёх
  // гранях, а купол получается тем, что верх не зажимают (銀座渡利: 「上をしめずに、親指と
  // 中指だけで横をしめます」). Четыре грани, каждая прижата или свободна: все четыре → квадрат,
  // две боковые → камабоко, ни одной → круг. Одна формула, три формы, ноль магических чисел.
  //
  // Пока этого нет, 0,90 остаётся ИГРОВОЙ УСЛОВНОСТЬЮ по требованию владельца «должен просто
  // круг получаться», а не утверждением о еде. Здесь было 0,55 — 45 % кривизны оставалось,
  // ролл выходил улиткой.
  // Теперь при спокойном прижиме остаётся около 10 %,
  // при крепком — почти ничего. Рука по-прежнему решает: слабая оставляет ролл бугристым.
  const round = clamp(0.90 * (g.press === undefined ? (S.hand ? S.hand.press : 1) : g.press), 0, 0.97);
  let sum = 0, cnt = 0;
  for (let b2 = 0; b2 < NB; b2++) if (top[b2] > g.r0) { sum += top[b2]; cnt++; }
  if (cnt) {
    const Rm = sum / cnt;
    // Обжим меняет ФОРМУ, а не количество риса. Радиусы тянутся к среднему, но площадь кольца
    // (∝ r² − r0²) от этого падает, поэтому вторым проходом возвращаем её на место.
    let a0 = 0, a1 = 0;
    for (let b2 = 0; b2 < NB; b2++) {
      if (top[b2] <= g.r0 + 1e-6) continue;
      const tgt = Rm + (1 - round) * (top[b2] - Rm);
      a0 += top[b2] * top[b2] - g.r0 * g.r0; a1 += tgt * tgt - g.r0 * g.r0;
    }
    const area = a1 > 1e-9 ? Math.sqrt(a0 / a1) : 1;
    Rout = g.r0;
    for (let b2 = 0; b2 < NB; b2++) {
      if (top[b2] <= g.r0 + 1e-6) continue;
      const tgt = g.r0 + (Rm + (1 - round) * (top[b2] - Rm) - g.r0) * area;
      const f = (tgt - g.r0) / (top[b2] - g.r0);   // сжимаем слои, ядро не трогаем
      if (!routOnly) for (let k2 = 0; k2 < KMAX; k2++) { const i2 = k2 * NB + b2; if (rin[i2] < 0) break; rin[i2] = g.r0 + (rin[i2] - g.r0) * f; rout[i2] = g.r0 + (rout[i2] - g.r0) * f; }
      top[b2] = tgt; if (tgt > Rout) Rout = tgt;
    }
  }
  // РИС ТЕЧЁТ, А НЕ ЛОЖИТСЯ ПЛИТОЙ. На шве спираль кладёт поверх намазки ЦЕЛЫЙ ЛИШНИЙ СЛОЙ, и контур
  // получает обрыв. Замерено 27.08 на футомаки при лёгком прижиме: 3,0 мм между СОСЕДНИМИ градусами,
  // дальше спад на 33° — это и есть «треугольник» на конце скрутки, который увидела владелец: «не
  // должно быть артефактов как в конце скрутки, так в жизни невозможно».
  // В жизни так и есть: две рисовые поверхности, встретившись, слипаются в ОДНУ массу, повар доглаживает
  // циновкой, и шов уходит в доли миллиметра. Наружу торчит только кромка нори (0,1 мм).
  // Обжим выше — про ФОРМУ ЦЕЛОГО: он тянет радиусы к среднему и разницу СОСЕДЕЙ уменьшает всего в
  // (1 − round) раз, поэтому от 12-миллиметрового слоя при лёгкой руке оставалось 3 мм. Здесь другое —
  // ЛОКАЛЬНОЕ РАСТЕКАНИЕ: высокая частота (обрыв на шве) уходит, низкая (овал от руки) остаётся, и
  // почерк по-прежнему виден. Площадь кольца возвращается тем же приёмом, что и в обжиме: риса ровно
  // столько же, он только перераспределён по окружности.
  // Не запускается, если ролл НЕ ЗАМКНУЛСЯ (есть бины, куда лист не дошёл): там сглаживать нечего —
  // размазывать поверхность в пустоту значило бы придумать рис, которого нет.
  let closed = true;
  for (let b2 = 0; b2 < NB; b2++) if (top[b2] <= g.r0 + 1e-6) { closed = false; break; }
  if (closed) {
    const RAD = 60;                                   // ±15°: шире шва, уже овала от руки
    let cur = Float32Array.from(top), tmp = new Float32Array(NB);
    for (let pass = 0; pass < 2; pass++) {
      let acc = 0;
      for (let o = -RAD; o <= RAD; o++) acc += cur[(o % NB + NB) % NB];
      for (let b2 = 0; b2 < NB; b2++) { tmp[b2] = acc / (2 * RAD + 1); acc += cur[(b2 + RAD + 1) % NB] - cur[((b2 - RAD) % NB + NB) % NB]; }
      const sw = cur; cur = tmp; tmp = sw;
    }
    let s0 = 0, s1 = 0;
    for (let b2 = 0; b2 < NB; b2++) { s0 += top[b2] * top[b2] - g.r0 * g.r0; s1 += cur[b2] * cur[b2] - g.r0 * g.r0; }
    const ar = s1 > 1e-9 ? Math.sqrt(s0 / s1) : 1;
    Rout = g.r0;
    for (let b2 = 0; b2 < NB; b2++) {
      const tgt = g.r0 + (cur[b2] - g.r0) * ar, f = (tgt - g.r0) / (top[b2] - g.r0);
      if (!routOnly) for (let k2 = 0; k2 < KMAX; k2++) { const i2 = k2 * NB + b2; if (rin[i2] < 0) break; rin[i2] = g.r0 + (rin[i2] - g.r0) * f; rout[i2] = g.r0 + (rout[i2] - g.r0) * f; }
      top[b2] = tgt; if (tgt > Rout) Rout = tgt;
    }
  }
  if (routOnly) return Rout;
  return { rin, rout, u0, u1, top, Rout, lastIdx, phiEnd, kmax: Math.min(KMAX, k + 1), turns: bins / NB, sClose, sEnd };
}
// Внешний радиус намотки без массивов витков — для Rmax модели и для превью скрутки.
const windRout = (vSlice, sMax, g, list) => wind(vSlice, sMax, g, list, true);
// Пиксель среза (r, φ) → на каком витке и где на листе. null — вне листа.
function sampleWind(wd, r, phi) {
  const fb = phi / DPHI; let b = Math.floor(fb); if (b >= NB) b = NB - 1; const frac = fb - b;
  for (let k = 0; k < wd.kmax; k++) {
    const idx = k * NB + b, ri = wd.rin[idx]; if (ri < 0) break;
    const ro = wd.rout[idx]; let ri2 = ri, ro2 = ro, f = frac;
    if (idx === wd.lastIdx) { const fe = (wd.phiEnd - b * DPHI) / DPHI; if (frac > fe) continue; f = fe > 1e-6 ? frac / fe : 0; }
    // Сосед для интерполяции берётся по ПОРЯДКУ НАМОТКИ. Внутри витка это верно. Два случая, где нет:
    //   1) на последнем бине витка сосед — бин 0 СЛЕДУЮЩЕГО витка, то есть поверхность на оборот дальше
    //      по листу. Там innerAt (он на шве не интерполирует) и sampleWind расходились, и у угла 0
    //      между сердцевиной и намазкой открывалась дыра шириной с воздух в намотке — «out», то есть
    //      цвет обёртки посреди риса. Через шов не интерполируем вовсе: четверть градуса роли не играет.
    //   2) сосед отскочил больше чем на полтолщины СВОЕГО слоя — признак, что лист в этом бине кончился
    //      (хвост сведён на нет), а не что виток продолжается; тянуть исчезающе тонкую ленту в него нельзя.
    else { const nidx = b + 1 < NB ? idx + 1 : -1; if (nidx > 0 && wd.rin[nidx] >= 0 && Math.abs(wd.rin[nidx] - ri) <= 0.5 * (ro - ri)) { ri2 = wd.rin[nidx]; ro2 = wd.rout[nidx]; } }
    const rIn = ri + (ri2 - ri) * f, rOut = ro + (ro2 - ro) * f;
    if (r >= rIn && r < rOut) return { u: wd.u0[idx] + (wd.u1[idx] - wd.u0[idx]) * f, zr: r - rIn, t: rOut - rIn, rOut };
  }
  return null;
}
function innerAt(wd, phi) { const fb = phi / DPHI; let b = Math.floor(fb); if (b >= NB) b = NB - 1; const f = fb - b, b2 = Math.min(NB - 1, b + 1); const a = wd.rin[b] >= 0 ? wd.rin[b] : -1, c = wd.rin[b2] >= 0 ? wd.rin[b2] : a; return a < 0 ? -1 : a + (c - a) * f; }
function topAt(wd, phi) { const fb = phi / DPHI; let b = Math.floor(fb); if (b >= NB) b = NB - 1; const f = fb - b, b2 = (b + 1) % NB; return wd.top[b] + (wd.top[b2] - wd.top[b]) * f; }
// Модель = список патчей + намотки на стандартных срезах; общий масштаб — по максимальному радиусу.
const SLICES = [0.5]; for (let i = 0; i < 6; i++) SLICES.push(i / 6 + 0.002); for (let i = 0; i < 3; i++) SLICES.push((i + 0.5) / 3); for (let i = 0; i < 6; i++) SLICES.push((i + 0.5) / 6);
const modelCaches = new Map();
// Подворот: начинки, лежащие вплотную у ближнего края, сминаются в ядро. «Постель» зоны сгиба складывается
// пополам: дальняя половина — нижний слой, ближняя ложится сверху перевёрнутой (её нори — внутренний крючок).
// Площадь ядра = рис + начинки; ядро — диск той же площади; остаток листа наматывается вокруг него.
function computeCore(list, g) {
  if (!g.tuck) return null;   // рулет — спираль без подворота
  // кластер у края — по центру и ширине начинки (повёрнутый габарит не считается: диагональная полоска не «затягивает» полстола в ядро)
  const L = g.L, T = g.T, items = list.filter(p => !ING[p.kind].paint).map(p => { const w = dims(p, g).du * L; return { p, s0: p.u * L - w / 2, s1: p.u * L + w / 2 }; }).sort((a, b) => a.s0 - b.s0);
  let end = 0;
  if (items.length && items[0].s0 <= 5) { end = items[0].s1; for (let i = 1; i < items.length; i++) { if (items[i].s0 - end > 2.5) break; end = Math.max(end, items[i].s1); } }
  // ПОДВОРОТ НЕ МОЖЕТ СЪЕСТЬ ЛИСТ. Цепочка выше тянется, пока соседние начинки ближе 2,5 ед.
  // (12,5 мм) друг к другу, — и на плотной раскладке она доходила до потолка 0,45·L. Замерено
  // на раскладке владельца: 5 начинок из 6 уезжали в ядро, подворот съедал 95 мм из 210, и ролл
  // делал 0,74 оборота — то есть НЕ ЗАМЫКАЛСЯ вовсе, нори не встречала саму себя.
  // Физическое условие простое: того, что осталось от листа, должно хватить хотя бы на один
  // оборот вокруг получившегося ядра. Радиус ядра сам зависит от подворота, поэтому решаем
  // сжатием: пробуем, не сходится — укорачиваем, пока не уложимся или не упрёмся в tuckMin.
  const hcAt = (sf) => {                       // высота ядра при таком подвороте
    let ha = T, hb = T;
    for (const p of list) { if (ING[p.kind].paint || p.u * L >= sf) continue;
      if (p.u * L >= sf / 2) hb = Math.max(hb, p.z1 * T); else ha = Math.max(ha, p.z1 * T); }
    return ha + hb + 2 * g.w;
  };
  const rAt = (sf) => Math.sqrt((sf / 2) * hcAt(sf) / Math.PI);
  // Сколько листа нужно на n оборотов вокруг ядра радиуса R с шагом P: длина архимедовой
  // спирали, TAU·(R·n + P·n²/2). Одного оборота МАЛО — нужен нахлёст, иначе нори не садится
  // сама на себя. Повара дают 1,0–1,35 (docs/reality-check.md); берём 1,15 как низ этого окна.
  // 1,15 — НИЖНЯЯ ТРЕТЬ окна, которое дают повара (1,0–1,35), а не его низ: низ — это 1,0.
  const MIN_TURNS = 1.15, P = T + g.w;
  const needFor = (sf) => TAU * (rAt(sf) * MIN_TURNS + P * MIN_TURNS * MIN_TURNS / 2);
  let sFold = Math.min(0.45 * L, Math.max(g.tuckMin || 0, end + 1.0));
  const floor = Math.max(g.tuckMin || 0, 2);
  for (let i = 0; i < 12 && sFold > floor; i++) {
    if (L - sFold >= needFor(sFold)) break;     // остатка хватает на оборот с нахлёстом
    sFold = Math.max(floor, sFold * 0.88);
  }
  const half = sFold / 2;
  const core = { sFold, Wc: half, items: [], HA: T, HB: T };
  // ТВЁРДЫЕ куски уезжают в ядро ЦЕЛИКОМ по центру: брусок не разрезать подворотом пополам.
  const inside = list.filter(p => !ING[p.kind].paint && p.u * L < sFold);
  for (const p of inside) { const far = p.u * L >= half; if (far) core.HB = Math.max(core.HB, p.z1 * T); else core.HA = Math.max(core.HA, p.z1 * T); }
  const W = g.w;
  for (const p of inside) {
    p.inCore = true; const d = ING[p.kind], far = p.u * L >= half;
    let y0, y1;
    if (far) { y0 = W + p.z0 * T; y1 = W + p.z1 * T; }
    else { y0 = W + core.HB + core.HA - p.z1 * T; y1 = W + core.HB + core.HA - p.z0 * T; }
    core.items.push({ p, d, y0, y1, far, paint: false });
  }
  // КРАСКА — НЕ ТЕЛО, А ЦВЕТ РИСА, и подворот её РЕЖЕТ, а не утаскивает целиком (issue #95).
  // Прежнее правило «по центру» давало ядро без краски вовсе: полоса у края центром лежала за
  // линией подворота, в inside не попадала — и при ПОЛНОСТЬЮ закрашенном листе ядро выходило
  // белым все 360° (замер: 4320/4320 точек «core»). Владелец это увидела на телефоне.
  // Теперь краска входит в ядро ПЕРЕСЕЧЕНИЕМ с [0, sFold]: ближняя половина сгиба красит верх
  // (постель перевёрнута), дальняя — низ; точную обрезку по sU делает система координат
  // coreMaterial сама (x ∈ [0, half] покрывает ровно [0, sFold]). inCore краске НЕ ставится:
  // её часть за сгибом остаётся в намотке (та всё равно начинается с sStart = sFold).
  for (const p of list) {
    const d = ING[p.kind]; if (!d.paint) continue;
    const w2 = dims(p, g).du * L / 2, s0 = p.u * L - w2, s1 = p.u * L + w2;
    if (s1 <= 0 || s0 >= sFold) continue;
    if (s0 < half) core.items.push({ p, d, y0: W + core.HB, y1: W + core.HB + core.HA, far: false, paint: true });
    if (s1 > half) core.items.push({ p, d, y0: W, y1: W + core.HB, far: true, paint: true });
  }
  // Нори — один непрерывный лист. Внутри ядра он идёт тремя участками: по верху постели (подвёрнутый
  // ближний край — «крючок»), вокруг сгиба и обратно по низу постели, откуда уходит в намотку.
  // Кольцо разомкнуто справа (φ = 0) — там лист выходит наружу и продолжается спиралью.
  // Нори внутрь не заходит: лист смыкается стык в стык снаружи. Внутри ядра — только рис и начинки
  // (нори внутри появляется, лишь если игрок сам её положил — обёрткой вокруг начинки или слоем).
  core.Hc = core.HA + core.HB + 2 * g.w;
  // почерк: сильный прижим уплотняет ядро, быстрая тяга оставляет в нём воздух (из паспорта модели, не из текущего S.hand)
  const press = g.press === undefined ? (S.hand ? S.hand.press : 1) : g.press, airRaw = g.air / g.T;
  core.R = Math.sqrt(core.Wc * core.Hc / Math.PI) * clamp(1 - 0.22 * (press - 1) + 0.35 * airRaw, 0.9, 1.12);
  return core;
}
// Диск → квадрат (обратное эллиптическое отображение Фонга): формы ядра почти не искажаются.
function diskToSquare(x, y) {
  const a = 2 + x * x - y * y, b = 2 * Math.SQRT2 * x, c = 2 - x * x + y * y, d = 2 * Math.SQRT2 * y;
  const u = 0.5 * Math.sqrt(Math.max(0, a + b)) - 0.5 * Math.sqrt(Math.max(0, a - b));
  const v = 0.5 * Math.sqrt(Math.max(0, c + d)) - 0.5 * Math.sqrt(Math.max(0, c - d));
  return [u, v];
}
function coreMaterial(m, r, phi, vSlice) {
  const c = m.core, xd = r * Math.cos(phi) / c.R, yd = r * Math.sin(phi) / c.R;
  const [us, vs] = diskToSquare(xd, yd);
  const x = (us + 1) / 2 * c.Wc, y = (vs + 1) / 2 * c.Hc;
  const L = m.g.L, half = c.Wc;
  for (let pass = 0; pass < 2; pass++) for (let i = c.items.length - 1; i >= 0; i--) {
    const it = c.items[i]; if (it.paint !== (pass === 1)) continue;
    if (y < it.y0 || y > it.y1) continue;
    const rg = patchSRange(it.p, vSlice, m.g); if (!rg) continue;
    const x0 = it.far ? rg[0] - half : half - rg[1], x1 = it.far ? rg[1] - half : half - rg[0];
    if (x < x0 || x > x1) continue;
    const sU = it.far ? half + x : half - x, du_ = sU - rg[2] * L, across = du_ * rg[5] + rg[7] * rg[6], along = -du_ * rg[6] + rg[7] * rg[5];
    let lu = across / rg[3], lz = (y - it.y0) / (it.y1 - it.y0);
    if (!it.far) { lz = 1 - lz; }
    if (!it.paint) { const sp = cutSpan(it.d, lu); if (lz < sp[0] || lz > sp[1]) continue; }
    return { cls: 'patch', mt: { p: it.p, d: it.d, lu, lz, lv: along / rg[4] } };
  }
  // ПУСТОТА БЛИЖНЕГО КЛАПАНА (issue #95). У подвёрнутой половины постели рис есть не везде:
  // голая полоса у кромки (до SPREAD_START) складывается внутрь как нори-«крючок» без риса.
  // Прямоугольная модель ядра отдавала этот объём белому «рису», которого там нет, — при
  // полностью закрашенном листе внизу-справа ядра оставался белый сектор. Физически прижим
  // схлопывает пустоту, и объём занимает НИЖНИЙ слой — дальняя половина сгиба; краску берём у
  // неё на той же поперечной координате. Твёрдые куски так не продлеваем: у них своя высота.
  const sUnear = half - x;
  if (sUnear >= 0 && spreadAt(sUnear / L, m.g) <= 1e-6) {
    for (let i = c.items.length - 1; i >= 0; i--) {
      const it = c.items[i]; if (!it.paint || !it.far) continue;
      const rg = patchSRange(it.p, vSlice, m.g); if (!rg) continue;
      if (x < rg[0] - half || x > rg[1] - half) continue;
      const sU = half + x, du_ = sU - rg[2] * L, across = du_ * rg[5] + rg[7] * rg[6], along = -du_ * rg[6] + rg[7] * rg[5];
      return { cls: 'patch', mt: { p: it.p, d: it.d, lu: across / rg[3], lz: 0.5, lv: along / rg[4] } };
    }
  }
  return { cls: 'core' };
}
// Ключ кэша модели. Строится КАНОНИЧЕСКИ и только из настоящих входов патча —
// kind, u, v, rot, wU, hU, dv, phase. Служебные поля (z0/z1 от restack, inCore от computeCore)
// в ключ не входят: раньше здесь стоял JSON.stringify(list), и одна и та же на вид раскладка
// давала РАЗНЫЕ ключи до и после restack — модель пересчитывалась заново и занимала второе место в кэше.
const numKey = x => (+x || 0).toFixed(5);
const patchKey = p => p.kind + ',' + numKey(p.u) + ',' + numKey(p.v) + ',' + numKey(p.rot) + ','
  + (p.wU == null ? '' : numKey(p.wU)) + ',' + (p.hU == null ? '' : numKey(p.hU)) + ','
  + (p.dv == null ? '' : numKey(p.dv)) + ',' + numKey(p.phase);
const listKey = list => list.map(patchKey).join(';');
// ОБЛЕГЧЁННЫЙ ПУТЬ ДЛЯ ПОИСКА (inverse design).
// Замерено 26.08 (docs/inverse-design.md, «Замер: где на самом деле узкое место поиска»):
// одна итерация поиска стоит 8 мс, из них buildModel — 7,49 мс, то есть 88 %. Растр карты
// класcов — 12 %, и грубый растр 32×32 против 64×64 экономит всего 7 %: запланированную
// оптимизацию «грубый растр для поиска» надо ВЫБРОСИТЬ, она ничего не даёт.
// Внутри buildModel математики почти нет — есть объём работы: Rmax считается по ВСЕМ
// шестнадцати ломтикам из SLICES, а поиску нужен ОДИН. Отсюда ~3× в чистом JS.
// ⚠ ЗДЕСЬ СТОЯЛО «~17×» — оценка ДО замера. Замерено 28.08 той же методикой: 2,33 → 0,77 мс,
// то есть ×3,0 (docs/inverse-design.md). Док поправили, код забыли — ровно тот разрыв, из-за
// которого числа и разъезжаются. И вывод «WASM не нужен» на ×3 держится уже не на этом
// сравнении (2–10× для такого кода перекрывает ×3), а на том, что 13 000 итераций влезают
// в бюджет и без него.
// `only` — номер ломтика; undefined означает прежнее поведение по всем SLICES.
// ⚑ Ключ кеша ОБЯЗАН это видеть: сегодня 28.08 я уже поймал себя на кеше, слепом к новому
// параметру (подбор SPREAD_W дал шесть одинаковых чисел подряд). Грабли известные — п. 2 навыка.
function buildModel(list, only) {
  const hd = S.hand || { air: 0, wobble: 0, phase: 0, press: 1 };
  // Обёртка входит в ключ: она меняет шаг витка (T + w), а с ним число оборотов и ⌀.
  // Без неё блин 2 мм давал ровно то же, что нори 0,1 мм — модель бралась из кэша.
  const key = S.base + '|' + (B().wrapKey || '-') + '|' + S.shape + '|' + (S.turns || '') + '|' + hd.air.toFixed(3) + ',' + hd.wobble.toFixed(3) + ',' + hd.phase.toFixed(2) + ',' + hd.press.toFixed(2) + '|s:' + (only === undefined ? 'all' : only.toFixed(4)) + '|' + listKey(list);
  let m = modelCaches.get(key); if (m) return m;
  if (modelCaches.size > 16) modelCaches.clear();
  // Клон ДО restack: стопку считаем на собственной копии, чужой список не трогаем.
  const own = JSON.parse(JSON.stringify(list));
  // g — ПАСПОРТ модели: всё, что геометрия раньше подсматривала в S и B(), теперь снято здесь один раз.
  const b = B(), g = { T: b.T, w: b.w, r0: R0, L: sheetLen(b), Wv: b.Wv, sStart: 0, air: hd.air * b.T, wobble: hd.wobble, phase: hd.phase,
    press: hd.press, beta: b.beta, kappa: b.kappa, spreadEnd: b.spreadEnd, tuck: !!b.tuck, flap: b.flap || 0, tuckMin: b.tuckMin || 0 };
  restack(own, g);
  m = { key, g, shape: S.shape, list: own, wds: new Map(), Rmax: 0, core: null };
  m.core = computeCore(m.list, g);
  if (m.core) { g.r0 = m.core.R; g.sStart = m.core.sFold; }
  // Rmax — по всем стандартным ломтикам (общий масштаб ролла), но ЛЁГКИМ проходом: сами витки
  // строит windFor тому ломтику, который спросят. Модель перестала весить 3 МБ намоток, а поиску,
  // которому нужен один срез из шестнадцати, не приходится мотать остальные пятнадцать.
  const scan = only === undefined ? SLICES : [only];
  for (const v of scan) m.Rmax = Math.max(m.Rmax, windRout(v, g.L, g, m.list));
  modelCaches.set(key, m); return m;
}
function getModel() { return buildModel(patches()); }
// Модель для ОДНОГО среза: тот же расчёт, но Rmax берётся только по нему.
// Для поиска этого достаточно — сравниваются карты классов на одном и том же ломтике,
// и общий масштаб ролла им нужен один, а не самый толстый из шестнадцати.
// НЕ для отрисовки: там Rmax обязан быть общим, иначе ломтики поедут по масштабу.
function modelForSlice(list, v) { return buildModel(list, v); }
function windFor(m, v) { const key = v.toFixed(4); let wd = m.wds.get(key); if (!wd) { wd = wind(v, m.g.L, m.g, m.list); m.wds.set(key, wd); } return wd; }
// Материал в точке среза (r, φ): 'out' | 'core' | 'wrap' | 'spread' | { патч }.
function materialAt(m, wd, vSlice, r, phi) {
  const g = m.g;
  const rin0 = innerAt(wd, phi), coreR = rin0 >= 0 ? rin0 : g.r0;
  // Внутри сердцевины материал берётся ТОЛЬКО у подворота (m.core). У спиральных баз ядра нет —
  // там полая трубка, и спрашивать лист при u = 0,002 нельзя: начинка у ближнего края проявлялась
  // внутри дырки, где листа физически нет.
  if (r < coreR) return m.core ? coreMaterial(m, r, phi, vSlice) : { cls: 'core' };
  const sm = sampleWind(wd, r, phi);
  if (!sm) return { cls: 'out' };
  let zn = (sm.t - g.w - sm.zr) / g.T;
  if (zn < 0) return { cls: 'wrap', sm };
  const H = stackTopAt(sm.u, vSlice, m.list, g), bandN = (sm.t - g.w - (m.g.air || 0)) / g.T; if (bandN > 1e-6) zn *= Math.max(1, H) / bandN;   // сжатый слой → собственные z стопки
  const mt = matAt(sm.u, vSlice, zn, m.list, g);
  return mt ? { cls: 'patch', mt, sm } : { cls: 'spread', sm };
}

// ---------------------------------------------------------------- цвета материалов на срезе
// Крупа рисуется в РАЗМЕРЕ ЗЕРНА, а не в пикселях экрана. Раньше здесь стояло hash(px>>1, py>>1) —
// шум по двухпиксельным клеткам, то есть зерно зависело от зума и выходило ~0,25 мм вместо 2,5 мм,
// в десять раз мельче настоящего. ⚠ Прежние 2,5 мм были ТОЛЩИНОЙ зерна, а не поперечником:
// поперечник по Мацуи 2001 — 3,5 мм, отсюда GRAIN = 0,7. В этой строке 2,5 мм называлось
// «верным размером» — прямо над константой, которая его опровергает.
// (им скругляются углы квадратного ролла, см. shapeInfo). Аргументы gx, gy — координаты В ЗЁРНАХ.
// Рельеф зерна, направление света и щель между зёрнами — УСЛОВНОСТИ ОТРИСОВКИ, помечены `inferred`:
// источника у них нет, замером они не являются и в таблицу физических толщин переезжать не имеют права
// (docs/geometry-audit.md, раздел «Условности отрисовки»).
const GRAIN = 0.7;
const GRAIN_ASPECT = 2.2;
const LIGHT_X = -0.70, LIGHT_Y = -0.71;   // one light for the whole slice; chosen to agree with `vig` in renderSection (key from the top-left)
const GRAIN_C = new Float32Array(3);   // [0],[1] — смещение к центру зерна; [2] — q (1 на кромке)      // смещение от точки к центру НАЙДЕННОГО зерна, в единицах зерна
// У КАЖДОГО ЗЕРНА СВОЙ УГОЛ. Без этого на плоском листе все рисинки лежат вдоль оси x —
// владелец: «кажется, что все рисинки лежат по горизонтали». Так и было: решётка задавала не
// только центры, но и направление. Замер по фотографиям (Kanpyō-maki 001, Makizushi2): вдоль
// касательной ≤30° лежат 50–56 % зёрен, радиально ≥60° — 18–20 %; случайная укладка дала бы 33/33.
// Значит уклон к намотке есть, но слабый. Здесь: 35 % зёрен идут вдоль (±25°), остальные как попало.
// Таблица — чтобы не звать синус и косинус по девять раз на пиксель.
const WRAP_BULGE = 0.12;   // 0,6 мм — насколько лист выгибается над выступающим зерном (inferred)
const RICE_FLAT = 0.55;
const GDIR_N = 512, GDIR = new Float32Array(GDIR_N * 3);
let GRAIN_SEC_MEAN = 1.0;
(function () {
  let sd = 12345; const rr = () => (sd = (sd * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
  let acc = 0;
  for (let i = 0; i < GDIR_N; i++) {
    const z = 2 * rr() - 1, th = rr() * TAU, rxy = Math.sqrt(Math.max(0, 1 - z * z));
    let nA = rxy * Math.cos(th), nT = rxy * Math.sin(th), nR = z * RICE_FLAT;
    const n = Math.hypot(nA, nT, nR) || 1; nA /= n; nT /= n; nR /= n;
    const c2 = nA * nA;
    const asp = GRAIN_ASPECT / Math.sqrt(GRAIN_ASPECT * GRAIN_ASPECT * c2 + (1 - c2));
    const m = Math.hypot(nT, nR) || 1;
    GDIR[3 * i] = nT / m; GDIR[3 * i + 1] = nR / m; GDIR[3 * i + 2] = asp; acc += asp;
  }
  GRAIN_SEC_MEAN = acc / GDIR_N;
})();
const RICE = {
  toneVar: 15, shade: 17, domeA: 18, level: 8.4,
  specLam: 0.8, specDome: 0.52, specP: 11, specA: 46,
  specBlue: 1.0, spark: 52, sparkF: 14, sparkT: 0.93,
  grit: 5.5, gritF: 13, lump: 0.22, blueK: 0.85,
  gapW: 0.13, gapMix: 0.42, gapMax: 0.92, gapK: 1.0,
  deepDark: 38, sesP: 0.988, sesR: 0.35, sesA: 1.25,
  rgBase: 0.665, rgVar: 0.1, sizeVar: 0.15, edge: 18,
  edgeW: 0.34, hueVar: 8, lightJit: 0.85, quant: 0,
  rim: 0, wrapBite: 0.6, gapRgb: [88, 84, 78], sesRgb: [222, 205, 160],
};
function spreadColor(gx, gy, b, ct, st, lod) {
  const c = b.spreadRgb;
  {                                                        // крупа — у всех баз
    // ЗЕРНО, А НЕ МОЗАИКА. Раньше центры стояли на КВАДРАТНОЙ сетке, а вытягивалась только метрика:
    // клетки выходили длинными, но соседи вдоль зерна оставались через 3,5 мм вместо 7,7 — зёрна
    // сидели впритык, и глазу оставался только узор границ. Владелец так и сказала: «рис не похож
    // на рис». Теперь в систему зерна переводится САМА ТОЧКА: вдоль единица = длина зерна (7,7 мм),
    // поперёк = ширина (3,5 мм), метрика обычная. Клетка снова квадратная, но её квадрат — это и
    // есть одно зерно.
    // РЕШЁТКА ДОЛЖНА БЫТЬ ПРИБИТА К МАТЕРИАЛУ, А НЕ К ЭКРАНУ. Если брать индекс клетки из
    // ПОВЁРНУТЫХ координат, на срезе он плывёт: касательная там своя в каждой точке, центры
    // ползут вместе с ней, расстояние до ближайшего почти не меняется — и зерно исчезает,
    // остаётся гладкая спираль. Поэтому на срезе решётка полярная: поперёк зерна — радиус,
    // вдоль — ДУГА. На кольце ровно n зёрен, n округлено, поэтому шва на угле 0 нет.
    let pa, pc, ring = 0, arcw = 1, ux = 1, uy = 0, vx = 0, vy = 1;
    const polar = ct !== undefined;
    if (ct === undefined) {                                 // плоский лист: зерно вдоль оси x
      pa = gx / GRAIN_ASPECT; pc = gy; arcw = GRAIN_ASPECT;
    } else {
      const rr = Math.hypot(gx, gy) || 1e-6;
      // каждое кольцо повёрнуто на свой случайный угол, иначе зёрна встают ровными рядами,
      // как кирпичная кладка: в настоящем ролле соседние витки не выровнены друг с другом
      // КОЛЬЦА НЕ ДОЛЖНЫ ЧИТАТЬСЯ. Полярная решётка сажает зёрна по целым радиусам, и границы
      // между рядами складываются в СПЛОШНЫЕ ОКРУЖНОСТИ. На ролле радиусом в восемь зёрен это
      // восемь концентрических линий — владелец увидела их и приняла за витки: «такое ощущение,
      // что просто свернут, там спиралей, наверное, десять как минимум слоёв». Витков при этом 1,1.
      // Лечится волной по радиусу: ряд перестаёт быть окружностью, границы рвутся, размер и
      // плотность зерна не меняются. Волна гладкая и замкнутая по кругу, иначе на стыке шов.
      // ВОЛНА БЫЛА ОДНА НА ВСЕ РАДИУСЫ — И В ЭТОМ БЫЛ ДЕФЕКТ. Смещение зависело ТОЛЬКО от угла, поэтому
      // все кольца изгибались СОГЛАСОВАННО: ряды не рвались, а дружно уходили в одну сторону и
      // складывались в крупные светлые и тёмные полосы — спираль «слоёв риса». Владелец 27.08:
      // «слои риса не должны быть видны в скрученном состоянии, так в жизни невозможно». Она права:
      // в настоящем ролле рис — одна масса, витки читаются по нори, а не по рису.
      // Теперь шум ДВУМЕРНЫЙ: гладкий и по углу, и по радиусу, соседние кольца смещаются независимо.
      // Амплитуда та же (0,85), меняется только связность — форму зерна это не трогает, а радиальная
      // длина волны взята большой (4 зерна), чтобы градиент варпа остался мелким и зёрна не тянуло.
      const ang = Math.atan2(gy, gx);
      const a8 = (ang / TAU + 0.5) * 8, i8 = Math.floor(a8), f8 = a8 - i8, sa = f8 * f8 * (3 - 2 * f8);
      const rq = rr / 4, j0 = Math.floor(rq), fr = rq - j0, sr = fr * fr * (3 - 2 * fr);
      const y0 = j0 * 131 + 3331, y1 = (j0 + 1) * 131 + 3331;
      const wA = hash(i8 & 7, y0) + (hash((i8 + 1) & 7, y0) - hash(i8 & 7, y0)) * sa;
      const wB = hash(i8 & 7, y1) + (hash((i8 + 1) & 7, y1) - hash(i8 & 7, y1)) * sa;
      pa = ang / TAU + 0.5;                                 // 0..1 по кругу; в клетки переводит уже РЯД
      pc = rr + (wA + (wB - wA) * sr - 0.5) * 0.85;
      vx = gx / rr; vy = gy / rr;                           // радиальная ось (поперёк зерна)
      ux = -vy; uy = vx;                                    // касательная (вдоль зерна)
    }
    const ci = polar ? 0 : Math.floor(pa), cj = Math.floor(pc);
    let q1 = 9, hit = 0, ex = 0, ey = 0, ses = false;
    let q2 = 9, hit2 = 0, ex2 = 0, ey2 = 0;
    for (let oj = -1; oj <= 1; oj++) {
      const j2 = cj + oj;
      // РЯД — САМОСТОЯТЕЛЬНОЕ КОЛЬЦО, И ВСЁ О НЁМ СЧИТАЕТСЯ ОТ ЕГО НОМЕРА. Здесь был настоящий
      // дефект, а не вопрос вкуса: число зёрен в кольце, его поворот и длина дуги брались от
      // ТЕКУЩЕГО радиуса точки (`ring` от rr, поворот от `Math.floor(rr)`), а сам ряд определялся
      // по `floor(pc)` — по радиусу, СДВИНУТОМУ волной. Два индекса расходились, и стоило rr перейти
      // целое, как вся окрестность разом проворачивалась на 3,7 клетки: по срезу шла ОКРУЖНОСТЬ
      // РАЗРЫВА. Радиус ролла — восемь-девять зёрен, значит восемь-девять таких окружностей. Это их
      // владелец приняла за витки («десять слоёв»), и это же 27.08 назвала прямо: «слои риса не
      // должны быть видны в скрученном состоянии, так в жизни невозможно». Волна по радиусу, которую
      // добавляли раньше, лечила симптом: рвала ряды, но расхождение индексов оставалось на месте.
      // Теперь ringj, поворот и arcj считаются от j2 — внутри ряда они постоянны, и разрыву взяться
      // неоткуда. В настоящем ролле рис — одна масса: витки читаются по нори, а не по рису.
      let ringj = ring, arcj = arcw, paj = pa, cij = ci;
      if (polar) {
        const rj = Math.max(0.5, j2 + 0.5);
        ringj = Math.max(1, Math.round(TAU * rj / GRAIN_SEC_MEAN));
        arcj = TAU * rj / ringj;                            // длина дуги на одну клетку этого ряда
        paj = ringj * pa - 3.7 * hash(j2, 991);             // свой поворот у каждого ряда
        cij = Math.floor(paj);
      }
      for (let oi = -1; oi <= 1; oi++) {
        const iw = ringj > 1 ? ((cij + oi) % ringj + ringj) % ringj : cij + oi;   // кольцо замкнуто
        const h = hash(iw, j2);
        const ax = cij + oi + 0.18 + 0.64 * h - paj, ac = j2 + 0.18 + 0.64 * hash(iw, j2 + 313) - pc;
        const dxr = ax * arcj * ux + ac * vx, dyr = ax * arcj * uy + ac * vy;   // смещение в настоящих осях
        const ti = (hash(iw, j2 + 7717) * GDIR_N) | 0, cA = GDIR[3 * ti], sA = GDIR[3 * ti + 1];
        const lx = ux * cA - uy * sA, ly = ux * sA + uy * cA;                   // длинная ось ЭТОГО зерна
        const al = dxr * lx + dyr * ly, ac2 = -dxr * ly + dyr * lx;
        const sez = polar && hash(iw, j2 + 5501) > RICE.sesP;
        const rg = (RICE.rgBase + RICE.rgVar * (h - 0.5)) * (sez ? RICE.sesR : 1)
                 * (RICE.sizeVar ? 1 - RICE.sizeVar * fract(h * 43.7) : 1);
        const ra = rg * (polar ? GDIR[3 * ti + 2] : GRAIN_ASPECT) * (sez ? RICE.sesA : 1);
        let qq = al * al / (ra * ra) + ac2 * ac2 / (rg * rg);
        if (RICE.lump > 0) {                                   // кромка зерна не эллипс, а комок
          const iq = 1 / Math.max(1e-4, Math.sqrt(qq)), X = al / ra * iq, Y = ac2 / rg * iq;
          const k2 = X * X - Y * Y, s2 = 2 * X * Y, k3 = X * k2 - Y * s2, s3 = X * s2 + Y * k2;
          const w = 1 + RICE.lump * ((fract(h * 7.13) - 0.5) * k2 + (fract(h * 13.77) - 0.5) * s2
                                   + (fract(h * 23.31) - 0.5) * k3 + (fract(h * 31.7) - 0.5) * s3);
          qq /= w * w;
        }
        if (qq < q1) { q1 = qq; hit = h; ex = dxr; ey = dyr; ses = sez; }
        // ПОД ЩЕЛЬЮ ЛЕЖИТ СЛЕДУЮЩЕЕ ЗЕРНО, А НЕ ПУСТОТА. Владелец 27.08: «в просветах свёрнутого
        // риса пустота». Так и было: `q` клампился в единицу, купол обнулялся, и ВСЕ пиксели щели
        // получали один и тот же плоский тёплый цвет — дырка между зёрнами вместо плотной массы.
        // В настоящем ролле рис уложен в несколько зёрен толщиной, и в просвет видно то, что лежит
        // ниже. Здесь второй слой той же решётки: те же ряды, сдвиг на полклетки, свои хеши. Он
        // считается в этом же проходе (лишнего обхода соседей нет) и проявляется только там, где
        // верхнее зерно кончилось.
        const hb = hash(iw, j2 + 4441);
        const bx = cij + oi + 0.68 + 0.64 * hb - paj, bc = j2 + 0.68 + 0.64 * hash(iw, j2 + 4759) - pc;
        const dxb = bx * arcj * ux + bc * vx, dyb = bx * arcj * uy + bc * vy;
        const tb = (hash(iw, j2 + 8819) * GDIR_N) | 0, cB = GDIR[3 * tb], sB = GDIR[3 * tb + 1];
        const bxa = ux * cB - uy * sB, bya = ux * sB + uy * cB;
        const bl = dxb * bxa + dyb * bya, bc2 = -dxb * bya + dyb * bxa;
        const rb = RICE.rgBase + RICE.rgVar * (hb - 0.5), rab = rb * (polar ? GDIR[3 * tb + 2] : GRAIN_ASPECT);
        const qb = bl * bl / (rab * rab) + bc2 * bc2 / (rb * rb);
        if (qb < q2) { q2 = qb; hit2 = hb; ex2 = dxb; ey2 = dyb; }
      }
    }
    // Зерно — не многоугольник, а ТЕЛО: высота идёт по эллипсоиду и обрывается на кромке. Всё, что
    // дальше R, — щель между зёрнами, и она затенена, а не обведена линией. Линия давала плитку.
    const qraw = Math.sqrt(q1), q = Math.min(1, qraw);
    GRAIN_C[0] = ex; GRAIN_C[1] = ey; GRAIN_C[2] = qraw;    // чей это пиксель, решает вызывающий — по центру
    const dome = Math.sqrt(Math.max(0, 1 - q * q));         // высота над листом, 1 в центре зерна
    const en = Math.hypot(ex, ey) || 1;
    // СВЕТ У КАЖДОГО ЗЕРНА СВОЙ. Один источник на весь срез ставит блик всем зёрнам в одно и то же
    // место, и поле читается штампом. На фотографии зёрна лежат под разными углами и бликуют
    // вразнобой: это не второй источник, а нормаль верхушки зерна, которую купол не моделирует.
    let LX = LIGHT_X, LY = LIGHT_Y;
    if (RICE.lightJit > 0) {
      const gi = (fract(hit * 97.3) * GDIR_N) | 0;
      LX += RICE.lightJit * GDIR[3 * gi]; LY += RICE.lightJit * GDIR[3 * gi + 1];
      const ln = Math.hypot(LX, LY) || 1; LX /= ln; LY /= ln;
    }
    const lam = -(ex * LX + ey * LY) / en;                  // ba,bc смотрят ОТ точки К центру
    const k = lod === undefined ? 1 : lod;
    // ПОЧЕМУ LOD. На плоском листе зерно занимает единицы пикселей, и полный рельеф превращает
    // намазку в сетку. Амплитуда гаснет, когда зерно мельче ~6 device-px.
    // ПОЧЕМУ LEVEL_FIX. Рельеф и затенённые щели темнее намазки; без компенсации рис молча темнеет.
    // Приёмка прежняя: |Δ средней| <= 3.
    const lvl = RICE.level * k;                             // DC-компенсация яркости — нейтральная, без наклона в тепло
    let t = (hit - 0.5) * RICE.toneVar + (RICE.shade * lam * q + RICE.domeA * (dome - 0.62)) * k;
    if (hit > 0.955) t -= 9;                                // редкое зерно потемнее
    // МЕЛКАЯ ФАКТУРА ПОВЕРХНОСТИ. Разрезанное зерно не гладкое: срез крахмалистый, в мелких кавернах.
    // Без неё зерно читается как отлитая из пластика фасолина — и заодно теряет масштаб.
    if (RICE.grit > 0) t += RICE.grit * (hash(Math.floor(gx * RICE.gritF) + 313, Math.floor(gy * RICE.gritF) + 757) - 0.5) * dome * k;
    if (RICE.quant > 0) t = Math.round(t / RICE.quant) * RICE.quant;
    if (RICE.edge > 0) t -= RICE.edge * smooth(1 - RICE.edgeW, 1, q) * k;    // мягкий контур зерна
    if (RICE.rim > 0) t += RICE.rim * Math.pow(q, 6) * (1 - Math.max(0, lam)) * k;  // просвет на кромке
    // Блик: варёный рис глянцевый. Узкий, только на освещённом склоне ближе к макушке.
    const spec = Math.pow(Math.max(0, lam * q * RICE.specLam + dome * RICE.specDome), RICE.specP);
    let sAdd = RICE.specA * spec * k;
    if (RICE.spark > 0) {                                   // мокрое зерно бликует мелкой крошкой
      const fx = gx * RICE.sparkF, fy = gy * RICE.sparkF, ix = Math.floor(fx), iy = Math.floor(fy);
      const sp = hash(ix + 911, iy + 37);
      if (sp > RICE.sparkT) {
        const dx0 = fx - ix - 0.2 - 0.6 * hash(ix + 17, iy + 53), dy0 = fy - iy - 0.2 - 0.6 * hash(ix + 71, iy + 29);
        const dd = (dx0 * dx0 + dy0 * dy0) / 0.09;
        if (dd < 1) sAdd += RICE.spark * dome * k * (1 - dd) * (1 - dd);
      }
    }
    const gap = qraw > 1 ? Math.min(1, (qraw - 1) / RICE.gapW) : 0;
    const bc = ses ? RICE.sesRgb : c;
    // ЗЁРНА НЕ ОДНОГО ЦВЕТА. На фотографиях соседние рисинки заметно расходятся по теплу: одна отдаёт
    // в холодный белый, другая в кремовый. Один общий тон читается как пластик.
    const hv = RICE.hueVar ? RICE.hueVar * (fract(hit * 61.7) - 0.5) : 0;
    const topRgb = [bc[0] + t + lvl + sAdd + hv, bc[1] + t + lvl + sAdd, bc[2] + t * RICE.blueK + lvl + sAdd * RICE.specBlue - hv];
    if (gap <= 0) return topRgb;
    // Зерно из нижнего слоя: тот же расчёт тела и блика, но света меньше — оно в тени соседей, —
    // и к тёплому тону щели подмешано ровно столько, чтобы просвет читался щелью, а не вторым
    // рядом вровень с первым. DEEP_DARK подобран под ту же приёмку: |Δ средней яркости| <= 3.
    const qr2 = Math.sqrt(q2), q2c = Math.min(1, qr2);
    const dome2 = Math.sqrt(Math.max(0, 1 - q2c * q2c));
    const en2 = Math.hypot(ex2, ey2) || 1, lam2 = -(ex2 * LX + ey2 * LY) / en2;
    const t2 = (hit2 - 0.5) * RICE.toneVar + (RICE.shade * lam2 * q2c + RICE.domeA * (dome2 - 0.62) - RICE.deepDark) * k;
    const deep = mix([c[0] + t2 + lvl, c[1] + t2 + lvl, c[2] + t2 * RICE.blueK + lvl], RICE.gapRgb, RICE.gapMix);
    return mix(topRgb, deep, Math.min(RICE.gapMax, gap * RICE.gapK) * k);
  }
  const t = (hash(Math.floor(gx * 2), Math.floor(gy * 2)) - 0.5) * 4;     // крем и соус — мелкая рябь
  return [c[0] + t, c[1] + t, c[2] + t];
}
function wrapperColor(px, py, b) {
  const c = b.wrapperRgb, n = hash(px, py + 999);
  let t = (n - 0.5) * 8;
  return [c[0] + t, c[1] + t, c[2] + t];
}
function patchColor(m, px, py) {
  const { d, lu, lz, lv } = m, c = d.rgb;
  const dd = Math.hypot(lu * 2, lz * 2 - 1);
  switch (d.tex) {
    case 'salmon': { const s = fract(lu * 5.5 + lz * 0.7 + m.p.phase * 0.3); return mix(c, [255, 246, 236], s < 0.13 ? 0.55 : 0); }
    case 'cucumber': { if (dd > 0.84) return [86, 138, 60]; if (dd < 0.35 && hash(px, py) > 0.93) return [196, 200, 146]; return mix([214, 232, 178], c, smooth(0.2, 0.84, dd)); }
    case 'tamago': return mix(c, [200, 150, 50], fract(lz * 3.5) < 0.12 ? 0.18 : 0);
    case 'avocado': return mix([226, 224, 140], [104, 150, 60], smooth(0.15, 1, dd));
    case 'shrimp': return fract(lu * 3 + lv * 2 + 0.2) < 0.45 ? [250, 236, 224] : c;
    case 'gloss': return mix(c, [255, 255, 255], lz > 0.72 ? 0.25 : 0);
    // Разрез целой ягоды: бледная сердцевина (узкая, не половина ягоды), от неё радиальные
    // белые прожилки к мякоти, семечки — только по самой кромке, они снаружи, а не внутри.
    case 'strawberry': {
      if (dd > 0.86 && hash(px, py) > 0.9) return [248, 230, 120];            // семечки на кожице
      const ang = Math.atan2(lz * 2 - 1, lu * 2);
      // прожилки живут в средней зоне: у центра гаснут (иначе сходятся в звезду), у кромки тоже
      const vein = (fract(ang / TAU * 9 + hash(px >> 3, py >> 3) * 0.15) < 0.26 ? 1 : 0)
                 * smooth(0.18, 0.42, dd) * (1 - smooth(0.62, 0.9, dd));
      const core = 1 - smooth(0.04, 0.3, dd);                                  // сердцевина мягкая, не точка
      const pale = Math.min(0.62, core * 0.62 + vein * 0.3);
      return mix(c, [252, 214, 206], pale);                                    // бледно-розовый, не белый
    }
    case 'kiwi': { if (dd > 0.92) return [110, 90, 60]; if (dd > 0.38 && dd < 0.56 && hash(px, py) > 0.85) return [30, 25, 20]; return mix([236, 240, 190], c, smooth(0.1, 0.7, dd)); }
    // ребро ломтика ягоды: мякоть, бледная сердцевина посередине, семечки крапинами у самых краёв
    case 'berryEdge': { if (Math.abs(lu) > 0.44 && hash(px, py) > 0.72) return [248, 230, 120];
      const core = 1 - Math.min(1, Math.abs(lu) * 2.6);
      return mix(c, [252, 214, 206], core * 0.5); }
    // ребро ломтика киви: тёмная кожица по краям, светлая сердцевина посередине, редкие семечки
    case 'kiwiEdge': { if (Math.abs(lu) > 0.44) return [120, 100, 62]; const core = 1 - Math.min(1, Math.abs(lu) * 3.2);
      if (core > 0.55 && hash(px, py) > 0.93) return [244, 246, 214];
      return mix(c, [232, 240, 186], core * 0.75); }
    case 'banana': { if (dd > 0.9) return [226, 208, 140];                       // тонкая шкурка-кромка
      const seeds = dd < 0.3 && hash(px >> 1, py >> 1) > 0.86;
      return seeds ? [148, 120, 78] : mix([252, 244, 208], c, smooth(0.1, 0.95, dd)); }
    case 'mango': return mix(c, [255, 214, 120], fract(lu * 4 + lz) < 0.2 ? 0.25 : 0);
    case 'nut': return mix([220, 180, 120], c, dd);
    case 'cheese': { if (hash(px >> 1, py >> 1) > 0.93) return [236, 214, 130]; return mix(c, [255, 240, 170], lz > 0.75 ? 0.2 : 0); }
    case 'tomato': { if (dd < 0.55 && hash(px, py) > 0.9) return [250, 230, 150]; return mix([246, 130, 110], c, smooth(0.2, 0.9, dd)); }
    case 'pepper': return dd > 0.8 ? [150, 30, 20] : mix([240, 90, 70], c, dd);
    case 'ham': { if (hash(px >> 1, py) > 0.94) return [250, 235, 230]; return c; }
    case 'lettuce': return fract(lu * 6 + m.p.phase) < 0.12 ? [214, 236, 170] : c;
    case 'dill': { const n = hash(px, py); return n > 0.7 ? [70, 110, 50] : n > 0.4 ? [190, 205, 160] : [230, 232, 212]; }
    case 'rice': { const n1 = hash(px >> 1, py >> 1), n2 = hash(px >> 2, (py >> 2) + 77); let t = (n1 - 0.5) * 10 + (n2 - 0.5) * 16; if (n1 > 0.965) t -= 24; return [c[0] + t, c[1] + t, c[2] + t * 0.6]; }
    default: return c;
  }
}

