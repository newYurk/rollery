  // `u0/u1` пишутся в цикле намотки по радиусам «как намотано», и там закон длины выполнен
  // ТОЖДЕСТВЕННО: шаг листа берётся `ds = DPHI·(r + t/2)`, то есть ровно дуга по средней линии.
  // Но дальше `переложить` переписывает `rin/rout` — трижды: обжим циновкой, растекание, грани.
  // Слой встаёт на другие радиусы, а карта остаётся от прежней геометрии.
