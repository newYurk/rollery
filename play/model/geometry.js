// ⚑ У ТЕЛА И У КРАСКИ РАЗНАЯ ГЛУБИНА, И ЭТО НЕ ПРИДИРКА (#134, 02.09).
//
// Слой в намотке толще или тоньше стопки, которую он несёт: профиль сглажен и в него входит
// раздача вытесненного риса, а `stackTopAt` отдаёт стопку сырой. Прежде это лечилось одной
// растяжкой — вся стопка натягивалась на слой, — и вместе с рисом растягивалось ТЕЛО куска.
// Замер: один тамаго, двигаемый вдоль листа, менял площадь среза с 80 % до 164 % каталожной.
//
// Разделяем. КРАСКА — это «рис такого цвета», она обязана заполнять ровно столько, сколько
// заполняет рис, и тянется со слоем как раньше. ТЕЛО имеет собственную толщину и тянуться не
// должно: избыток слоя над стопкой — это рис, а не разбухший кусок. Сжатие телу оставлено:
// когда слой ТОНЬШЕ стопки, кусок обязан в него влезть, иначе он вылезет за виток.
//
// Проба «убрать растяжку всем» провалила #95: краска переставала доходить до конца листа,
// в намотке оставался белый рис на 1339 точек. Это и показало, что величины две, а не одна.
// ⚑ СДАВЛЕННЫЙ КУСОК РАСШИРЯЕТСЯ ПО ДУГЕ: h × дуга = const (#134, правка 03.09).
//
// Слой в намотке бывает тоньше стопки, которую несёт, и тогда `натяг` в materialAt сжимает
// кусок радиально — иначе он вылез бы за виток. Но сжимался он БЕЗ КОМПЕНСАЦИИ: толщина
// падала, дуга оставалась своей, и площадь сечения терялась. Замер (тамаго между двумя
// соседями, футомаки):
//
//     u      площадь/каталог   толщина куска   полоса слоя
//     0,30   0,908             8,47 мм         9,28 мм
//     0,40   1,123             9,95            13,35
//     0,50   0,948             9,15             9,20
//     0,60   0,910             8,78             8,82
//     0,70   0,937             8,94             8,99
//
// Толщина идёт следом за полосой, а не держится — то есть кусок сминается вместе со слоем.
// Разложение: `S/каталог = f2 × min(1, полоса/hU)`, и второй множитель даёт больший разброс
// (1,175 против 1,085). Это его и снимает.
//
// Физика прямая: несжимаемое тело, сдавленное по одной оси, обязано раздаться по другой.
// Кусок начинки не сыпучий — огурец и тамаго объём сохраняют, — значит `h × дуга = const`.
// Разбор веером 02.09 показал, что этого правила не называл ни один из трёх вариантов, между
// которыми я выбирала, и без него мягкий порог #134 не зеленеет ни при одном.
//
// Реализация: координата листа СЖИМАЕТСЯ К ЦЕНТРУ КУСКА на тот же множитель. Тогда в кусок
// попадает `натяг` раз более широкая полоса угла — то есть дуга растёт ровно во столько же,
// во сколько упала толщина.
//
// ⚠ ТОЛЬКО ТЕЛУ, НЕ КРАСКЕ. Краска — это «рис такого цвета», она обязана заполнять ровно
// столько, сколько заполняет рис, и площадь свою не хранит (её сохранение сломало бы #95).
// ⚠ И ТОЛЬКО ПРИ СЖАТИИ. Когда слой ТОЛЩЕ стопки, кусок не растянут — он лежит своей
// толщиной и плавает в слое, дуге меняться не с чего.
// ⚠ matAt зовётся ТОЛЬКО из materialAt, то есть из намотки. Плоский лист и профиль идут
// другим путём, и растяжение до них не доходит — проверено grep по вызовам.
function matAt(u, v, z, list, g, zКраска, полосаN) {
  const L = gL(g);
  for (let pass = 0; pass < 2; pass++) for (let i = list.length - 1; i >= 0; i--) {
    const p = list[i], d = ING[p.kind];
    if (d.bedDelta) continue;   // грядка/ложбинка — это толщина постели, а не тело на срезе (#17)
    if (p.inCore || !!d.paint !== (pass === 1)) continue;
    // ⚑ КРАСКА ТЕПЕРЬ ТОЖЕ ПРОВЕРЯЕТСЯ ПО ГЛУБИНЕ (01.09, #132). Прежде проверка её пропускала:
    // «краска — не тело, а цвет риса», и она красила столбик насквозь. В спирали это давало
    // тонкую полоску на витке, в кольце — сектор во всю толщину. Глубину краске назначает
    // restack: верх постели на её собственную толщину, потому что 「塗るようにおいて」 — намазывают
    // ПО ПОВЕРХНОСТИ. Цветом риса она от этого быть не перестала: тело у неё по-прежнему не
    // считается отдельно, она просто перекрашивает рис там, где лежит.
    const rg = patchSRange(p, v, g); if (!rg) continue;
    // ⚑ ВЫСОТА ТОЖЕ ПО ПРОФИЛЮ ВДОЛЬ ОСИ (#10). Кусок сужается телом, а не сплющивается:
    // тот же множитель, что у ширины, и считается от НИЗА — кусок лежит на рисе, а не висит.
    const kA = rg[8] === undefined ? 1 : rg[8];
    const z1k = p.z0 + (p.z1 - p.z0) * kA;
    const zz = (d.paint && zКраска !== undefined) ? zКраска : z;
    if (zz < p.z0 || zz > z1k) continue;
    // Сжатие координаты к центру куска — то самое `h × дуга = const`; краска идёт без него.
    //
    // ⚠ МНОЖИТЕЛЬ БЕРЁТСЯ ОТ САМОГО КУСКА, А НЕ ОТ ТОЧКИ ЗАМЕРА, И ЭТО НЕ ПЕДАНТИЗМ. Первая
    // редакция брала `натяг` из materialAt — а он считается по стопке В ТОЧКЕ, и за пределами
    // куска стопка ниже, натяг падает к единице, расширение само себя гасило. Замер: дуга
    // выросла на 7,5 % при сжатии 13,1 %, то есть меньше половины нужного. Собственная высота
    // куска `z1k` от угла не зависит, поэтому множитель постоянен по всей его дуге.
    const ст_ = (d.paint || !(полосаN > 1e-6) || z1k <= полосаN) ? 1 : z1k / полосаN;
    const sUц = rg[2] * L;
    const sU = ст_ === 1 ? u * L : sUц + (u * L - sUц) / ст_;
    if (sU < rg[0] || sU > rg[1]) { if (!smearAt(p, d, sU, g)) continue; }
    const du_ = sU - sUц, across = du_ * rg[5] + rg[7] * rg[6], along = -du_ * rg[6] + rg[7] * rg[5];
    const lu = across / rg[3];
    const lz = d.paint ? 0.5 : (zz - p.z0) / Math.max(1e-9, z1k - p.z0);
    if (!d.paint) {
      // ОБОЛОЧКА ОБЁРНУТОГО КУСКА (issue #115). Габарит уже увеличен на 2·hN (см. dims), поэтому
      // lu и lz идут по ВНЕШНЕМУ контуру. Пересчитываем их во внутренний: попал — это сам кусок,
      // не попал — значит между контурами, и там нори. Профиль один и тот же, оттого оболочка
      // повторяет форму куска и сходится по углам сама, без торцевых плашек.
      if (p.noriWrap) {
        const hN = WRAP_HU(), w0 = (p.wU ?? d.wU), h0 = (p.hU ?? d.hU);
        const kw = (w0 + 2 * hN) / w0, kh = (h0 + 2 * hN) / h0;
        const luIn = lu * kw, lzIn = (lz - hN / (h0 + 2 * hN)) * kh;
        const внутри = Math.abs(luIn) <= 0.5 && lzIn >= 0 && lzIn <= 1 &&
                       (() => { const sp = cutSpan(d, luIn); return lzIn >= sp[0] && lzIn <= sp[1]; })();
        const spOut = cutSpan(d, lu);
        if (lz < spOut[0] || lz > spOut[1]) continue;          // вне внешнего контура — мимо куска
        if (!внутри) return { p, d: ING.nori, lu, lz, lv: along / rg[4], оболочка: true };
        return { p, d, lu: luIn, lz: lzIn, lv: along / rg[4] };
      }
      const sp = cutSpan(d, lu); if (lz < sp[0] || lz > sp[1]) continue;
    }
    return { p, d, lu, lz, lv: along / rg[4] };
  }
  return null;
}
