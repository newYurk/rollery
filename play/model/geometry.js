const RIM_W = 0.05;   // доля листа под бортиком: ≈ 10 мм на футомаки, ≈ 5 мм на хосомаки
const RIM_H = 1.30;   // во сколько раз бортик выше грядки
// СЛАДКИЙ РУЛЕТ — ЗЕРКАЛЬНО К СУШИ, И ЭТО НЕ ОПЕЧАТКА. Крем кладут густо у БЛИЖНЕГО края и
