// Материал в точке среза (r, φ): 'out' | 'core' | 'wrap' | 'spread' | { патч }.
function materialAt(m, wd, vSlice, r, phi) {
  const g = m.g;
  const rin0 = innerAt(wd, phi), coreR = rin0 >= 0 ? rin0 : g.r0;
  // Внутри сердцевины материал берётся ТОЛЬКО у подворота (m.core). У спиральных баз ядра нет —
  // там полая трубка, и спрашивать лист при u = 0,002 нельзя: начинка у ближнего края проявлялась
  // внутри дырки, где листа физически нет.
  // ⚑ У СПИРАЛИ СЕРЕДИНА — ВДАВЛЕННЫЙ РИС, А НЕ ПУСТОТА (#154). Разбор — над `g.coreFill`.
  // Класс 'spread' здесь честен: за этот рис платит постель, площадь сходится.
  if (r < coreR) return m.core ? coreMaterial(m, r, phi, vSlice) : { cls: 'spread', sm: null };
  const sm = sampleWind(wd, r, phi);
  if (!sm) return { cls: 'out' };
  // ⚠ У УРАМАКИ ОБЁРТКА НА ВНУТРЕННЕМ КРАЮ ВИТКА, А НЕ НА ВНЕШНЕМ (#124, 01.09).
  // Так его и делают: рис намазан на нори, лист ПЕРЕВОРАЧИВАЮТ рисом на циновку, начинку
  // кладут на голую нори — и она заворачивает начинку первой, а рис остаётся снаружи.
  // До этой правки `inverted` жил в ОДНОЙ строке отрисовки: «рис снаружи» было нарисовано,
  // но не смоделировано — модель наматывала урамаки как обычный маки.
  //
  // zn — высота над обёрткой, вдоль которой растёт стопка (рис, потом начинки). У обычного
  // маки обёртка снаружи витка, и стопка растёт ВНУТРЬ; у вывернутого наоборот.
  // ⚑ У ВЫВЕРНУТОГО ОБЁРТКА — ПЕРВЫЙ СЛОЙ ОТ ЯДРА (#124, правка 02.09). Раньше она была
  // вторым витком снаружи при любой базе, и это правило разворачивало стопку «наоборот»,
  // чтобы компенсировать. Теперь намотка кладёт её на своё место, и компенсация не нужна:
  // толщина над обёрткой считается одинаково, разница живёт в намотке.
  // ⚑ В КОЛЬЦЕ НОСИТЕЛЬ — ОТДЕЛЬНЫЙ СЛОЙ, В СПИРАЛИ ОН ВНУТРИ СЛОЯ (#164, правка 02.09).
  //
  // Здесь стояло безусловное `− g.w`: «в каждом слое снизу лежит носитель, вычтем его». Для
  // спирали это правда — там намотка кладёт `t += W` (см. `wind`), носитель действительно часть
  // слоя. В кольце НЕТ: слой риса это `rр = √(r0b² + 2·t·Lрис/TAU)` при `t = prof` БЕЗ `w`, а
  // нори лежит отдельным витком толщиной ровно `w`. Вычитание срабатывало дважды — честно на
  // слое нори и ещё раз на внешних `w` рисового слоя.
  //
  // Замер: нори на срезе кольца выходила 0,200 мм при каталожных 0,100, под нахлёстом 0,300.
  // Ровно вдвое и втрое. У спирали в том же замере 9,00 при 1,50 — это шесть пересечений луча
  // по шести виткам, то есть там всё верно. Рассогласование двух веток, а не общая ошибка.
  //
  // Второе, что чинится этим же: глубина `zn` отсчитывалась от неверной границы, и КАЖДЫЙ кусок
  // в кольцевой намотке был сдвинут внутрь на толщину нори.
  const носительВСлое = g.winding === 'spiral';
  let zn = (sm.t - (носительВСлое ? g.w : 0) - sm.zr) / g.T;
  // ⚑ У ВЫВЕРНУТОГО СНАРУЖИ РИС, И «НИЖЕ ОБЁРТКИ» ЗНАЧИТ ДРУГОЕ (#124, правка 02.09).
  //
  // `zn < 0` означает «мы за пределами намазки, дальше обёртка» — верно для обычного маки,
  // где нори снаружи витка. У урамаки нори ПЕРВЫМ слоем от ядра, а снаружи рис, и то же
  // условие красило внешнюю кромку в нори: замер по лучу давал zn = −0,008 на 0,99 радиуса,
  // и на срезе выходило «ПНрН» вместо «ПНр».
  //
  // Проверено 22 источниками (разбор в #124): 東京すしアカデミー 「外側に寿司飯、内側に海苔」,
  // ja.wikipedia 「外側から酢飯、海苔、具の順」, и порядок сборки в рецептах — начинку
  // заворачивают в нори, ПОТОМ обматывают рисом. Второго слоя нори нет.
  // ⚠ У ВЫВЕРНУТОГО ОБЁРТКА — ЭТО ВЕСЬ ПЕРВЫЙ СЛОЙ, а не «то, что ниже намазки». Намотка
  // кладёт её отдельным витком толщиной ровно `w`, поэтому и узнаём её по толщине слоя, а не
  // по знаку zn: у слоя-обёртки `t ≈ w`, у слоя-риса `t ≈ T`. Разница в семьдесят раз, спутать
  // нечего. Через zn не выходит: там `zr` меряется внутри СВОЕГО слоя и про соседей не знает.
  // Носитель узнаём по ТОЛЩИНЕ СЛОЯ там, где он сам себе слой (кольцо, любое — обычное и
  // вывернутое): у него `t ≈ w`, у слоя риса `t ≈ T`, разница в семьдесят раз. В спирали он
  // внутри слоя, и там его выдаёт знак `zn`. Прежде по толщине опознавался только вывернутый —
  // отсюда и удвоение нори у обычного кольца.
  if (!носительВСлое) { if (sm.t <= g.w * 1.5) return { cls: 'wrap', sm }; }
  else if (zn < 0) return { cls: 'wrap', sm };
  if (zn < 0) zn = 0;
  const H = stackTopAt(sm.u, vSlice, m.list, g), bandN = (sm.t - (носительВСлое ? g.w : 0) - (m.g.air || 0)) / g.T;
  const натяг = bandN > 1e-6 ? Math.max(1, H) / bandN : 1;
  // Телу — только сжатие (натяг > 1), краске — и сжатие, и растяжение: разбор над matAt.
  const znТело = натяг > 1 ? zn * натяг : zn, znКраска = zn * натяг;
  const mt = matAt(sm.u, vSlice, znТело, m.list, g, znКраска, bandN);
  return mt ? { cls: 'patch', mt, sm } : { cls: 'spread', sm };
}

