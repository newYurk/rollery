function windFor(m, v) { const key = v.toFixed(4); let wd = m.wds.get(key); if (!wd) { wd = wind(v, m.g.L, m.g, m.list); m.wds.set(key, wd); } return wd; }
// Материал в точке среза (r, φ): 'out' | 'core' | 'wrap' | 'spread' | { патч }.
function materialAt(m, wd, vSlice, r, phi) {
  const g = m.g;
  const rin0 = innerAt(wd, phi), coreR = rin0 >= 0 ? rin0 : g.r0;
  // Внутри сердцевины материал берётся ТОЛЬКО у подворота (m.core). У спиральных баз ядра нет —
  // там полая трубка, и спрашивать лист при u = 0,002 нельзя: начинка у ближнего края проявлялась
  // внутри дырки, где листа физически нет.
  if (r < coreR) return m.core ? coreMaterial(m, r, phi, vSlice) : { cls: 'core' };
  const sm = sampleWind(wd, r, phi);
  if (!sm) return { cls: 'out' };
  // ⚠ У УРАМАКИ ОБЁРТКА НА ВНУТРЕННЕМ КРАЮ ВИТКА, А НЕ НА ВНЕШНЕМ (#124, 01.09).
  // Так его и делают: рис намазан на нори, лист ПЕРЕВОРАЧИВАЮТ рисом на циновку, начинку
  // кладут на голую нори — и она заворачивает начинку первой, а рис остаётся снаружи.
  // До этой правки `inverted` жил в ОДНОЙ строке отрисовки: «рис снаружи» было нарисовано,
  // но не смоделировано — модель наматывала урамаки как обычный маки.
  //
  // zn — высота над обёрткой, вдоль которой растёт стопка (рис, потом начинки). У обычного
  // маки обёртка снаружи витка, и стопка растёт ВНУТРЬ; у вывернутого наоборот.
  let zn = g.inverted ? (sm.zr - g.w) / g.T : (sm.t - g.w - sm.zr) / g.T;
  if (zn < 0) return { cls: 'wrap', sm };
  const H = stackTopAt(sm.u, vSlice, m.list, g), bandN = (sm.t - g.w - (m.g.air || 0)) / g.T; if (bandN > 1e-6) zn *= Math.max(1, H) / bandN;   // сжатый слой → собственные z стопки
  const mt = matAt(sm.u, vSlice, zn, m.list, g);
  return mt ? { cls: 'patch', mt, sm } : { cls: 'spread', sm };
}

// ---------------------------------------------------------------- цвета материалов на срезе
// Крупа рисуется в РАЗМЕРЕ ЗЕРНА, а не в пикселях экрана. Хеш от экранных координат —
// шум по двухпиксельным клеткам, то есть зерно зависело от зума и выходило ~0,25 мм вместо 2,5 мм,
// в десять раз мельче настоящего. ⚠ Прежние 2,5 мм были ТОЛЩИНОЙ зерна, а не поперечником:
// поперечник по Мацуи 2001 — 3,5 мм, отсюда GRAIN = 0,7. В этой строке 2,5 мм называлось
// «верным размером» — прямо над константой, которая его опровергает.
// (им скругляются углы квадратного ролла, см. shapeInfo). Аргументы gx, gy — координаты В ЗЁРНАХ.
// Рельеф зерна, направление света и щель между зёрнами — УСЛОВНОСТИ ОТРИСОВКИ, помечены `inferred`:
// источника у них нет, замером они не являются и в таблицу физических толщин переезжать не имеют права
// (docs/geometry-audit.md, раздел «Условности отрисовки»).
const GRAIN = 0.7;
const GRAIN_ASPECT = 2.2;
const LIGHT_X = -0.70, LIGHT_Y = -0.71;   // one light for the whole slice; chosen to agree with `vig` in renderSection (key from the top-left)
const GRAIN_C = new Float32Array(3);   // [0],[1] — смещение к центру зерна; [2] — q (1 на кромке)      // смещение от точки к центру НАЙДЕННОГО зерна, в единицах зерна
// У КАЖДОГО ЗЕРНА СВОЙ УГОЛ. Без этого на плоском листе все рисинки лежат вдоль оси x —
// владелец заметила, что все рисинки будто уложены строго горизонтально. Так и было: решётка задавала не
// только центры, но и направление. Замер по фотографиям (Kanpyō-maki 001, Makizushi2): вдоль
// касательной ≤30° лежат 50–56 % зёрен, радиально ≥60° — 18–20 %; случайная укладка дала бы 33/33.
// Значит уклон к намотке есть, но слабый. Здесь: 35 % зёрен идут вдоль (±25°), остальные как попало.
// Таблица — чтобы не звать синус и косинус по девять раз на пиксель.
const WRAP_BULGE = 0.12;   // 0,6 мм — насколько лист выгибается над выступающим зерном (inferred)
const RICE_FLAT = 0.55;
const GDIR_N = 512, GDIR = new Float32Array(GDIR_N * 3);
let GRAIN_SEC_MEAN = 1.0;
(function () {
  let sd = 12345; const rr = () => (sd = (sd * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
  let acc = 0;
  for (let i = 0; i < GDIR_N; i++) {
    const z = 2 * rr() - 1, th = rr() * TAU, rxy = Math.sqrt(Math.max(0, 1 - z * z));
    let nA = rxy * Math.cos(th), nT = rxy * Math.sin(th), nR = z * RICE_FLAT;
    const n = Math.hypot(nA, nT, nR) || 1; nA /= n; nT /= n; nR /= n;
    const c2 = nA * nA;
    const asp = GRAIN_ASPECT / Math.sqrt(GRAIN_ASPECT * GRAIN_ASPECT * c2 + (1 - c2));
    const m = Math.hypot(nT, nR) || 1;
    GDIR[3 * i] = nT / m; GDIR[3 * i + 1] = nR / m; GDIR[3 * i + 2] = asp; acc += asp;
  }
  GRAIN_SEC_MEAN = acc / GDIR_N;
})();
const RICE = {
  toneVar: 15, shade: 17, domeA: 18, level: 8.4,
  specLam: 0.8, specDome: 0.52, specP: 11, specA: 46,
  specBlue: 1.0, spark: 52, sparkF: 14, sparkT: 0.93,
  grit: 5.5, gritF: 13, lump: 0.22, blueK: 0.85,
  gapW: 0.13, gapMix: 0.42, gapMax: 0.92, gapK: 1.0,
  deepDark: 38, sesP: 0.988, sesR: 0.35, sesA: 1.25,
  rgBase: 0.665, rgVar: 0.1, sizeVar: 0.15, edge: 18,
  edgeW: 0.34, hueVar: 8, lightJit: 0.85, quant: 0,
  rim: 0, wrapBite: 0.6, gapRgb: [88, 84, 78], sesRgb: [222, 205, 160],
};
function spreadColor(gx, gy, b, ct, st, lod) {
  const c = b.spreadRgb;
  {                                                        // крупа — у всех баз
    // ЗЕРНО, А НЕ МОЗАИКА. Раньше центры стояли на КВАДРАТНОЙ сетке, а вытягивалась только метрика:
    // клетки выходили длинными, но соседи вдоль зерна оставались через 3,5 мм вместо 7,7 — зёрна
    // сидели впритык, и глазу оставался только узор границ. Владелец так и сказала: рис на рис
    // не похож. Теперь в систему зерна переводится САМА ТОЧКА: вдоль единица = длина зерна (7,7 мм),
    // поперёк = ширина (3,5 мм), метрика обычная. Клетка снова квадратная, но её квадрат — это и
    // есть одно зерно.
    // РЕШЁТКА ДОЛЖНА БЫТЬ ПРИБИТА К МАТЕРИАЛУ, А НЕ К ЭКРАНУ. Если брать индекс клетки из
    // ПОВЁРНУТЫХ координат, на срезе он плывёт: касательная там своя в каждой точке, центры
    // ползут вместе с ней, расстояние до ближайшего почти не меняется — и зерно исчезает,
    // остаётся гладкая спираль. Поэтому на срезе решётка полярная: поперёк зерна — радиус,
    // вдоль — ДУГА. На кольце ровно n зёрен, n округлено, поэтому шва на угле 0 нет.
    let pa, pc, ring = 0, arcw = 1, ux = 1, uy = 0, vx = 0, vy = 1;
    const polar = ct !== undefined;
    if (ct === undefined) {                                 // плоский лист: зерно вдоль оси x
      pa = gx / GRAIN_ASPECT; pc = gy; arcw = GRAIN_ASPECT;
    } else {
      const rr = Math.hypot(gx, gy) || 1e-6;
      // каждое кольцо повёрнуто на свой случайный угол, иначе зёрна встают ровными рядами,
      // как кирпичная кладка: в настоящем ролле соседние витки не выровнены друг с другом
      // КОЛЬЦА НЕ ДОЛЖНЫ ЧИТАТЬСЯ. Полярная решётка сажает зёрна по целым радиусам, и границы
      // между рядами складываются в СПЛОШНЫЕ ОКРУЖНОСТИ. На ролле радиусом в восемь зёрен это
      // восемь концентрических линий — владелец увидела их и приняла за витки: ей показалось, что
      // ролл свёрнут по меньшей мере в десяток слоёв-спиралей. Витков при этом 1,1.
      // Лечится волной по радиусу: ряд перестаёт быть окружностью, границы рвутся, размер и
      // плотность зерна не меняются. Волна гладкая и замкнутая по кругу, иначе на стыке шов.
      // ВОЛНА БЫЛА ОДНА НА ВСЕ РАДИУСЫ — И В ЭТОМ БЫЛ ДЕФЕКТ. Смещение зависело ТОЛЬКО от угла, поэтому
      // все кольца изгибались СОГЛАСОВАННО: ряды не рвались, а дружно уходили в одну сторону и
      // складывались в крупные светлые и тёмные полосы — спираль «слоёв риса». Владелец 27.08
      // потребовала убрать это: на скрученном ролле слои риса видны быть не должны, в жизни так не бывает. Она права:
      // в настоящем ролле рис — одна масса, витки читаются по нори, а не по рису.
      // Теперь шум ДВУМЕРНЫЙ: гладкий и по углу, и по радиусу, соседние кольца смещаются независимо.
      // Амплитуда та же (0,85), меняется только связность — форму зерна это не трогает, а радиальная
      // длина волны взята большой (4 зерна), чтобы градиент варпа остался мелким и зёрна не тянуло.
      const ang = Math.atan2(gy, gx);
      const a8 = (ang / TAU + 0.5) * 8, i8 = Math.floor(a8), f8 = a8 - i8, sa = f8 * f8 * (3 - 2 * f8);
      const rq = rr / 4, j0 = Math.floor(rq), fr = rq - j0, sr = fr * fr * (3 - 2 * fr);
      const y0 = j0 * 131 + 3331, y1 = (j0 + 1) * 131 + 3331;
      const wA = hash(i8 & 7, y0) + (hash((i8 + 1) & 7, y0) - hash(i8 & 7, y0)) * sa;
      const wB = hash(i8 & 7, y1) + (hash((i8 + 1) & 7, y1) - hash(i8 & 7, y1)) * sa;
      pa = ang / TAU + 0.5;                                 // 0..1 по кругу; в клетки переводит уже РЯД
      pc = rr + (wA + (wB - wA) * sr - 0.5) * 0.85;
      vx = gx / rr; vy = gy / rr;                           // радиальная ось (поперёк зерна)
      ux = -vy; uy = vx;                                    // касательная (вдоль зерна)
    }
    const ci = polar ? 0 : Math.floor(pa), cj = Math.floor(pc);
    let q1 = 9, hit = 0, ex = 0, ey = 0, ses = false;
    let q2 = 9, hit2 = 0, ex2 = 0, ey2 = 0;
    for (let oj = -1; oj <= 1; oj++) {
      const j2 = cj + oj;
      // РЯД — САМОСТОЯТЕЛЬНОЕ КОЛЬЦО, И ВСЁ О НЁМ СЧИТАЕТСЯ ОТ ЕГО НОМЕРА. Здесь был настоящий
      // дефект, а не вопрос вкуса: число зёрен в кольце, его поворот и длина дуги брались от
      // ТЕКУЩЕГО радиуса точки (`ring` от rr, поворот от `Math.floor(rr)`), а сам ряд определялся
      // по `floor(pc)` — по радиусу, СДВИНУТОМУ волной. Два индекса расходились, и стоило rr перейти
      // целое, как вся окрестность разом проворачивалась на 3,7 клетки: по срезу шла ОКРУЖНОСТЬ
      // РАЗРЫВА. Радиус ролла — восемь-девять зёрен, значит восемь-девять таких окружностей. Это их
      // владелец приняла за витки — насчитала на глаз десяток слоёв, — и это же 27.08 назвала прямо:
      // на скрученном ролле слои риса видны быть не должны, в жизни так не бывает. Волна по радиусу, которую
      // добавляли раньше, лечила симптом: рвала ряды, но расхождение индексов оставалось на месте.
      // Теперь ringj, поворот и arcj считаются от j2 — внутри ряда они постоянны, и разрыву взяться
      // неоткуда. В настоящем ролле рис — одна масса: витки читаются по нори, а не по рису.
      let ringj = ring, arcj = arcw, paj = pa, cij = ci;
      if (polar) {
        const rj = Math.max(0.5, j2 + 0.5);
        ringj = Math.max(1, Math.round(TAU * rj / GRAIN_SEC_MEAN));
        arcj = TAU * rj / ringj;                            // длина дуги на одну клетку этого ряда
        paj = ringj * pa - 3.7 * hash(j2, 991);             // свой поворот у каждого ряда
        cij = Math.floor(paj);
      }
      for (let oi = -1; oi <= 1; oi++) {
        const iw = ringj > 1 ? ((cij + oi) % ringj + ringj) % ringj : cij + oi;   // кольцо замкнуто
        const h = hash(iw, j2);
        const ax = cij + oi + 0.18 + 0.64 * h - paj, ac = j2 + 0.18 + 0.64 * hash(iw, j2 + 313) - pc;
        const dxr = ax * arcj * ux + ac * vx, dyr = ax * arcj * uy + ac * vy;   // смещение в настоящих осях
        const ti = (hash(iw, j2 + 7717) * GDIR_N) | 0, cA = GDIR[3 * ti], sA = GDIR[3 * ti + 1];
        const lx = ux * cA - uy * sA, ly = ux * sA + uy * cA;                   // длинная ось ЭТОГО зерна
        const al = dxr * lx + dyr * ly, ac2 = -dxr * ly + dyr * lx;
        const sez = polar && hash(iw, j2 + 5501) > RICE.sesP;
        const rg = (RICE.rgBase + RICE.rgVar * (h - 0.5)) * (sez ? RICE.sesR : 1)
                 * (RICE.sizeVar ? 1 - RICE.sizeVar * fract(h * 43.7) : 1);
        const ra = rg * (polar ? GDIR[3 * ti + 2] : GRAIN_ASPECT) * (sez ? RICE.sesA : 1);
        let qq = al * al / (ra * ra) + ac2 * ac2 / (rg * rg);
        if (RICE.lump > 0) {                                   // кромка зерна не эллипс, а комок
          const iq = 1 / Math.max(1e-4, Math.sqrt(qq)), X = al / ra * iq, Y = ac2 / rg * iq;
          const k2 = X * X - Y * Y, s2 = 2 * X * Y, k3 = X * k2 - Y * s2, s3 = X * s2 + Y * k2;
          const w = 1 + RICE.lump * ((fract(h * 7.13) - 0.5) * k2 + (fract(h * 13.77) - 0.5) * s2
                                   + (fract(h * 23.31) - 0.5) * k3 + (fract(h * 31.7) - 0.5) * s3);
          qq /= w * w;
        }
        if (qq < q1) { q1 = qq; hit = h; ex = dxr; ey = dyr; ses = sez; }
        // ПОД ЩЕЛЬЮ ЛЕЖИТ СЛЕДУЮЩЕЕ ЗЕРНО, А НЕ ПУСТОТА. Владелец 27.08 указала на дефект: в
        // просветах между зёрнами свёрнутого риса зияет пустота. Так и было: `q` клампился в единицу, купол обнулялся, и ВСЕ пиксели щели
        // получали один и тот же плоский тёплый цвет — дырка между зёрнами вместо плотной массы.
        // В настоящем ролле рис уложен в несколько зёрен толщиной, и в просвет видно то, что лежит
        // ниже. Здесь второй слой той же решётки: те же ряды, сдвиг на полклетки, свои хеши. Он
        // считается в этом же проходе (лишнего обхода соседей нет) и проявляется только там, где
        // верхнее зерно кончилось.
        const hb = hash(iw, j2 + 4441);
        const bx = cij + oi + 0.68 + 0.64 * hb - paj, bc = j2 + 0.68 + 0.64 * hash(iw, j2 + 4759) - pc;
        const dxb = bx * arcj * ux + bc * vx, dyb = bx * arcj * uy + bc * vy;
        const tb = (hash(iw, j2 + 8819) * GDIR_N) | 0, cB = GDIR[3 * tb], sB = GDIR[3 * tb + 1];
        const bxa = ux * cB - uy * sB, bya = ux * sB + uy * cB;
        const bl = dxb * bxa + dyb * bya, bc2 = -dxb * bya + dyb * bxa;
        const rb = RICE.rgBase + RICE.rgVar * (hb - 0.5), rab = rb * (polar ? GDIR[3 * tb + 2] : GRAIN_ASPECT);
        const qb = bl * bl / (rab * rab) + bc2 * bc2 / (rb * rb);
        if (qb < q2) { q2 = qb; hit2 = hb; ex2 = dxb; ey2 = dyb; }
      }
    }
    // Зерно — не многоугольник, а ТЕЛО: высота идёт по эллипсоиду и обрывается на кромке. Всё, что
    // дальше R, — щель между зёрнами, и она затенена, а не обведена линией. Линия давала плитку.
    const qraw = Math.sqrt(q1), q = Math.min(1, qraw);
    GRAIN_C[0] = ex; GRAIN_C[1] = ey; GRAIN_C[2] = qraw;    // чей это пиксель, решает вызывающий — по центру
    const dome = Math.sqrt(Math.max(0, 1 - q * q));         // высота над листом, 1 в центре зерна
    const en = Math.hypot(ex, ey) || 1;
    // СВЕТ У КАЖДОГО ЗЕРНА СВОЙ. Один источник на весь срез ставит блик всем зёрнам в одно и то же
    // место, и поле читается штампом. На фотографии зёрна лежат под разными углами и бликуют
    // вразнобой: это не второй источник, а нормаль верхушки зерна, которую купол не моделирует.
    let LX = LIGHT_X, LY = LIGHT_Y;
    if (RICE.lightJit > 0) {
      const gi = (fract(hit * 97.3) * GDIR_N) | 0;
      LX += RICE.lightJit * GDIR[3 * gi]; LY += RICE.lightJit * GDIR[3 * gi + 1];
      const ln = Math.hypot(LX, LY) || 1; LX /= ln; LY /= ln;
    }
    const lam = -(ex * LX + ey * LY) / en;                  // ba,bc смотрят ОТ точки К центру
    const k = lod === undefined ? 1 : lod;
    // ПОЧЕМУ LOD. На плоском листе зерно занимает единицы пикселей, и полный рельеф превращает
    // намазку в сетку. Амплитуда гаснет, когда зерно мельче ~6 device-px.
    // ПОЧЕМУ LEVEL_FIX. Рельеф и затенённые щели темнее намазки; без компенсации рис молча темнеет.
    // Приёмка прежняя: |Δ средней| <= 3.
    const lvl = RICE.level * k;                             // DC-компенсация яркости — нейтральная, без наклона в тепло
    let t = (hit - 0.5) * RICE.toneVar + (RICE.shade * lam * q + RICE.domeA * (dome - 0.62)) * k;
    if (hit > 0.955) t -= 9;                                // редкое зерно потемнее
    // МЕЛКАЯ ФАКТУРА ПОВЕРХНОСТИ. Разрезанное зерно не гладкое: срез крахмалистый, в мелких кавернах.
    // Без неё зерно читается как отлитая из пластика фасолина — и заодно теряет масштаб.
    if (RICE.grit > 0) t += RICE.grit * (hash(Math.floor(gx * RICE.gritF) + 313, Math.floor(gy * RICE.gritF) + 757) - 0.5) * dome * k;
    if (RICE.quant > 0) t = Math.round(t / RICE.quant) * RICE.quant;
    if (RICE.edge > 0) t -= RICE.edge * smooth(1 - RICE.edgeW, 1, q) * k;    // мягкий контур зерна
    if (RICE.rim > 0) t += RICE.rim * Math.pow(q, 6) * (1 - Math.max(0, lam)) * k;  // просвет на кромке
    // Блик: варёный рис глянцевый. Узкий, только на освещённом склоне ближе к макушке.
    const spec = Math.pow(Math.max(0, lam * q * RICE.specLam + dome * RICE.specDome), RICE.specP);
    let sAdd = RICE.specA * spec * k;
    if (RICE.spark > 0) {                                   // мокрое зерно бликует мелкой крошкой
      const fx = gx * RICE.sparkF, fy = gy * RICE.sparkF, ix = Math.floor(fx), iy = Math.floor(fy);
      const sp = hash(ix + 911, iy + 37);
      if (sp > RICE.sparkT) {
        const dx0 = fx - ix - 0.2 - 0.6 * hash(ix + 17, iy + 53), dy0 = fy - iy - 0.2 - 0.6 * hash(ix + 71, iy + 29);
        const dd = (dx0 * dx0 + dy0 * dy0) / 0.09;
        if (dd < 1) sAdd += RICE.spark * dome * k * (1 - dd) * (1 - dd);
      }
    }
    const gap = qraw > 1 ? Math.min(1, (qraw - 1) / RICE.gapW) : 0;
    const bc = ses ? RICE.sesRgb : c;
    // ЗЁРНА НЕ ОДНОГО ЦВЕТА. На фотографиях соседние рисинки заметно расходятся по теплу: одна отдаёт
    // в холодный белый, другая в кремовый. Один общий тон читается как пластик.
    const hv = RICE.hueVar ? RICE.hueVar * (fract(hit * 61.7) - 0.5) : 0;
    const topRgb = [bc[0] + t + lvl + sAdd + hv, bc[1] + t + lvl + sAdd, bc[2] + t * RICE.blueK + lvl + sAdd * RICE.specBlue - hv];
    if (gap <= 0) return topRgb;
    // Зерно из нижнего слоя: тот же расчёт тела и блика, но света меньше — оно в тени соседей, —
    // и к тёплому тону щели подмешано ровно столько, чтобы просвет читался щелью, а не вторым
    // рядом вровень с первым. DEEP_DARK подобран под ту же приёмку: |Δ средней яркости| <= 3.
    const qr2 = Math.sqrt(q2), q2c = Math.min(1, qr2);
    const dome2 = Math.sqrt(Math.max(0, 1 - q2c * q2c));
    const en2 = Math.hypot(ex2, ey2) || 1, lam2 = -(ex2 * LX + ey2 * LY) / en2;
    const t2 = (hit2 - 0.5) * RICE.toneVar + (RICE.shade * lam2 * q2c + RICE.domeA * (dome2 - 0.62) - RICE.deepDark) * k;
    const deep = mix([c[0] + t2 + lvl, c[1] + t2 + lvl, c[2] + t2 * RICE.blueK + lvl], RICE.gapRgb, RICE.gapMix);
    return mix(topRgb, deep, Math.min(RICE.gapMax, gap * RICE.gapK) * k);
  }
  const t = (hash(Math.floor(gx * 2), Math.floor(gy * 2)) - 0.5) * 4;     // крем и соус — мелкая рябь
  return [c[0] + t, c[1] + t, c[2] + t];
}
function wrapperColor(px, py, b) {
  const c = b.wrapperRgb, n = hash(px, py + 999);
  let t = (n - 0.5) * 8;
  return [c[0] + t, c[1] + t, c[2] + t];
}
function patchColor(m, px, py) {
  const { d, lu, lz, lv } = m, c = d.rgb;
  const dd = Math.hypot(lu * 2, lz * 2 - 1);
  switch (d.tex) {
    case 'salmon': { const s = fract(lu * 5.5 + lz * 0.7 + m.p.phase * 0.3); return mix(c, [255, 246, 236], s < 0.13 ? 0.55 : 0); }
    case 'cucumber': { if (dd > 0.84) return [86, 138, 60]; if (dd < 0.35 && hash(px, py) > 0.93) return [196, 200, 146]; return mix([214, 232, 178], c, smooth(0.2, 0.84, dd)); }
    case 'tamago': return mix(c, [200, 150, 50], fract(lz * 3.5) < 0.12 ? 0.18 : 0);
    // Краб-палочка: белые волокна сурими вдоль, красная плёнка по ОДНОЙ стороне.
    case 'kanikama': {
      if (lz > 0.86) return [212, 78, 60];
      const s = fract(lu * 7.5 + m.p.phase * 0.4);
      return mix(c, [255, 253, 248], s < 0.16 ? 0.45 : 0);
    }
    // НАРУТО: спираль рисуется ФАКТУРОЙ, а не намоткой ролла. Розовое и белое чередуются по
    // углу со сдвигом по радиусу — это и есть спираль Архимеда в плоскости среза самого куска.
    // Единственное место в модели, где узор живёт ВНУТРИ материала: обычный кусок однотонен,
    // а у 鳴門巻き 「小口に渦巻き模様が見られるのが特徴」.
    case 'naruto': {
      if (dd > 0.93) return [238, 230, 216];                       // ободок камабоко ровный
      const ang = Math.atan2(lz * 2 - 1, lu * 2) / TAU;            // −0,5…0,5
      return fract(ang + dd * NARUTO_TURNS + m.p.phase * 0.15) < 0.5
        ? [246, 244, 238] : [232, 118, 130];
    }
    case 'avocado': return mix([226, 224, 140], [104, 150, 60], smooth(0.15, 1, dd));
    case 'shrimp': return fract(lu * 3 + lv * 2 + 0.2) < 0.45 ? [250, 236, 224] : c;
    case 'gloss': return mix(c, [255, 255, 255], lz > 0.72 ? 0.25 : 0);
    // Разрез целой ягоды: бледная сердцевина (узкая, не половина ягоды), от неё радиальные
    // белые прожилки к мякоти, семечки — только по самой кромке, они снаружи, а не внутри.
    case 'strawberry': {
      if (dd > 0.86 && hash(px, py) > 0.9) return [248, 230, 120];            // семечки на кожице
      const ang = Math.atan2(lz * 2 - 1, lu * 2);
      // прожилки живут в средней зоне: у центра гаснут (иначе сходятся в звезду), у кромки тоже
      const vein = (fract(ang / TAU * 9 + hash(px >> 3, py >> 3) * 0.15) < 0.26 ? 1 : 0)
                 * smooth(0.18, 0.42, dd) * (1 - smooth(0.62, 0.9, dd));
      const core = 1 - smooth(0.04, 0.3, dd);                                  // сердцевина мягкая, не точка
      const pale = Math.min(0.62, core * 0.62 + vein * 0.3);
      return mix(c, [252, 214, 206], pale);                                    // бледно-розовый, не белый
    }
    case 'kiwi': { if (dd > 0.92) return [110, 90, 60]; if (dd > 0.38 && dd < 0.56 && hash(px, py) > 0.85) return [30, 25, 20]; return mix([236, 240, 190], c, smooth(0.1, 0.7, dd)); }
    // ребро ломтика ягоды: мякоть, бледная сердцевина посередине, семечки крапинами у самых краёв
    case 'berryEdge': { if (Math.abs(lu) > 0.44 && hash(px, py) > 0.72) return [248, 230, 120];
      const core = 1 - Math.min(1, Math.abs(lu) * 2.6);
      return mix(c, [252, 214, 206], core * 0.5); }
    // ребро ломтика киви: тёмная кожица по краям, светлая сердцевина посередине, редкие семечки
    case 'kiwiEdge': { if (Math.abs(lu) > 0.44) return [120, 100, 62]; const core = 1 - Math.min(1, Math.abs(lu) * 3.2);
      if (core > 0.55 && hash(px, py) > 0.93) return [244, 246, 214];
      return mix(c, [232, 240, 186], core * 0.75); }
    case 'banana': { if (dd > 0.9) return [226, 208, 140];                       // тонкая шкурка-кромка
      const seeds = dd < 0.3 && hash(px >> 1, py >> 1) > 0.86;
      return seeds ? [148, 120, 78] : mix([252, 244, 208], c, smooth(0.1, 0.95, dd)); }
    case 'mango': return mix(c, [255, 214, 120], fract(lu * 4 + lz) < 0.2 ? 0.25 : 0);
    case 'nut': return mix([220, 180, 120], c, dd);
    case 'cheese': { if (hash(px >> 1, py >> 1) > 0.93) return [236, 214, 130]; return mix(c, [255, 240, 170], lz > 0.75 ? 0.2 : 0); }
    case 'tomato': { if (dd < 0.55 && hash(px, py) > 0.9) return [250, 230, 150]; return mix([246, 130, 110], c, smooth(0.2, 0.9, dd)); }
    case 'pepper': return dd > 0.8 ? [150, 30, 20] : mix([240, 90, 70], c, dd);
    case 'ham': { if (hash(px >> 1, py) > 0.94) return [250, 235, 230]; return c; }
    case 'lettuce': return fract(lu * 6 + m.p.phase) < 0.12 ? [214, 236, 170] : c;
    case 'dill': { const n = hash(px, py); return n > 0.7 ? [70, 110, 50] : n > 0.4 ? [190, 205, 160] : [230, 232, 212]; }
    case 'rice': { const n1 = hash(px >> 1, py >> 1), n2 = hash(px >> 2, (py >> 2) + 77); let t = (n1 - 0.5) * 10 + (n2 - 0.5) * 16; if (n1 > 0.965) t -= 24; return [c[0] + t, c[1] + t, c[2] + t * 0.6]; }
    default: return c;
  }
}

