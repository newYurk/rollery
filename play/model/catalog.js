const R0 = 0.25;   // радиус сердцевины
// Длина листа. Лист — физический продукт с известным размером (лист нори 19x21 см, лаваш, противень),
// поэтому если у базы задан sheetCm — он и есть источник, а число витков из него ВЫВОДИТСЯ.
// Обратный порядок (витки → длина) остаётся запасным для баз без замера и опирается на угаданный turns,
// из-за чего ошибка в толщине листа w молча уезжала в длину листа. См. sim/KINEMATICS.md.
const U_MM = 5;    // одна единица модели = 5 мм
function turnsFor(L, P0) { // сколько витков даст лист длины L при шаге P0 (спираль Архимеда, обратная sheetLen)
  return (Math.sqrt(R0 * R0 + 2 * P0 * L / TAU) - R0) / P0;
}
for (const k in BASES) {
  const b = BASES[k], P0 = b.T + b.w;
  if (b.sheetCm) { b.L = b.sheetCm * 10 / U_MM; b.turns = turnsFor(b.L, P0); }
  else { const th = TAU * b.turns; b.L = R0 * th + P0 * th * th / (2 * TAU); }
}
