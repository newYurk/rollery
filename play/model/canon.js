// футомаки: 「не закрыто: おぼろ」.
//
// Граница проходит не по «краска или тело», а по другому вопросу: **это добавленный продукт
// или это цвет самого риса?** Дэмбу и майо — продукты, их кладут. Крашеный рис — тот же рис,
// просто окрашенный (в источниках его и делают подмешиванием: 「酢飯に混ぜ込んで」).
// Нори-патч — обёртка, а не начинка.
const CANON_NOT_A_FILLING = new Set(['nori', 'ricePink', 'riceYellow', 'riceGreen', 'riceBlack']);
function canonSummary(baseKey, list) {
  const тела = (list || []).filter(p => ING[p.kind] && !CANON_NOT_A_FILLING.has(p.kind));
  const виды = [...new Set(тела.map(p => p.kind))];
  return {
    база: baseKey,
    тела, виды,
    ролей: Object.entries(CANON_ROLES)
      .filter(([, kinds]) => kinds.some(k => виды.includes(k))).map(([r]) => r),
    // средняя позиция вдоль листа у рассыпчатых и у держащих форму
    uРассып: сред(тела.filter(p => CANON_CRUMBLY.has(p.kind)).map(p => p.u)),
    uТвёрд:  сред(тела.filter(p => CANON_FIRM.has(p.kind)).map(p => p.u)),
    // ШИРИНА НАБОРА В ДОЛЯХ ПОСТЕЛИ — для правила четверти (id quarter-of-bed).
    // Меряем от края первой начинки до края последней: источник говорит про 一辺 — сторону
    // набора, а не про сумму ширин, и зазоры между кусками в неё входят.
    // ⚑ КРАСКА В СТОРОНУ НАБОРА НЕ ВХОДИТ (01.09, #129). У присыпки (おぼろ, wU 6 = 30 мм)
    // стороны нет — её сыплют рядом со связкой или на неё, а не кладут бруском. Пока она
    // считалась, ряд из четырёх кусков (0,275 постели) с дэмбу за ним давал 0,44 и «нарушал»
    // правило, которое про него не написано.
    доляНабора: (() => {
      const куски = тела.filter(p => !ING[p.kind].paint);
      if (!куски.length) return null;
      const b = BASES[baseKey]; if (!b) return null;
      const L = b.sheetCm * 10 / U_MM;
      const s0 = b.spreadStart === undefined ? 0.048 : b.spreadStart;
      const постель = (b.spreadEnd - s0) * L; if (постель <= 0) return null;
      let гр0 = Infinity, гр1 = -Infinity;
      for (const p of куски) {
        const w2 = (p.wU ?? ING[p.kind].wU) / 2;
        гр0 = Math.min(гр0, p.u * L - w2); гр1 = Math.max(гр1, p.u * L + w2);
      }
      return (гр1 - гр0) / постель;
    })(),
  };
}
