// Проверить раскладку. Возвращает { нарушено, соблюдено, неприменимо, непроверяемо } —
// строками, готовыми к печати и к показу игроку.
function canonCheck(baseKey, list) {
  const s = canonSummary(baseKey, list);
  const out = { нарушено: [], соблюдено: [], неприменимо: [], непроверяемо: [], сводка: s };
  for (const r of CANON) {
    if (r.базы && !r.базы.includes(baseKey)) { out.неприменимо.push(r.id); continue; }
    if (!r.проверка) { out.непроверяемо.push(`${r.что} — мерки пока нет`); continue; }
    if (r.проверка(s)) out.соблюдено.push(r.что);
    else {
      const чего = r.чегоНеХватает ? ' — не закрыто: ' + r.чегоНеХватает(s).join(', ') : '';
      out.нарушено.push({ id: r.id, что: r.что + чего, подсказка: r.подсказка, источник: r.источник });
    }
  }
  return out;
}
