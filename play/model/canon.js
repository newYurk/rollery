// Общая укладка ряда: куски встык от начала, краска — за рядом (см. правило crumbly-far).
function рядИз(виды, краска) {
  const b = BASES.futo, g = { T: b.T, L: b.L, w: b.w };   // паспорт футомаки, без S.turns
  const list = [];
  let u = CANON_ROW_START, phase = 0.7;
  for (const kind of виды) {
    const du = dims({ kind }, g).du;
    list.push({ kind, u: u + du / 2, v: 0.5, z0: 0, z1: 0, phase });
    u += du; phase += 1.2;
  }
  if (краска) {
    const dк = dims({ kind: краска }, g).du;
    list.push({ kind: краска, u: u + dк / 2, v: 0.5, z0: 0, z1: 0, phase });
  }
  return list;
}
