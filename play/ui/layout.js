// Подпись под чипом шире самого чипа («Креветка» ≈ 52 px при чипе 44), а полоса чипов
// отсекается по своей рамке. Отсюда отступ: на сколько содержимое полосы надо отодвинуть
// от края, чтобы крайняя подпись целиком осталась внутри.
// ПОДПИСЬ ЧИПА НЕ ШИРЕ СВОЕЙ ЯЧЕЙКИ (#157, 02.09).
//
// Подпись рисовалась ПОЛНЫМ именем по центру чипа, а ячейка — это чип плюс зазор, 52 px.
// Пока имена были короткие, никто не замечал; с приходом краб-палочки (78 px при ячейке 52)
// три подписи нижнего ряда слились в «АнагоКраб-палочкаНаруто».
//
// Вторая половина той же беды тише и дороже: отступ резервировался по САМОМУ ШИРОКОМУ имени,
// и одно длинное слово отнимало у ленты 36 px — то есть число чипов в ряду решало одно имя.
//
// Теперь имя для чипа даёт ОДНА функция, и её же спрашивает расчёт отступа: разойтись им
// нечем. Порядок уступок — короткое имя из каталога (`short`), потом обрезка с многоточием.
function chipLabel(kind, maxW) {
  const d = ING[kind]; ctx.font = font(11);
  if (ctx.measureText(d.name).width <= maxW) return d.name;
  if (d.short && ctx.measureText(d.short).width <= maxW) return d.short;
  let t = d.short || d.name;
  while (t.length > 1 && ctx.measureText(t + '…').width > maxW) t = t.slice(0, -1);
  return t + '…';
}
function chipLabelPad(size, list) {
  ctx.font = font(11);
  const ячейка = size + 8;                       // чип плюс зазор: столько места у подписи есть
  let w = 0; for (const k of list) w = Math.max(w, ctx.measureText(chipLabel(k, ячейка)).width);
  return Math.max(0, Math.ceil((w - size) / 2));
}
