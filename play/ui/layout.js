//
// ⚠ ЛЕСТНИЦА ДОХОДИТ ДО КОНЦА, И ПОСЛЕДНЯЯ СТУПЕНЬ — АРИФМЕТИЧЕСКАЯ (17.09, замечание
// проверки). Первая редакция на TAB_W_MIN останавливалась и возвращала ленту КАК ЕСТЬ, даже
// если та в полосу не влезла: на 320×568 у узумаки полоса палитры 149,1 px (она привязана к
// узкой циновке спирали), а шесть вкладок по 26 с зазором 4 требуют 176 — и ряд уезжал за
// ЛЕВЫЙ край полосы на 26,9 px. Дальше ступени такие: имени нет — значит вкладкам достаётся
// ВСЯ полоса, и они снова идут от 32 (на 375×667 у узумаки это 28 вместо 26); потом сжимается
// зазор (−20 px на шести вкладках); последняя ступень — полоса делится на n без зазора:
// floor(w / n) · n ≤ w тождественно, то есть выйти за полосу уже нельзя ПО ПОСТРОЕНИЮ, а не по
// доброй воле. Ниже 26 px вкладка мельче нормы, и сторож говорит об этом в мягком канале с
// числом (на 320×568 у узумаки выходит 24) — мелкая вкладка внутри полосы честнее нормальной
// снаружи, но молчать об этом нельзя.
//
// ⚠ ЛЕСТНИЦА МЕРИТ САМОЕ ДЛИННОЕ ИМЯ СРЕДИ ГРУПП, А НЕ ИМЯ ОТКРЫТОЙ. Иначе ширина вкладки
// зависела бы от того, какую страницу листаешь: на узкой полосе «Рыба» влезала при 32, а
// «Фрукты и сладкое» требовала 26 — и ряд вкладок ездил под пальцем на каждом перелистывании,
// то есть цель касания меняла место у того, кто на неё смотрит. Полоса считается ОДИН РАЗ на
// базу: либо полные имена у всех, либо короткие у всех. Поэтому в записи есть `form` — какой
// ступенью взято имя: сторож сверяет ЕЁ и сам текст, а не только ширину (в браузере шрифт
// настоящий, и подмена «Краски и рельеф» на «Краски» ширину ленты не меняет ни на пиксель).
const TAB_H = 28, TAB_GAP = 4, TAB_W = 32, TAB_W_MIN = 26;
function palStrip(x, y, w, groups, cur) {
  if (!groups || groups.length < 2) return null;    // одна группа — листать нечего, вкладок нет
  const g = groups[cur] || groups[0], n = groups.length;
  ctx.font = font(12);
  const мера = k => groups.reduce((m, q) => Math.max(m, ctx.measureText(q[k] || q.name).width), 0);
  const полные = мера('name'), краткие = мера('short');
  const лента = (tw, gap) => n * tw + (n - 1) * gap;
  const готово = (tw, gap, form) => ({
    x, y, w, h: TAB_H, tabW: tw, gap, tabsX: x + w - лента(tw, gap), tabsW: лента(tw, gap), n, form,
    label: form === 'name' ? g.name : form === 'short' ? (g.short || g.name) : '',
  });
  for (let tw = TAB_W; tw >= TAB_W_MIN; tw -= 2) {
    const свободно = w - лента(tw, TAB_GAP) - 10;   // 10 px — зазор между именем и вкладками
    if (свободно >= полные) return готово(tw, TAB_GAP, 'name');
    if (свободно >= краткие) return готово(tw, TAB_GAP, 'short');
  }
  for (let tw = TAB_W; tw >= TAB_W_MIN; tw -= 2)    // имени нет: полоса целиком отдана вкладкам
    if (лента(tw, TAB_GAP) <= w) return готово(tw, TAB_GAP, 'none');
  for (let gap = TAB_GAP - 1; gap >= 0; gap--)      // не влезли и так: сжимаем зазор
    if (лента(TAB_W_MIN, gap) <= w) return готово(TAB_W_MIN, gap, 'none');
  return готово(Math.max(1, Math.floor(w / n)), 0, 'none');
}
// Сколько высоты полоса вкладок отнимает у листа. Считается ДО раскладки: у базы с одной
// группой (фруктовая) полосы нет, и лист не платит за неё ни пикселя.
const palStripH = () => (uiGroups().length > 1 ? TAB_H + 6 : 0);
// ПОЛ ЛИСТА — ФОРМУЛА, А НЕ ЧИСЛО. На листе кладут начинки пальцем: hitPatch расширяет патч
// на HIT_PAD с каждой стороны, значит экранная высота патча должна быть ≥ TOUCH − 2·HIT_PAD.
// Самая узкая начинка палитры занимает wU/L высоты. Отсюда пол = (TOUCH − 2·HIT_PAD) · L / wU.
// ⚠ ШИРИНУ НАЧИНКИ ЧИСЛОМ ЗДЕСЬ НЕ ПИСАТЬ. Каталог меняется (лосось 1,6, майо 0,8), и любое
// вписанное число разойдётся с ним молча, завысив обещанную цель касания. Спрашиваем каталог.
// ⚠ И САМ ПОЛ ЧИСЛОМ НЕ ПИСАТЬ. Он зависит от длины листа, а она у баз разная: вписанное
// число устареет вдвое при первой же смене базы и молча срежет цель касания.
// Длина берётся у sheetLen(): в «Пазле» её меняет уровень, и лист там действительно длиннее.
const HIT_PAD = 14;   // ореол вокруг патча, px с каждой стороны (см. hitPatch)
const TOUCH = 44;     // норма цели касания
// ⚠ ТИПОВАЯ, А НЕ САМАЯ УЗКАЯ — и первая редакция этой правки ошиблась именно здесь.
// Взять минимум по палитре кажется безопаснее, но майо (`паста`, wU 0,8) в четыре раза уже
// тамаго: пол по ней задирается так, что ни одна раскладка не проходит, и сторож загорается
// красным тридцать два раза на том, что УЖЕ заведено отдельной задачей (#47, узкие начинки).
// Красный сторож, горящий месяцами, перестают читать — под ним прячется настоящая поломка.
// Поэтому пол считается по МЕДИАННОЙ начинке (та самая «обычная», которую прежде писали
// числом 2), а узкие остаются в мягком канале с номером задачи.
// Краска и паста в расчёт не идут: их не кладут пальцем как кусок.
const typicalU = () => {
  const b = B();
  const ws = (b.ingredients || [])
    .filter(k => ING[k] && !ING[k].paint && ING[k].cut !== 'паста')
    .map(k => ING[k].wU).sort((x, y) => x - y);
  return ws.length ? ws[ws.length >> 1] : 2;
};
const sheetFloor = () => (TOUCH - 2 * HIT_PAD) * sheetLen(B()) / typicalU();
// ОТБОР РАСКЛАДОК ДВУХСТУПЕНЧАТЫЙ, и это не украшение. Чистый максимум площади ошибается:
// два ряда чипов с прокруткой дают лист выше, чем три ряда без неё, и правило само отдало бы
// видимость палитры за пиксели листа. Порядок такой:
//   1) жёсткий фильтр — лист не ниже пола пальца (ниже него класть начинки просто нечем);
//   2) среди прошедших — БОЛЬШЕ ВИДНЫХ ЧИПОВ (сколько начинок помещается без прокрутки);
//   3) при равенстве — больше ПОЛЕЗНОЙ площади листа (то, что закрывает накладка, вычтено).
// Если пол не берёт никто — берём самый высокий лист: это единственное, что там ещё улучшишь.
// ⚠ На второй ступени стояло «больше РЯДОВ» — и это ошибка, замеренная на 1440x900: там лист
// шириной 1240 берёт все двадцать чипов в ОДИН ряд без прокрутки, а боковая колонка сужает
// его до 896 и требует двух рядов. По числу рядов выигрывала колонка, и лист падал с 58,7 %
// до 37,6 % ради ряда, который ничего не показывал сверх первого. Считать надо видимость,
// а не строки: два ряда по шесть лучше одного ряда по шесть, но не лучше одного ряда по двадцать.
// Пол пальца — это минимум ВДОЛЬ ОСИ СКРУТКИ u (sheetFloor считается из длины листа), поэтому
// ранжируем по alongU, а не по sh: сегодня они совпадают (u лежит по вертикали), но после
// поворота листа (#23) u уйдёт в ширину, и «самый высокий лист» стал бы отбором не по той оси.
const betterFit = floor => (a, c) => {
  const rank = x => (x.alongU >= floor ? [1, x.vis, x.area] : [0, 0, x.alongU]);
  const ra = rank(a), rc = rank(c);
  for (let i = 0; i < 3; i++) if (Math.abs(rc[i] - ra[i]) > 0.5) return rc[i] > ra[i] ? c : a;
  return a;
};
// ── ОКОШКО ЖИВОГО СРЕЗА НА ЛИСТЕ: ОДНА ФУНКЦИЯ НА РАСКЛАДЧИКА И НА РИСОВАНИЕ (17.09) ─────────
//
// Раскладчик выбирает между полосой над листом и окошком на листе по ПОЛЕЗНОЙ площади: то, что
// окошко закрывает, вычитается. Закрытое он считал числом 102 × 102 — окошко было таким, пока
// рисовалось диском 88 px с подложкой. 31.08 оно стало отладочным окном владельца в 62 % меньшей
// стороны листа, а число в раскладчике осталось: на футомаки 393 × 852 рисовался диск 236 px,
// то есть закрыто было в 5,4 раза больше, чем думал раскладчик, и накладка выигрывала там, где
// прятала треть листа. Та же ошибка, что «раскладчик оптимизировал пустоту» ниже: решение
// принималось по величине, которую никто не рисует.
//
// Теперь размер окошка знает только эта функция; её зовут и отбор раскладки (layout, ветка P и
// T/D), и рисование (overlayGeom в render/screens.js). Координаты — от угла листа (0, 0).
// `закрыто` — квадрат, в который вписан диск (у пазла — полоса целей): класть под ним можно,
// но не видно, что кладёшь.
function overlayBox(w, h, pz) {
  if (pz) {
    const k = pz.vs.length, fs = Math.min(56, (w - 16 - 6 * (k - 1)) / k);
    return { fs, x0: w / 2 - ((k - 1) * (fs + 6)) / 2, y: fs / 2 + 8, низ: 4 + fs + 8, закрыто: w * (fs + 16) };
  }
  const fs = Math.round(Math.min(w, h) * 0.62), поле = 6, дШир = fs + 2 * поле, поля = 10;
  return { fs, дШир, x: w - дШир / 2 - поля, y: дШир / 2 + поля, низ: дШир + поля, закрыто: дШир * дШир };
}
// ── ЖИВОЙ СРЕЗ ПОЛОСОЙ — ВЕРХНЯЯ ЧАСТЬ ЦИНОВКИ (17.09, просьба владельца) ────────────────────
//
// Владелец со снимка iPhone 15 Pro: срез «очень неудачно закрывает очень большой кусок листа», а
// прежняя полоса — карточка со срезом посередине и подписью справа — «выносят очень некрасиво.
// Уж если выносить, то выносить прям справа и подписывать текстом». Отсюда устройство:
//   · полоса — не отдельная табличка, а та же циновка, продолженная вверх: одна заливка, одни
//     прутья, края совпадают с краями циновки по построению (x и ширина берутся у ручки);
//   · срез прижат к правому краю — к краю нори, по которому стоит и лист;
//   · слева колонка текста о состоянии ролла (screens.js, bandFacts) — то, что раньше висело
//     надписями поверх листа;
//   · все поля — одно число ПОЛЕ: сколько дерева видно между краем циновки и нори. Сверху, справа,
//     до листа и до колонки — одно и то же, поэтому ни один отступ не выглядит случайным.
const РАМКА = 18;                 // рамка циновки вокруг листа: ручка шире листа на 18 с каждой стороны
const КРАЙ_НОРИ = 5;              // нори рисуется шире листа на 5 px с каждой стороны (drawLay)
const ПОЛЕ = РАМКА - КРАЙ_НОРИ;   // 13 px видимого дерева
// Срез в полосе: 116 — прежний размер (его же берёт экран ролла), 84 — клетка цели пазла. Между
// ними полоса берёт ровно тот запас, что остаётся над листом, и лист за неё не платит; ниже 84
// не сжимается — дальше честнее окошко или меньший лист, и это решает отбор по площади.
const СРЕЗ_MAX = 116, СРЕЗ_MIN = 84;
// Уже этого колонку текста не заводим: заголовок «живой срез» кеглем 11 — 66 px (замер в браузере),
// и более узкая колонка не держала бы даже его.
const КОЛОНКА_MIN = 72;
// Геометрия полосы по готовым листу и ручке (ветка P). h — высота полосы над верхней рамкой, n —
// сколько срезов в ряду (у пазла — цели). Всё, что рисуется в полосе, и всё, что меряет сторож,
// берётся отсюда: отдельной формулы ни у рисования, ни у проверки нет.
function bandGeom(h, n) {
  const s = L.sheet, hd = L.handle;
  const верх = s.y - РАМКА - h;                          // верх циновки: полоса — её верхняя часть
  const лев = s.x - КРАЙ_НОРИ, прав = s.x + s.w + КРАЙ_НОРИ;   // края нори: по ним стоит и лист
  const fs = Math.min(h - ПОЛЕ, (прав - лев - 8 * (n - 1)) / n);
  const cy = верх + ПОЛЕ + (h - ПОЛЕ) / 2;              // от поля над срезом до рамки над листом
  const cells = [];
  for (let i = 0; i < n; i++) cells.push({ x: прав - fs / 2 - (n - 1 - i) * (fs + 8), y: cy, size: fs });
  const колонкаП = cells[0].x - fs / 2 - ПОЛЕ;           // колонка кончается за полем до среза
  const col = колонкаП - лев >= КОЛОНКА_MIN ? { x: лев, y: верх + ПОЛЕ, w: колонкаП - лев, h: h - ПОЛЕ } : null;
  return { x: hd.x, y: верх, w: hd.w, h, fs, cells, col };
}
// Раскладка экрана. Режимы: P — телефон портрет, L — телефон альбом, T — планшет, D — широкий десктоп.
// Всё считается в рамке cw × ch внутри safe-area; лист — в приоритете, предпросмотр/цель — полосой, накладкой или в боковой колонке.
