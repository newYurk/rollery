// ВЫБОР НАЧИНКИ ПЕРЕЖИВАЕТ СМЕНУ БАЗЫ. Здесь стояло безусловное «первая начинка новой базы»
// в четырёх местах (смена базы, загрузка из альбома, пазл по ссылке, чтение сохранённого) —
// и выбор терялся даже когда начинка есть и у новой базы. Страница палитры при этом остаётся
// той же, если такая группа у новой базы есть; иначе открывается группа выбранной начинки.
function palSync() {
  const gs = uiGroups(); if (!gs.length) return;
  if (!gs.some(g => g.ings.indexOf(S.sel) >= 0)) S.sel = gs[0].ings[0];
  if (!gs.some(g => g.key === S.palGroup)) S.palGroup = gs[uiPalIndex()].key;
}
// Вкладка и жест меняют ТОЛЬКО страницу: выбранная начинка остаётся выбранной, даже когда
// уехала на другую страницу (сторож «П» это проверяет).
function palSet(key) {
  const gs = uiGroups();
  if (!gs.some(g => g.key === key) || S.palGroup === key) return false;
  S.palGroup = key; return true;
}
function palStep(d) {
  const gs = uiGroups(), i = uiPalIndex(), j = clamp(i + d, 0, gs.length - 1);
  if (j === i) return false;
  S.palGroup = gs[j].key; return true;
}

