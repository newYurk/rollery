const _палКеш = {};
function uiPalette() {
  const ключ = S.base + (FULL_UI ? '' : '|min');
  let п = _палКеш[ключ];
  if (!п) {
    const есть = B().ingredients, groups = [], flat = [];
    for (const g of ING_GROUPS) {
      const ings = g.ings.filter(k => есть.indexOf(k) >= 0 && (FULL_UI || MIN_ING.has(k)));
      if (!ings.length) continue;                       // пустая группа: её у этой базы нет
      groups.push({ key: g.key, name: g.name, short: g.short,
                    icon: ings.indexOf(g.icon) >= 0 ? g.icon : ings[0], ings });
      for (const k of ings) flat.push(k);
    }
    п = { groups, flat, max: groups.reduce((m, g) => Math.max(m, g.ings.length), 0) };
    _палКеш[ключ] = п;
  }
  return п;
}
