// спрятан на чужой странице.
function uiPalIndex() {
  const gs = uiGroups();
  let i = -1;
  for (let k = 0; k < gs.length; k++) if (gs[k].key === S.palGroup) { i = k; break; }
  if (i < 0) for (let k = 0; k < gs.length; k++) if (gs[k].ings.indexOf(S.sel) >= 0) { i = k; break; }
  return i < 0 ? 0 : i;
}
