// ⚠ РАЗМЕР — КАК ПОЛОЖЕН, БЕЗ ПРИЖИМА (`bounds(p, g, true)`): правило про то, куда кладут, а
// прижим случается потом, при скрутке, и от руки прошлого ролла зависеть не должен.
//
// Куда кусок девается: на БЛИЖАЙШЕЕ разрешённое место по u, вдоль ролла (v) не двигается.
// Текста нет (подсказки на экране раскладки нет, решение 02.09): отказ виден сам — кусок
// упирается в кромку риса, как раньше в край листа.
//
// ⚠ КУСОК ШИРЕ ВСЕЙ ГРЯДКИ. Места на рисе для него нет вовсе. Бывает только в пазле узумаки на
// двух витках (уровни 5 и 12; лист 36–53 мм, рис 29–45 мм): омлет-лист, киви, манго, банан,
// дэмбу — замер 17.09 по всем базам, виткам уровней и обёрткам. Что с ним делается:
//   · фишка такого куска ТУСКЛАЯ И НЕДОСТУПНАЯ (`chipFits`, drawChips) — выбрать её нельзя, а
//     выбранная прежде уходит на первую доступную (`selOnRice`). Так касание листа всегда что-то
//     кладёт: до 17.09 (замечание проверки) фишка выбиралась, а касание не давало ни куска, ни
//     звука, ни снимка — игра молча не отвечала. Тусклая, а не спрятанная: ряд не прыгает, и
//     видно, что кусок на этом листе есть, но не ложится (тот же приём, что у тусклой «Отменить»);
//   · обёртку, на которой лежащий кусок или цель пазла перестали бы помещаться, перебор
//     пропускает (`sheetTakes`, действие 'sheet');
//   · генератор такой кусок в цель не берёт;
//   · снимок истории с таким куском (снят на другой обёртке) возвращается без него (`histApply`);
//   · старый рецепт с витками (ссылка, альбом) открывается на листе, где помещается каждый его
//     кусок (`recipeTurns`, решение владельца 17.09); рецепт без витков — полный лист базы, там
//     помещается всё. Если места не нашлось бы и так, кусок встал бы в середину грядки.
function riceSpanU(g) {
  const P = spreadPre(g), A = edgeRagAmp() / gL(g);
  return { u0: P.s0 + A, u1: P.se - A };
}
// ⚑ ПОЛУШИРИНА СЛЕДА — ПО КОПИИ С u = 0, КАК В genTarget (17.09, замечание проверки #253).
// `bounds` даёт края как u ∓ h, и разность (u + h) − (u − h) на плавающей точке зависит от u в
// последнем разряде. Кусок, упёртый в кромку, повторный layU сдвигал на 1e-16: ссылка на цель
// пазла возвращала не тот бит (#236) — 63 цели из 28 800 (100 зёрен × 3 обёртки), и 1914 упоров
// из 64 962 меняли u при втором вызове. От u след не зависит, а при u = 0 разность точная, и
// layU(p, layU(p, u)) === layU(p, u) до бита.
function halfU(p, g) { const bb = bounds(Object.assign({}, p, { u: 0 }), g, true); return (bb.u1 - bb.u0) / 2; }
function layFits(p, g) {
  const r = riceSpanU(g);
  return 2 * halfU(p, g) <= r.u1 - r.u0;
}
function layU(p, u, g) {
  const hu = halfU(p, g), r = riceSpanU(g);
  const lo = r.u0 + hu, hi = r.u1 - hu;
  return lo > hi ? (r.u0 + r.u1) / 2 : clamp(u, lo, hi);
}
// Фишка доступна, если её кусок вообще помещается на рис текущего листа.
const chipFits = kind => !!ING[kind] && layFits({ kind, u: 0.5, v: 0.5 });
// Выбранная фишка перестала помещаться (лист стал короче: уровень пазла, обёртка) — выбор
// переходит на первую доступную в палитре, чтобы касание листа не пропадало молча.
function selOnRice() {
  if (chipFits(S.sel)) return;
  const k = uiIngredients().find(chipFits);
  if (k) S.sel = k;
}
// Кусок, оказавшийся на голом крае, сдвигаем на ближайшее место на рисе — прямо в самом
// списке. Отвечает, сколько кусков сдвинуто.
function layOnRice(list, g) {
  let n = 0;
  for (const p of list) {
    if (!ING[p.kind]) continue;                // снятая начинка: её отсеют свои фильтры, мерить нечем
    const u = layU(p, p.u, g); if (u !== p.u) { p.u = u; n++; }
  }
  return n;
}
// Правило спрашивает текущий лист (база, обёртка, витки). Чужой рецепт проверяется на своём
// листе: состояние подменяется на время вызова и возвращается, как в `withRecipe` альбома.
function withSheetOf(st, fn) {
  const keep = { base: S.base, wrap: S.wrap, turns: S.turns };
  S.base = st.base; S.wrap = (st.wrap && WRAPPERS[st.wrap]) ? st.wrap : null; S.turns = turnsOf(st.turns);
  try { return fn(); }
  finally { S.base = keep.base; S.wrap = keep.wrap; S.turns = keep.turns; }
}
// ⚑ ЛИСТ КОРОЧЕ НАЧИНКИ НЕ ПРИНИМАЕТСЯ (решение владельца 17.09, #253): «в ссылке-пазле меньше
// 2 витков не бывает, старая ссылка открывается с наименьшим допустимым листом — как с голым
// краем». Рецепт с витками (ссылка, запись альбома), сделанный до запрета, мог нести кусок шире
// всей грядки: генератор брал омлет-лист в узумаки на двух витках (лист 53 мм, рис 45, омлет 50).
// Проверка 17.09: 288 таких целей уровня 12 из 288 открывались с омлетом на голом, фишка тусклая,
// засчитано 9. Поэтому витки рецепта — не меньше 2 и не меньше записанных, и к ним добавляется по
// целому витку, пока на рис листа (база и обёртка рецепта) не ляжет каждый кусок. По целому —
// листы игры считаются витками уровня (2, 3, 4), и подпись «N вит.» дробей не знает. Замер 17.09
// (runs/continuation/task11-253/fix3/probe/fitgrid.txt): не помещается что-то только у узумаки на
// 2 витках (омлет-лист и киви; на нори и сое ещё манго, банан, дэмбу; на рисовой бумаге — манго),
// а с 3 витков на любой базе и обёртке ложится всё — старая цель с омлет-листом открывается на 3.
// Рецепт, где всё помещается, не меняется ни в витках, ни в битах. Рецепт без витков — полный
// лист базы, там помещается всё.
// ⚑ НОЛЬ ВИТКОВ — ЭТО КОРОТКИЙ ЛИСТ, А НЕ «ЛИСТ БАЗЫ» (сведение при слиянии 17.09, #36/#253).
// Здесь стояло `if (!t) return t`, и ноль уходил наружу нулём: `sheetLen` читает его как полный
// лист базы. У хосомаки это почти совпадает (105,0 мм против 104,9 на двух витках), а у урамаки
// два витка — 113,0 мм, то есть «лист базы» КОРОЧЕ наименьшего допустимого, и правило владельца
// «лист короче 2 витков не принимается» на нуле не исполнялось. `null` («витков нет») от нуля
// отличается: его и оставляем как есть, а числовой ноль поднимается до порога наравне с 0,5 и 1,5.
// Сторож — §7г в checks.js, набор витков начинается с 0 именно поэтому.
const RECIPE_TURNS_MIN = 2;
function recipeTurns(st, list) {
  let t = turnsOf(st.turns);
  if (t === null) return t;
  t = Math.max(t, RECIPE_TURNS_MIN);
  const fits = tt => withSheetOf({ base: st.base, wrap: st.wrap, turns: tt },
    () => list.every(p => !ING[p.kind] || layFits(p)));
  for (let k = 0; k < 8 && !fits(t); k++) t = Math.floor(t) + 1;
  return t;
}
// ⚑ КРУГ ОБЁРТОК ВОЗВРАЩАЕТ РАСКЛАДКУ И ЦЕЛЬ ДО БИТА (#253, 17.09, замечание проверки). При
// заданных витках обёртка меняет длину листа, и кусок у кромки встаёт на рис (layRefit). Прежде
// сдвиг копился: игрок перебирал обёртки, возвращался к исходной, а куски у кромок стояли не там,
// где он их положил, — 7680 раскладок из 9600 (два тамаго у кромок; 6 баз × 16 уровней × 5
// обёрток × 20 зёрен), до 4,9 мм; цель пазла менялась в 700 из 9600, до 8,76 мм, и игрок,
// собравший её до круга, сравнивался уже с другой.
//   · Кусок раскладки помнит u, с которым его положили (`layAnchor`), и на каждом листе встаёт
//     по правилу от этого u, а не от уже сдвинутого. На исходном листе это прежнее место до бита:
//     layU идемпотентен. Память слабая (WeakMap) — в сохранение, историю и ссылку не попадает; кусок,
//     который игрок сдвинул сам (u уже не тот, что поставила подгонка), запоминается заново.
//     Снимок истории — новые объекты без памяти: после отмены место считается от u снимка.
//   · Цель пазла игрок не двигает, поэтому она выводится заново из сгенерированной (`target0`)
//     на каждом листе.
// Смена базы зовёт layOnRice сама: у каждой базы своя раскладка, а пазл начинается заново.
const layAnchor = new WeakMap();
function layRefitList(list) {
  for (const p of list) {
    if (!ING[p.kind]) continue;
    const a = layAnchor.get(p), u0 = a && a.at === p.u ? a.u : p.u;
    p.u = layU(p, u0);
    layAnchor.set(p, { u: u0, at: p.u });
  }
}
function layRefit() {
  layRefitList(patches());
  const pz = S.puzzle;
  if (pz && pz.target0) { const t = pz.target0.map(p => Object.assign({}, p)); layOnRice(t); pz.target = t; }
  else if (pz && pz.target) layOnRice(pz.target);
}
// Ляжет ли то, что уже есть (раскладка и цель пазла), на рис листа с обёрткой `wrap`.
function sheetTakes(wrap) {
  const fits = p => !ING[p.kind] || layFits(p);
  const цель = S.puzzle && (S.puzzle.target0 || S.puzzle.target);
  return withSheetOf({ base: S.base, wrap, turns: S.turns },
    () => patches().every(fits) && !(цель && !цель.every(fits)));
}

function load() {
  try {
    const m = JSON.parse(localStorage.getItem('rollery.model.v2') || 'null');
    if (m && m.lists) { S.base = m.base in BASES ? m.base : 'hoso'; S.lists = m.lists; S.wrap = (m.wrap && WRAPPERS[m.wrap]) ? m.wrap : null; }
    for (const k in BASES) if (!S.lists[k]) S.lists[k] = [];
    // ⚑ ЖИВОЙ СРЕЗ ВКЛЮЧЁН ПО УМОЛЧАНИЮ. Он и есть обратная связь игры: узор
    // следует из раскладки, и без него первый игрок не видит связи между тем,
    // что кладёт, и тем, что получит. Раньше стоило места — предпросмотр
    // ложился накладкой поверх листа; после правки раскладчика он занимает
    // пустоту над листом и лист не уменьшает. Глаз в панели выключает за тап,
    // и выбор запоминается: null (первый запуск) — да, '0' — нет.
    { const pv = localStorage.getItem('rollery.preview'); S.preview = pv === null ? true : pv === '1'; }
    // ⚑ ЗВУК ВКЛЮЧЁН ВСЕГДА (17.09, решение владельца): кнопки больше нет, и сохранённое
    // «выключено» заперло бы игрока в тишине без выхода. Молчание — дело телефона: беззвучный
    // режим и громкость (audioSession 'ambient' в audio.js). Старый ключ убираем.
    S.mute = false; localStorage.removeItem('rollery.mute');
    S.shape = localStorage.getItem('rollery.shape') || 'round';
    S.cutsTotal = +(localStorage.getItem('rollery.cuts') || 0);
    S.album = JSON.parse(localStorage.getItem('rollery.album') || '[]');
    if (!Array.isArray(S.album)) S.album = [];
  } catch (e) {}
  // Минимальный стенд: сохранённая база/начинка может быть спрятана (#96) — раскладки при этом
  // НЕ трогаем, они переживут и вернутся с ?full.
  if (!uiBases().includes(S.base)) S.base = 'futo';
  palSync();
  for (const b in S.lists) S.lists[b] = S.lists[b].filter(p => ING[p.kind]);
  // Сохранённое до 17.09 могло лежать на голом крае — сдвигаем, у каждой базы по её постели (#253).
  for (const b in S.lists) if (BASES[b]) withSheetOf({ base: b, wrap: S.wrap, turns: S.turns }, () => layOnRice(S.lists[b]));
}
function save() {
  try {
    localStorage.setItem('rollery.model.v2', JSON.stringify({ base: S.base, lists: S.lists, wrap: S.wrap }));
    localStorage.setItem('rollery.preview', S.preview ? '1' : '0');
    localStorage.setItem('rollery.shape', S.shape);
    localStorage.setItem('rollery.cuts', String(S.cutsTotal));
  } catch (e) {}
}

