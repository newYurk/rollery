// поплатимся какими-нибудь вариантами пазлов, но лучше так.» Откуда вопрос (#249): кусок на голой
// полосе ближнего или дальнего края вставал в кольце клином через весь рис — кольцо строится по
// отрезку листа, где профиль не пуст, и кусок на голой нори этот отрезок растягивал.
//
// ПРАВИЛО: след куска вдоль u — `bounds` (с волной у пасты и поворотом у старых сохранений) —
// лежит на рисе В КАЖДОМ срезе ролла. Касается всего, что кладёт игрок: кусков, листа нори,
// краски, грядки и ложбинки. Правила #57 (2 см от кромки, не за середину) остаются подсказкой:
// запрет только про голую нори.
//
// ГДЕ РИС — знает модель, а не этот файл: кромки берутся из `spreadPre` без среза (номинальные
// spreadStart/spreadEnd базы), и к ним добавляется размах рваной кромки `edgeRagAmp` (#24) —
// кромка гуляет вдоль ролла на ползерна, 1,75 мм, и след, дотянутый до номинальной кромки, в
// части срезов лёг бы на нори. Окно по базам (замер 17.09, runs/continuation/task11-253):
//     хосомаки           окно 0,065…0,863 листа   голые поля 5,0 и 12,6 мм, плюс 1,75 мм кромки
//     тюмаки                   0,059…0,869                    7,7 и 19,2
//     футомаки, фруктовые      0,056…0,882                   10,1 и 23,1
//     урамаки                  0,065…0,983                    5,0 и 0 — своя постель, рис до
//                                                             дальнего края (#124)
//     узумаки                  0,052…0,946                   20,2 и 21,0 (лист 42 см)
// У пазла лист другой длины (S.turns, а при витках — и обёртка), и доля кромки считается от неё.
//
// ⚠ РАЗМЕР — КАК ПОЛОЖЕН, БЕЗ ПРИЖИМА (`bounds(p, g, true)`): правило про то, куда кладут, а
// прижим случается потом, при скрутке, и от руки прошлого ролла зависеть не должен.
//
// Куда кусок девается: на БЛИЖАЙШЕЕ разрешённое место по u, вдоль ролла (v) не двигается.
// Текста нет (подсказки на экране раскладки нет, решение 02.09): отказ виден сам — кусок
// упирается в кромку риса, как раньше в край листа.
//
// ⚠ КУСОК ШИРЕ ВСЕЙ ГРЯДКИ. Места на рисе для него нет вовсе. Бывает только в пазле узумаки на
// двух витках (лист 36–53 мм, рис 29–45 мм): омлет-лист, киви, манго, банан, дэмбу — замер
// 17.09 по всем базам, виткам уровней и обёрткам. Касание такой кусок не кладёт (`layFits`),
// генератор его в цель не берёт; старый рецепт ставит его в середину грядки — ближе к правилу
// встать нельзя, а выбрасывать кусок из чужого рецепта молча хуже.
function riceSpanU(g) {
  const P = spreadPre(g), A = edgeRagAmp() / gL(g);
  return { u0: P.s0 + A, u1: P.se - A };
}
// ⚑ ПОЛУШИРИНА СЛЕДА — ПО КОПИИ С u = 0, КАК В genTarget (17.09, замечание проверки #253).
// `bounds` даёт края как u ∓ h, и разность (u + h) − (u − h) на плавающей точке зависит от u в
// последнем разряде. Кусок, упёртый в кромку, повторный layU сдвигал на 1e-16: ссылка на цель
// пазла возвращала не тот бит (#236) — 63 цели из 28 800 (100 зёрен × 3 обёртки), и 1914 упоров
// из 64 962 меняли u при втором вызове. От u след не зависит, а при u = 0 разность точная, и
// layU(p, layU(p, u)) === layU(p, u) до бита.
function halfU(p, g) { const bb = bounds(Object.assign({}, p, { u: 0 }), g, true); return (bb.u1 - bb.u0) / 2; }
function layFits(p, g) {
  const r = riceSpanU(g);
  return 2 * halfU(p, g) <= r.u1 - r.u0;
}
function layU(p, u, g) {
  const hu = halfU(p, g), r = riceSpanU(g);
  const lo = r.u0 + hu, hi = r.u1 - hu;
  return lo > hi ? (r.u0 + r.u1) / 2 : clamp(u, lo, hi);
}
// Кусок, оказавшийся на голом крае, сдвигаем на ближайшее место на рисе — прямо в самом
// списке. Отвечает, сколько кусков сдвинуто.
function layOnRice(list, g) {
  let n = 0;
  for (const p of list) {
    if (!ING[p.kind]) continue;                // снятая начинка: её отсеют свои фильтры, мерить нечем
    const u = layU(p, p.u, g); if (u !== p.u) { p.u = u; n++; }
  }
  return n;
}
// Правило спрашивает текущий лист (база, обёртка, витки). Чужой рецепт проверяется на своём
// листе: состояние подменяется на время вызова и возвращается, как в `withRecipe` альбома.
function withSheetOf(st, fn) {
  const keep = { base: S.base, wrap: S.wrap, turns: S.turns };
  S.base = st.base; S.wrap = (st.wrap && WRAPPERS[st.wrap]) ? st.wrap : null; S.turns = turnsOf(st.turns);
  try { return fn(); }
  finally { S.base = keep.base; S.wrap = keep.wrap; S.turns = keep.turns; }
}
// Лист сменился под лежащей раскладкой (обёртка при заданных витках меняет длину листа, а с ней
// долю куска; база — свою постель): раскладку и цель пазла возвращаем на рис.
function layRefit() {
  layOnRice(patches());
  if (S.puzzle && S.puzzle.target) layOnRice(S.puzzle.target);
}

function load() {
  try {
    const m = JSON.parse(localStorage.getItem('rollery.model.v2') || 'null');
    if (m && m.lists) { S.base = m.base in BASES ? m.base : 'hoso'; S.lists = m.lists; S.wrap = (m.wrap && WRAPPERS[m.wrap]) ? m.wrap : null; }
    for (const k in BASES) if (!S.lists[k]) S.lists[k] = [];
    // ⚑ ЖИВОЙ СРЕЗ ВКЛЮЧЁН ПО УМОЛЧАНИЮ. Он и есть обратная связь игры: узор
    // следует из раскладки, и без него первый игрок не видит связи между тем,
    // что кладёт, и тем, что получит. Раньше стоило места — предпросмотр
    // ложился накладкой поверх листа; после правки раскладчика он занимает
    // пустоту над листом и лист не уменьшает. Глаз в панели выключает за тап,
    // и выбор запоминается: null (первый запуск) — да, '0' — нет.
    { const pv = localStorage.getItem('rollery.preview'); S.preview = pv === null ? true : pv === '1'; }
    // Ключа нет — новый игрок, звук молчит. Сравнение с '1' давало обратное:
    // отсутствие ключа читалось как «не выключено» и игра начинала со звуком.
    S.mute = localStorage.getItem('rollery.mute') !== '0';
    S.shape = localStorage.getItem('rollery.shape') || 'round';
    S.cutsTotal = +(localStorage.getItem('rollery.cuts') || 0);
    S.album = JSON.parse(localStorage.getItem('rollery.album') || '[]');
    if (!Array.isArray(S.album)) S.album = [];
  } catch (e) {}
  // Минимальный стенд: сохранённая база/начинка может быть спрятана (#96) — раскладки при этом
  // НЕ трогаем, они переживут и вернутся с ?full.
  if (!uiBases().includes(S.base)) S.base = 'futo';
  S.sel = uiIngredients()[0] || B().ingredients[0];
  for (const b in S.lists) S.lists[b] = S.lists[b].filter(p => ING[p.kind]);
  // Сохранённое до 17.09 могло лежать на голом крае — сдвигаем, у каждой базы по её постели (#253).
  for (const b in S.lists) if (BASES[b]) withSheetOf({ base: b, wrap: S.wrap, turns: S.turns }, () => layOnRice(S.lists[b]));
}
function save() {
  try {
    localStorage.setItem('rollery.model.v2', JSON.stringify({ base: S.base, lists: S.lists, wrap: S.wrap }));
    localStorage.setItem('rollery.preview', S.preview ? '1' : '0');
    localStorage.setItem('rollery.mute', S.mute ? '1' : '0');
    localStorage.setItem('rollery.shape', S.shape);
    localStorage.setItem('rollery.cuts', String(S.cutsTotal));
  } catch (e) {}
}

