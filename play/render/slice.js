// краю куска угадать нельзя в принципе. Замена ниже не угадывает.
// ГРАНИЦЫ СРЕЗА — ОБХОДОМ ЯЧЕЕК, А НЕ ОПРОСОМ ЛУЧАМИ (issue #121).
//
// Замечание владельца 31.08: «я не ожидала, что эти пути могут быть прерывистыми». Она права
// по существу: контур куска — замкнутая линия на плоском листе. Скрутка его деформирует,
// сминает, может сплющить почти в нить — но НЕ РАЗРЫВАЕТ. Разрыв в картинке означал бы, что
// кусок разорвало, а этого не бывает.
//
// РВАЛА МЕРКА, А НЕ ГЕОМЕТРИЯ. Прежний приём пускал лучи из центра и отмечал на каждом смены
// материала, а потом угадывал, какая точка на соседнем луче продолжает какую. На краю куска
// угадать нельзя в принципе: две границы — вход луча и выход — там сходятся в одну и пропадают
// обе. Любое правило сшивки в этой точке ошибается. Сшивка по близости радиуса (правка 31.08)
// помогла, но не вылечила: замер давал 22 пути, из них 13 обрывков короче десяти точек.
//
// Marching squares не угадывает ничего. Он идёт по ЯЧЕЙКАМ сетки классов и в каждой знает
// точно, как граница её пересекает, потому что видит все четыре угла разом. Отрезки стыкуются
// по общим рёбрам, и петля выходит ЗАМКНУТОЙ ПО ПОСТРОЕНИЮ — рваться нечему.
//
// Сетка уже есть и ничего нового считать не надо: materialMapOf отдаёт коды классов, те же,
// по которым рисуется сам срез. Значит контур не может разойтись с картинкой — он строится
// из тех же данных.
const КОД_ОБЁРТКИ = 2;             // тот же класс, что отдаёт materialMapOf
const LINE_GRID = 200;              // сторона сетки классов для обхода границ
const LINE_SMOOTH = 2;              // проходов сглаживания петли: убирает ступеньку сетки

// Обход одной бинарной маски. Возвращает массив замкнутых петель в долях [-1…1].
function marchMask(маска, N) {
  // Точка кладётся на СЕРЕДИНУ ребра сетки, и ключ ребра целочисленный — поэтому концы
  // отрезков совпадают ТОЧНО, без допусков на сравнение чисел с плавающей точкой.
  const рёбра = new Map();          // ключ ребра → индекс точки
  const точки = [];
  const соседи = new Map();         // индекс точки → массив соседей
  const узел = (гор, x, y) => {     // гор: 1 — ребро вправо от (x,y), 0 — вниз
    const k = (гор ? 1 : 0) + 2 * (x + (N + 1) * y);
    let id = рёбра.get(k);
    if (id === undefined) { id = точки.length; точки.push(гор ? [x + 0.5, y] : [x, y + 0.5]); рёбра.set(k, id); }
    return id;
  };
  const связать = (a, b) => {
    if (a === b) return;
    if (!соседи.has(a)) соседи.set(a, []); if (!соседи.has(b)) соседи.set(b, []);
    соседи.get(a).push(b); соседи.get(b).push(a);
  };
  const внутри = (x, y) => x >= 0 && y >= 0 && x < N && y < N && маска[y * N + x] === 1;
  for (let y = -1; y < N; y++) for (let x = -1; x < N; x++) {
    // Углы ячейки — четыре соседних узла сетки; код 0…15 говорит, как граница её режет.
    const tl = внутри(x, y) ? 1 : 0, tr = внутри(x + 1, y) ? 1 : 0;
    const bl = внутри(x, y + 1) ? 1 : 0, br = внутри(x + 1, y + 1) ? 1 : 0;
    const код = tl * 8 + tr * 4 + br * 2 + bl;
    if (код === 0 || код === 15) continue;
    const В = () => узел(1, x, y), Н = () => узел(1, x, y + 1);
    const Л = () => узел(0, x, y), П = () => узел(0, x + 1, y);
    switch (код) {
      case 1: case 14: связать(Л(), Н()); break;
      case 2: case 13: связать(Н(), П()); break;
      case 3: case 12: связать(Л(), П()); break;
      case 4: case 11: связать(В(), П()); break;
      case 6: case 9:  связать(В(), Н()); break;
      case 7: case 8:  связать(Л(), В()); break;
      // Сёдла (5 и 10): диагональ можно соединить двояко, и оба варианта законны. Берём тот,
      // что не слипает разные куски: соединяем углы, лежащие ВНУТРИ маски, — иначе две
      // соприкоснувшиеся начинки слились бы в одну петлю.
      case 5:  связать(Л(), В()); связать(Н(), П()); break;
      case 10: связать(В(), П()); связать(Л(), Н()); break;
    }
  }
  // Отрезки в петли: идём от точки к точке, не возвращаясь туда, откуда пришли.
  const петли = [], пройдено = new Set();
  for (const [старт] of соседи) {
    if (пройдено.has(старт)) continue;
    const путь = []; let тек = старт, пред = -1;
    while (тек !== undefined && !пройдено.has(тек)) {
      пройдено.add(тек); путь.push(точки[тек]);
      const сп = соседи.get(тек) || [];
      const след = сп.find(n => n !== пред && !пройдено.has(n));
      пред = тек; тек = след;
    }
    if (путь.length >= 4) петли.push(путь);
  }
  // ⚠ ОТСЕВ ПИКСЕЛЬНОГО ШУМА, И ПО ПЛОЩАДИ, А НЕ ПО ЧИСЛУ ТОЧЕК. На границе двух материалов
  // карта классов даёт одиночные клетки чужого цвета — каждая рождает честную замкнутую петлю
  // из четырёх точек. Первый прогон дал 141 петлю, из них 121 такую. По длине их не отличить
  // от маленькой начинки, а по площади — сразу: настоящая начинка занимает сотни клеток.
  // Порог 6 клеток: одиночная клетка даёт 1, пара — 2, а самая мелкая осмысленная деталь
  // (зерно 0,7 ед. при сетке 200 на ролл ⌀12 ед.) — уже больше сотни.
  const МИН_КЛЕТОК = 6;
  const площадь = п => {                     // формула шнурков, знак не важен
    let a = 0;
    for (let i = 0, n = п.length; i < n; i++) {
      const [x1, y1] = п[i], [x2, y2] = п[(i + 1) % n];
      a += x1 * y2 - x2 * y1;
    }
    return Math.abs(a) / 2;
  };
  const крупные = петли.filter(п => площадь(п) >= МИН_КЛЕТОК);
  // Сглаживание: середина рёбер даёт лесенку в полпикселя сетки. Скользящее среднее по трём
  // соседям её снимает, формы не двигая, — петля замкнутая, поэтому края не нужны.
  const половина = N / 2;
  return крупные.map(п => {
    let т = п;
    for (let s = 0; s < LINE_SMOOTH; s++) {
      const n = т.length, out = new Array(n);
      for (let i = 0; i < n; i++) {
        const a = т[(i - 1 + n) % n], b = т[i], c = т[(i + 1) % n];
        out[i] = [(a[0] + 2 * b[0] + c[0]) / 4, (a[1] + 2 * b[1] + c[1]) / 4];
      }
      т = out;
    }
    return т.map(([x, y]) => [(x - половина) / половина, (y - половина) / половина]);
  });
}

// Границы всех материалов среза. Возвращает [{ петли, code }], где code — класс из
// materialMapOf (0 out · 1 рис · 2 обёртка · 3+ начинка по виду).
// ⚑ КОНТУР ОБЁРТКИ ВЕДЁТСЯ ПО МОДЕЛИ, А НЕ ПО РАСТРУ (правка 01.09).
//
// Обход маски работает, пока материал толще клетки сетки. Обёртка тоньше: нори 0,1 мм на
// ролле ⌀56 — это 0,0036 радиуса, при сетке 200 ровно 0,36 КЛЕТКИ. Растр такую полосу
// держит через раз, и вместо кольца выходило ВОСЕМЬ отдельных дуг с провалами между ними
// (замер 01.09: петли по 42/160/160/18/42/298/160/42 точки). Владелец увидела это сразу:
// «это всё непрерывные линии должны быть… в норе это должна быть просто непрерывная».
//
// Сеткой это не лечится: чтобы удержать 0,36 клетки, сетку надо утроить, и она всё равно
// будет держать её на пределе. Но растр здесь и не нужен — обёртка не пятно произвольной
// формы, а КОЛЬЦО с известными радиусами на каждом углу: внутренний край это верх риса
// (rin слоя k=1), внешний — контур ролла (top). Две замкнутые петли, непрерывные по
// построению, без единого допуска.
//
// Координаты те же, что у обхода маски, и выводятся из materialMapOf в обратную сторону:
// пиксель (px+0,5) ↦ модель через scale = (N/2−1)/(Rmax·margin), значит модель ↦ узел
// сетки через умножение и сдвиг на полклетки. Иначе линия ляжет рядом с картинкой, а не на неё.
function wrapLoops(m, vSlice) {
  const wd = windFor(m, vSlice), NB = wd.top.length;
  if (!NB) return [];
  const si = shapeInfo(m.shape || S.shape, m.Rmax, m.g.press);
  const половина = LINE_GRID / 2, scale = (половина - 1) / (m.Rmax * si.margin);
  const точка = (r, phi) => {
    const h = r / shapeK(phi, si) * scale;
    return [(h * Math.cos(phi) - 0.5) / половина, (h * Math.sin(phi) - 0.5) / половина];
  };
  const ШАГОВ = 720;                       // полградуса: контур гладкий, бугры от начинок целы
  const внеш = [], внутр = [];
  for (let i = 0; i < ШАГОВ; i++) {
    const phi = i / ШАГОВ * TAU, b = Math.min(NB - 1, Math.round(i / ШАГОВ * NB));
    const rВнеш = wd.обёртка.внеш(b), rВнутр = wd.обёртка.внутр(b);
    if (!(rВнеш > 0)) return [];           // намотки нет — молчим, а не рисуем мусор
    внеш.push(точка(rВнеш, phi));
    внутр.push(точка(rВнутр >= 0 ? rВнутр : rВнеш, phi));
  }
  return [внеш, внутр];
}
function sliceLines(m, vSlice) {
  const N = LINE_GRID;
  const карта = materialMapOf(N, vSlice, m, m.Rmax);
  const коды = new Set(карта); коды.delete(0);          // «вне ролла» само по себе не рисуем
  коды.delete(КОД_ОБЁРТКИ);                             // обёртку ведём по модели, см. wrapLoops
  const out = [];
  const маска = new Uint8Array(N * N);
  for (const code of коды) {
    for (let i = 0; i < карта.length; i++) маска[i] = карта[i] === code ? 1 : 0;
    const петли = marchMask(маска, N);
    if (петли.length) out.push({ петли, code });
  }
  const обёртка = wrapLoops(m, vSlice);
  if (обёртка.length) out.push({ петли: обёртка, code: КОД_ОБЁРТКИ });
  return out;
}

function face(vSlice, cssSize, m, Rref) {
  const size = Math.round(cssSize * DPR);
  if (S.v2) {
    const blank = () => { const c = document.createElement('canvas'); c.width = c.height = size; return c; };
    // Мост — модуль, он выполняется позже классических скриптов: первый кадр
    // может успеть раньше. Пустой холст плюс dirty, а не заглушка навсегда.
    if (!window.CoreV2) { dirty = true; return blank(); }
    const snap = v2Snap();
    // Отказ рисует экран целиком (drawRolled), а не срез: причину надо назвать
    // словами, а не показать чёрный квадрат.
    if (!snap || !snap.ok) return blank();
    const img = window.CoreV2.faceCanvas(size);
    if (!img) return blank();
    img._v = vSlice;
    return img;
  }
  m = m || getModel();
  const key = m.key + '|' + vSlice.toFixed(3) + '|' + size + '|' + (Rref ? Rref.toFixed(3) : '') + '|' + S.shape + (PIX ? '|p' + PIX : '');
  let img = faceCache.get(key);
  if (!img) {
    if (faceCache.size > 60) faceCache.clear();
    if (PIX) {
      // Считаем срез в PIX раз мельче и увеличиваем ЦЕЛЫМ множителем с выключенным сглаживанием.
      // Целым — обязательно: дробное увеличение возвращает мыло, ради борьбы с которым всё и затеяно.
      // Размер выхода кратен PIX, поэтому вызывающий получает картинку не мельче запрошенной.
      const small = Math.max(8, Math.round(size / PIX)), out = small * PIX;
      const src = renderSection(small, vSlice, m, Rref);
      const cv = document.createElement('canvas'); cv.width = cv.height = out;
      const cx = cv.getContext('2d'); cx.imageSmoothingEnabled = false;
      cx.drawImage(src, 0, 0, small, small, 0, 0, out, out);
      img = cv;
    } else img = renderSection(size, vSlice, m, Rref);
    faceCache.set(key, img);
  }
  // ⚑ Модель цепляется к картинке, а не передаётся через все точки вызова: drawFaceImg
  // зовут из десяти мест, и добавлять туда параметр значило бы править десять строк ради
  // отладочного режима. Линии считаются лениво и живут на том же кеше, что и картинка.
  img._m = m; img._v = vSlice;
  return img;
}
