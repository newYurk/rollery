//
// Смысл не в отладке пикселей, а в независимости от них: точки берутся у МОДЕЛИ, а не у
// картинки. Поэтому линия одинаково верна поверх пиксельного вида, поверх гладкого и поверх
// любого будущего — расхождение линии с картинкой И ЕСТЬ ошибка отрисовки. Пиксельная сетка
