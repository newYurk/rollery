// риса на всех базах.
//
// ПОДТВЕРЖДЕНО ИСТОЧНИКОМ, А НЕ ВКУСОМ. Толщина постели ВЫВЕДЕНА из массы риса (#131), значит
// обратный ход обязан вернуть те же граммы. С правкой: тюмаки 140 г, футомаки 200 г — ровно как
