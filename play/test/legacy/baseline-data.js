// ⚠ ИМЕННО ТАК И ДОЛЖНО ВЫГЛЯДЕТЬ ЭТО ИЗМЕНЕНИЕ. Крупный сдвиг означал бы, что амплитуда
// шума задана не в зерне, а в чём-то большем; малый — что кромка стала рваной, а количество
// риса осталось прежним (масса нормируется, см. thicknessProfile).

// ⚑ ПЕРЕСНЯТО 02.09.2026 — правка #151: ролл больше не больше своего материала.
//
// Ядро дорисовывало рис в промежутках между начинками: диск = кольцо (честное) + ядро СВЕРХ
// листа. На каноне футомаки это 28,3 ед² из ниоткуда, 28 % ролла. Проверено и то, что могло
// бы это оправдать: рис из-под начинок не вытеснялся вовсе — пустой лист 58,5 и лист с
// четырьмя начинками те же 58,5. Теперь постель платит за зазоры, и площадь сходится точно:
// диск = рис + зазоры + начинки + носитель, до последней десятой на всех трёх кольцевых базах.
//
// ЧТО ПОЕХАЛО. Диаметры упали тем сильнее, чем больше зазор у фикстуры:
//
//   F04 пазл          54,71 → 54,68   −0,1 %     зазоров почти нет
//   F03 обёртка       49,44 → 48,93   −1,0 %
//   F01 хосомаки      32,03 → 30,70   −4,2 %     рулетка 27.08 давала 25–30 мм
//   F05 рука          58,52 → 51,60  −11,8 %
//   F02 футомаки      53,38 → 46,92  −12,1 %
//   F07 перегруз      44,63 → 37,35  −16,3 %
//   F06 поворот       57,54 → 46,35  −19,5 %
//
// Витки при этом ВЫРОСЛИ (1,17→1,18 … 1,18→1,23) — ролл меньше, значит лист обходит его больше
// раз. Направление согласовано у всех семи, разброс объясняется зазором, а не шумом.
//
// ⚠ Хосомаки — единственная база с опорой на реальность, и он подошёл к коридору рулетки, а не
// ушёл от него. Это независимое подтверждение, что правка в верную сторону.
// ⚑ ПЕРЕСНЯТО 02.09.2026 — нори обнимает начинку, а не прошивает её (#124).
//
// Владелец посмотрела на кадр и сказала: «и херня в середине», потом «нори не обнимает с двух
// сторон начинку». Оба замечания верны, и оба — то, чего я не проверила, закрывая задачу.
//
// ПЕРВОЕ. Замер заливкой: 99 отдельных пятен нори вместо одного кольца. В модели она при этом
// цела — непрерывна на всех 360 углах; рвалась при отрисовке, потому что 0,10 мм при масштабе
// 13 px/мм это 1,3 ПИКСЕЛЯ. У обычного маки её спасает обводка контура, а у вывернутого стоял
// `if (b.inverted) return;` — и рядом честный комментарий «отрисовку внутренней линии ещё
// предстоит завести». Завела: та же линия ведётся по ВНУТРЕННЕЙ кромке (`innerAt`), штрих
// сдвигается наружу, контактная тень снята — она для силуэта, а линия внутри риса.
//
// ВТОРОЕ, и это уже модель. Нори садилась на окружность 1,98, а начинка доходила до 2,22 —
// обёртка проходила СКВОЗЬ неё. Причина: в `переложить` пандус считался как
// `Math.max(0, rin0 − g.r0)`, и отрицательное срезалось нулём. С ядром-коробкой (#152) контур
// БЛИЖЕ плоского r0 по сторонам и дальше по углам, поэтому половина поугловой границы молча
// терялась: замер по стадиям дал 1,98 · 1,44 · 1,02 до обжима и 1,98 · 1,61 · 1,61 после —
// уцелел только бин, где старт больше r0. Ноль стоял с тех пор, когда ядро было КРУГОМ и
// старт не мог быть меньше.
//
// После: старт совпадает с контуром коробки на всех стадиях, нори снаружи начинки на 359
// углах из 360, пятен 99 → 20 (остаток — субпиксельная лента, её и закрывает обводка).
//
// Слепок поехал широко: доли классов у всех фикстур — прямое следствие того, что пандус
// перестал обнуляться, то есть поугловая граница ядра заработала везде, а не только у урамаки.
// ⚑ ПЕРЕСНЯТО 02.09.2026 — носитель перестал считаться дважды в кольце (#164).
//
// `materialAt` вычитала толщину носителя из КАЖДОГО слоя: `zn = (sm.t − g.w − sm.zr)/g.T`.
// Для спирали это правда — там намотка кладёт `t += W`, носитель часть слоя. В кольце нет:
// слой риса считается по `prof` БЕЗ `w`, а нори лежит отдельным витком толщиной ровно `w`.
// Вычитание срабатывало дважды — честно на слое нори и ещё раз на внешних `w` слоя риса.
//
// ЗАМЕР ДО И ПОСЛЕ, толщина нори на срезе против каталожной 0,100 мм:
//
//   футомаки, кольцо   0,202 · 0,199 · 0,202 → 0,101 · 0,098 · 0,101
//   под нахлёстом      0,300               → 0,202   (два слоя, как и должно)
//   узумаки, спираль   9,00 при 1,50       → без изменений (шесть пересечений по шести виткам)
//
// ЧТО ПОЕХАЛО В СЛЕПКЕ. Кольцо нори стало вдвое тоньше, и на сетке инвариантов оно местами
// перестало попадать в отсчёты вовсе: у хосомаки доля `wrap` 0,0023 → 0, а доля `spread`
// выросла ровно на столько же. Материал НЕ пропал — замер по лучу даёт 0,100 мм на месте;
// пропала его различимость на грубой сетке. Это стоит знать про сам инвариант: при 0,1 мм
// на ролле 30 мм доля обёртки — величина ниже разрешения слепка, и полагаться на неё нельзя.
//
// Второе, что чинится этим же и в слепке не видно: каждый кусок в кольцевой намотке был
// сдвинут внутрь на толщину нори, потому что `zn` отсчитывался от неверной границы.
//
// Найдено независимым разбором математики (скептик, 02.09), проверено отдельным замером.

// ⚑ ПЕРЕСНЯТО 02.09.2026 — постель перестала платить за голую полосу (#166).
