// ── ИСПОЛНИТЕЛЬ ───────────────────────────────────────────────────────────────
// Зовётся из play/checks.js. Возвращает { провалы, пробелы, сошлось } — строками, готовыми
// к печати. Провал — модель посчитала число и оно ВНЕ диапазона источника. Пробел — источник
// есть, а мерки нет: молчать об этом нельзя, но и валить проверку не за что.
//
// ⚠ Записи с `база` меряются на своей базе: диаметр хосомаки и футомаки — разные числа.
// Состояние S восстанавливается после каждой, иначе проверка испортит то, что идёт следом.
function runPracticeChecks(env) {
  const { B, ING, S, touchModel, layout, getModel, windFor, topAt, materialAt, TAU, U_MM, NPIECES } = env;
  const провалы = [], пробелы = [], сошлось = [], заведено = [];

  const наБазе = (base) => {
    const keep = { base: S.base, wrap: S.wrap, turns: S.turns, shape: S.shape, hand: S.hand,
                   list: S.lists[base] };
    S.base = base; S.wrap = null; S.turns = null; S.shape = 'round';
    S.hand = { air: 0, wobble: 0, phase: 0, press: 1, v: 1, cv: 0, hold: 0 };
    S.lists[base] = [];
    let out;
    try {
      // ⚠ Путь тот же, что в play/checks.js: touchModel → layout → getModel. Звать buildModel
      // напрямую нельзя — он читает список патчей из S и падает, если состояние не подготовлено.
      touchModel(); layout();
      const m = getModel(), wd = windFor(m, 0.5), N = 360, rs = [];
      for (let i = 0; i < N; i++) rs.push(topAt(wd, i / N * TAU));
      rs.sort((a, b) => a - b);
      out = { m, wd, turns: wd.turns, diaMm: 2 * rs[N >> 1] * U_MM };
    } finally {
      S.base = keep.base; S.wrap = keep.wrap; S.turns = keep.turns; S.shape = keep.shape;
      S.hand = keep.hand; S.lists[base] = keep.list;
    }
    return out;
  };

  const кэш = {};
  for (const p of PRACTICE) {
    if (!p.мерка) {
      пробелы.push(`${p.что}\n      не проверяется: ${p.чегоНеУмеем || 'мерки нет'}`);
      continue;
    }
    const base = p.база;
    if (base && !кэш[base]) кэш[base] = наБазе(base);
    const ctx = Object.assign({ B, ING, NPIECES, materialAt, TAU }, base ? кэш[base] : {});
    let v;
    try { v = p.мерка(ctx); } catch (e) { провалы.push(`${p.что} — мерка упала: ${e.message}`); continue; }
    if (v === null || v === undefined || !isFinite(v)) {
      пробелы.push(`${p.что}\n      мерка вернула не число`);
      continue;
    }
    const ok = p.ожидание !== undefined ? v === p.ожидание
                                        : (v >= p.диапазон[0] && v <= p.диапазон[1]);
    const строка = `${p.что}: ${(+v).toFixed(2)}${p.ед ? ' ' + p.ед : ''}` +
                   (p.диапазон ? `, источник даёт ${p.диапазон[0]}…${p.диапазон[1]}` : '');
    // РАСХОЖДЕНИЕ С ЗАВЕДЁННЫМ issue — НЕ КРАСНЫЙ, НО И НЕ МОЛЧАНИЕ. Красный сторож, который
    // горит месяцами, перестают читать, и под ним прячется настоящая поломка. Поэтому
    // расхождение, у которого есть `известно`, печатается отдельным списком с номером задачи:
    // видно всегда, чинит очередь, а не паника.
    if (!ok && p.известно) { заведено.push(строка + `\n      ${p.известно}`); continue; }
    (ok ? сошлось : провалы).push(строка + (ok ? '' : `\n      ${p.источник}`));
  }
  return { провалы, пробелы, сошлось, заведено, неизвестно: PRACTICE_UNKNOWN };
}

